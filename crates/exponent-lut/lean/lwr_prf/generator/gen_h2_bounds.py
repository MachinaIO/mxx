CUTOFF = 26
TAU = 14


def up(x, bits=24):
    """A dyadic upper bound of the positive rational `x` with about `bits` significant bits."""
    x = Fr(x)
    if x == 0:
        return Fr(0)
    e = bits - (x.numerator.bit_length() - x.denominator.bit_length())
    if e >= 0:
        return Fr(-((-x.numerator * 2 ** e) // x.denominator), 2 ** e)
    return Fr(-((-x.numerator) // (x.denominator * 2 ** (-e))) * 2 ** (-e))


def lit(x):
    """A real literal for the rational `x`."""
    x = Fr(x)
    if x.denominator == 1:
        return f'({x.numerator} : ℝ)'
    return f'(({x.numerator} : ℝ) / {x.denominator})'


def h2_constants(I, SF):
    L, B, C, n, W = I.L, I.B, I.C, I.n, I.W
    beta = I.digit
    m = I.m
    P, Q = I.P, I.Q
    m1 = m(1)
    lam = {}
    lam[B] = up(Fr(SF * 2 * m1 * n * beta * W, P[2]))
    for b in range(B - 1, -1, -1):
        qb = L - b
        lam[b] = up(lam[b + 1] * 2 * m(qb - 1) * n * beta * C / P[qb])
    rem = {}
    P2 = P[2]
    rem['lut'] = up(SF * (Fr(W * (2 * m1 * n * beta * CUTOFF + (n * (P2 // 2) + P2 // 2)) + (n * (P2 // 2) + P2 // 2), P2)
                         + W * CUTOFF))
    for b in range(B):
        qb = L - b
        Pb = P[qb]
        ms, mA, mT = m(qb - 1), m(qb), m(L)
        rem[('cell', b)] = up(lam[b + 1] * C * (Fr(n * (Pb // 2) + Pb // 2, Pb) + CUTOFF))
        alignL1 = 2 * C * (lam[b + 1] * 2 * ms * n * beta * mA * n * beta)
        if b == 0:
            rem[('member', b)] = up(alignL1 * CUTOFF / Pb)
        else:
            A = Q[L] // Q[qb]
            SH = mT * n * beta
            rem[('align', b)] = up(alignL1 * (SH * CUTOFF + A // 2) / (Pb * A))
    rem['state'] = up(lam[0] * CUTOFF)
    Lmax = up(sum(rem.values()))
    ER = {}
    EK = {}
    for b in range(B):
        qb = L - b
        Pb = P[qb]
        ms, mA = m(qb - 1), m(qb)
        ER[('x', b)] = up(Fr(Pb // 2, Pb) ** 2 * C * lam[b + 1] ** 2)
        if b >= 1:
            A = Q[L] // Q[qb]
            en = 2 * C * ((lam[b + 1] * 2 * ms * n * beta) ** 2 * mA * n * beta ** 2)
            ER[('r', b)] = up(Fr(A // 2, Pb * A) ** 2 * en)
            EK[b] = up(TAU ** 2 * Fr(A // 2, Pb * A) ** 2 * (n * en))
    ER['lut'] = up(Fr(P2 // 2, P2) ** 2 * SF ** 2)
    ERt = up(sum(ER.values()))
    EKt = up(sum(EK.values()))
    return dict(lam=lam, rem=rem, Lmax=Lmax, ER=ER, EK=EK, ERt=ERt, EKt=EKt)


