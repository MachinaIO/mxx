def deterministic_action_proof(scope, key_scope, roots, goals):
    online_flow, key_flow = meta.Flow(scope), meta.Flow(key_scope)
    equalities, lines = dict(roots), []

    def prove(key_wire, online_wire):
        pair = key_wire, online_wire
        if pair in equalities:
            return equalities[pair]
        key_atom = key_flow.producers.get(key_wire)
        online_atom = online_flow.producers.get(online_wire)
        dependencies = []
        if key_atom is not None:
            meta.require(online_atom is not None and key_atom.head == online_atom.head,
                         f"Public-action node mismatch: {pair}")
            key_inputs = meta.xmodel.WIRE.findall(" ".join(key_atom.args[:-1]))
            online_inputs = meta.xmodel.WIRE.findall(" ".join(online_atom.args[:-1]))
            meta.require(len(key_inputs) == len(online_inputs), "Public-action arity mismatch")
            dependencies = [prove(left, right) for left, right in zip(key_inputs, online_inputs)]
        else:
            key_value, online_value = key_scope.wires[key_wire], scope.wires[online_wire]
            meta.require(key_value.term is not None and online_value.term is not None,
                         f"Unlinked public-action input: {pair}")
            key_head, key_args = meta.xmodel.app_split(key_value.term)
            online_head, online_args = meta.xmodel.app_split(online_value.term)
            meta.require(key_head == online_head, f"Public-expression mismatch: {pair}")
            if key_head in ["MxxRuntime.matrixMulScalarLeft", "MxxRuntime.matrixMulScalarRight"]:
                dependencies = [prove(left, right) for left, right in zip(key_args, online_args)]
            else:
                meta.require("matrixPolynomial" in key_value.term and
                             "matrixPolynomial" in online_value.term and
                             key_flow.constant(key_wire) == online_flow.constant(online_wire),
                             f"Unsupported public expression: {pair}")
        name = f"actionEq{len(equalities)}"
        key_ref = "W_Stage_keys_online_0_0." + wire(key_scope, key_wire, "keyCtx")[1:-1]
        online_ref = "W_Stage_online_0." + wire(scope, online_wire)[1:-1]
        lines.append(f"  have {name} : ({key_ref}) = ({online_ref}) := by")
        if key_atom is not None:
            unique = key_atom.kind + "_unique"
            meta.require(key_atom.kind in ["gadgetMatrixRuns", "gadgetDecomposeRuns",
                         "modulusReduceRuns", "centeredRebaseRuns", "compactCenteredRebaseRuns",
                         "blockDiagonalRuns"],
                         f"Unsupported public witness {key_atom.kind}")
            lines.append(f"    have keyFact := {fact(key_atom, 'Fk')}")
            if dependencies:
                lines.append(f"    rw [{', '.join(dependencies)}] at keyFact")
            positivity = " (by decide) (by decide)" if key_atom.kind == "blockDiagonalRuns" else ""
            lines.append(f"    exact {unique}{positivity} keyFact {fact(online_atom, 'Fo')}")
        elif dependencies:
            lines.append(f"    exact congrArg₂ {key_head} {' '.join(dependencies)}")
        else:
            lines.append("    rfl")
        equalities[pair] = name
        return name

    conclusions = [prove(left, right) for left, right in goals]
    return lines, conclusions


def public_action_proof(online, keys, scope, key_scope, prime, rows):
    key_flow = meta.Flow(key_scope)
