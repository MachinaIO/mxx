def header(imports, description):
    return "\n".join("import " + name for name in imports) + f'''

/-! {description}

Generated by `crates/io/lean/dio2/generator/gen_online0_parts.py`.
All export-dependent identifiers and dimensions are extracted using `dio2_meta.py`.
-/

set_option maxHeartbeats 32000000
set_option maxRecDepth 10000

''' + OPEN


def fact(atom, variable="F"):
    field = "hout" if atom.head == "out" else "h" + atom.args[-1][2:]
    meta.require(re.fullmatch(r"h(?:out|\d+_\d+)", field) is not None,
                 f"Unsupported Facts output: {atom.args}")
    return f"{variable}.c{atom.frag}.{field}"


def wire(scope, name, ctx="ctx"):
    return f"({scope.name}.{name} {ctx})"


def natural_adapter_indices(scope):
    unnamed_index = 0
    indices = []
    for name, ty in scope.sig:
        if name == '_':
            name = f'x_{unnamed_index}'
            unnamed_index += 1
        if ty == 'Nat':
            indices.append(name)
    return indices


