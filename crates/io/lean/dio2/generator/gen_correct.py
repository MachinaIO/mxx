#!/usr/bin/env python3
"""Generate the dio2 top-level reduction, decoder and ideal-function proofs.

The reduction leaves operational stage invariants explicit, but never assumes a
decoding inequality. Its final error envelope and margin are the existing sharp
``Dio2Noise`` certificate at refreshed-root bound n+2. Generate that dependency
with ``gen_noise_cert.py --package PACKAGE --sharp --out DIR``.

Use --output-dir for scratch-only production generation. Metadata supplies all
package dimensions and source identities; the metadata parser discovers claim
wiring, decode loops, ideal tables and validity projections. Unsupported claim
shapes fail before any proof is written. No large finite family is expanded.
"""

import argparse
import hashlib
import json
import re
from pathlib import Path
from string import Template

import dio2_meta as meta


DECODE = Template('''import W_Stage_decode

/-!
# The exported decode stage

Generated by `gen_correct.py`. The loop invariant quantifies over coefficients;
it does not enumerate the ring. On the monomial at exponent $STRIDE * z the
coefficient sum is $STRIDE * z, and the exported final division returns z.
-/

namespace Dio2Proof

open W_Stage_decode

/-- A zero/one coefficient contributes its index times its value. -/
theorem decode_step (params : Params) (index : Nat) (hindex : index < $N)
    (current next : Int) (family : Fin $N → Int)
    (hcoeff : family ⟨index, hindex⟩ = 0 ∨ family ⟨index, hindex⟩ = 1)
    (hrun : $LOOP params index (current, (family, ())) next) :
    next = current + index * family ⟨index, hindex⟩ := by
  obtain ⟨value, hconstraints⟩ := hrun
  simp only [$LOOP.constraints_0] at hconstraints
  obtain ⟨$LOOP_PATTERN⟩ := hconstraints
  have hposition' : position = ⟨index, hindex⟩ := by
    apply Fin.ext
    have hcast : ((position.val : Nat) : Int) = (index : Int) := by
      simpa using hposition
    exact_mod_cast hcast
  subst hposition'
  rw [hnext, hvalue]
  rcases hcoeff with hzero | hone
  · rw [hzero]; norm_num
  · rw [hone]; norm_num

/-- The actual decoder returns the encoded in-range monomial exponent divided by its stride. -/
theorem decode_monomial (params : Params)
    (plaintext : Mxx.Primitives.ExactMatrix modulus_0 $N 1 1)
    (value : Nat) (hvalue : $STRIDE * value < $N)
    (hcoeff : ∀ index : Fin $N, (((plaintext 0 0).coeff index).val : Int) =
      if index.val = $STRIDE * value then 1 else 0)
    (output : Int) (hrun : generatedRoot params plaintext output) : output = value := by
  obtain ⟨witness, hbody⟩ := hrun
  simp only [generatedRoot.body, generatedRoot.constraints_0] at hbody
  obtain ⟨$ROOT_PATTERN⟩ := hbody
  simp only [MxxRuntime.polynomialValues, Bool.false_eq_true, ↓reduceIte] at hvalues
  have hfamily : ∀ index : Fin $N,
      witness.$FAMILY index = if index.val = $STRIDE * value then 1 else 0 := by
    intro index
    rw [hvalues index, hcoeff index]
  have hsum := MxxIR.IterRuns.invariant
    (Invariant := fun index (total : Int) ↦ index ≤ $N →
      total = if $STRIDE * value < index then ($STRIDE * value : Int) else 0)
    (by intro _; simp)
    (by
      intro index current next hinvariant hstep hle
      have hindex : index < $N := by omega
      have hcell := hfamily ⟨index, hindex⟩
      have hnext := decode_step params index hindex current next witness.$FAMILY
        (by rw [hcell]; split_ifs <;> simp) hstep
      rw [hnext, hinvariant (by omega), hcell]
      by_cases hequal : index = $STRIDE * value
      · subst hequal; simp
      · simp only [hequal, if_false]; split_ifs <;> omega)
    hiter
  have hcount : Int.toNat $N = $N := rfl
  rw [hcount] at hsum
  have hfinal := hsum le_rfl
  rw [hout, hfinal, if_pos hvalue]
  omega

end Dio2Proof
''')


IDEAL = Template('''import W_Ideal

/-!
# The exported two-step ideal functionality

Generated by `gen_correct.py` from the ideal program and metadata state tables.
Only the fixed four-entry Boolean function is case-split, never a label family.
-/

namespace Dio2Proof

/-- The exported first state table. -/
def table0 : List Int := $TABLE0

/-- The exported second state table. -/
def table1 : List Int := $TABLE1

/-- An integer-indexed table entry, with the runtime's zero default. -/
def entry (table : List Int) (index : Int) : Int := table.getD index.toNat 0

/-- The runtime's four-way selection agrees with table lookup. -/
theorem select_entry {index output first second third fourth : Int}
    (hselect : MxxRuntime.select index [first, second, third, fourth] output) :
    output = entry [first, second, third, fourth] index := by
  obtain ⟨position, hposition, houtput⟩ := hselect
  subst hposition
  fin_cases position <;> simp [houtput, entry]

/-- The actual ideal program is the composition of its two state tables. -/
theorem ideal_value (params : W_Ideal.Params) (initial : Int) (bits : Fin 2 → Int)
    (output : Int) (hrun : W_Ideal.generatedRoot params (initial, (bits, ())) output) :
    output = entry table1 (entry table0 (initial + bits 0) + 1 + bits 1) := by
  obtain ⟨witness, hbody⟩ := hrun
  simp only [W_Ideal.generatedRoot.body, W_Ideal.generatedRoot.constraints_0] at hbody
  obtain ⟨$PATTERN⟩ := hbody
  have hposition0' : position0 = 0 := by fin_cases position0 <;> simp_all
  have hposition1' : position1 = 1 := by fin_cases position1 <;> simp_all
  subst hposition0' hposition1'
  have htable0 := select_entry hselect0
  have htable1 := select_entry hselect1
  rw [hout, htable1, htable0, hbit1, hbit0]
  simp [entry, table0, table1]

end Dio2Proof
''')


CORRECT = Template('''import BridgeRuns
import W_Claim
import Dio2Decode
import Dio2Ideal
import Dio2Final
import Dio2Noise

/-!
# Stage-conditional dio2 correctness and the average-case certificate

Generated by `gen_correct.py`. `CorrectInputs` is the remaining operational
assembly contract, not an assumed decoding inequality or an unconditional claim.
The two state predicates and label predicate must be instantiated by Complete.
Transitions are specialized to the in-range Boolean state-table messages actually
needed by this claim, rather than arbitrary plaintexts or enumerated label forests.

The last transition supplies a bounded pre-switch error and the actual switch
relation. `decoding_margin` comes from the existing sharp numerical certificate
at refreshed-root envelope n+2. `final_output_residues` applies generic nearest
rounding; no strict noise inequality is a field of `CorrectInputs`.

`correct` combines the transitions, exported decoder, validity bits and ideal
program. `certificate` transports average runs through `runs_bridge`, making
the failure set empty. The exported failure exponent ($FAILURE) is not replaced
by a toy exponent; the zero-measure proof works at that exact claim type.
-/

set_option maxRecDepth 16384

namespace Dio2Proof

open Mxx.Primitives MxxRuntime MxxExponentLut RefreshTopProof.GenFinal

/-- The ciphertext modulus of the actual last online stage. -/
abbrev ciphertextModulus : Nat := W_Stage_online_1.modulus_0

/-- The prime consumed by the exported decoder. -/
abbrev decodePrime : Nat := W_Stage_decode.modulus_0

/-- The scalar retarget factor from the sharp CRT certificate. -/
abbrev decodeQuotient : Nat := Dio2NoiseCertificate.quotient0

/-- The conservative sharp final error, including the centered smudge residual. -/
abbrev finalNoiseBound : Nat :=
  Dio2NoiseCertificate.b${ROOT}_final + Dio2NoiseCertificate.b${ROOT}_residue

/-- The exported ciphertext modulus factors through the certified first prime. -/
theorem decoding_modulus : ciphertextModulus = decodeQuotient * decodePrime :=
  Dio2NoiseCertificate.quotient0_exact.symm

/-- The decoding margin is a numerical theorem, never a stage assumption. -/
theorem decoding_margin : 2 * finalNoiseBound < decodeQuotient := by
  rw [← Dio2NoiseCertificate.b${ROOT}_left_final_eval]
  exact Dio2NoiseCertificate.b${ROOT}_final_p0

/-- The actual final switch has a bounded integer error around its intended plaintext.
The stage-1 worker derives this by `unmask_out_gen`, actual final-switch Facts,
and domination of the constituent bounds by the sharp certificate's envelope. -/
def FinalOutput (execution : GeneratedClaim.Execution) (message : ErrorPoly $N) : Prop :=
  ∃ (beforeSwitch : ExactMatrix ciphertextModulus $N 1 1)
    (error : ErrorMatrix $N 1 1),
    CoeffBound error finalNoiseBound ∧
    beforeSwitch = ((decodeQuotient : Int) : ExactPoly ciphertextModulus $N) •
      reduceMatrix ciphertextModulus $N 1 1 (fun _ _ ↦ message) +
      reduceMatrix ciphertextModulus $N 1 1 error ∧
    modulusSwitchRuns beforeSwitch execution.«$ONLINE_OUTPUT».1

/-- A sharper stage-specific error bound can be enlarged to the certified envelope. -/
theorem final_output_of_bound {execution : GeneratedClaim.Execution} {message : ErrorPoly $N}
    {beforeSwitch : ExactMatrix ciphertextModulus $N 1 1} {error : ErrorMatrix $N 1 1}
    {bound : Nat} (herror : CoeffBound error bound) (hbound : bound ≤ finalNoiseBound)
    (hvalue : beforeSwitch = ((decodeQuotient : Int) : ExactPoly ciphertextModulus $N) •
      reduceMatrix ciphertextModulus $N 1 1 (fun _ _ ↦ message) +
      reduceMatrix ciphertextModulus $N 1 1 error)
    (hswitch : modulusSwitchRuns beforeSwitch execution.«$ONLINE_OUTPUT».1) :
    FinalOutput execution message :=
  ⟨beforeSwitch, error, fun row column index ↦ (herror row column index).trans hbound,
    hvalue, hswitch⟩

/-- Generic nearest rounding, with the concrete certified margin already discharged. -/
theorem final_output_residues {execution : GeneratedClaim.Execution} {message : ErrorPoly $N}
    (houtput : FinalOutput execution message) (index : Fin $N) :
    (execution.«$ONLINE_OUTPUT».1 0 0).coeff index =
      ((((reducePoly ciphertextModulus $N message).coeff index).val : Nat) : ZMod decodePrime) := by
  obtain ⟨beforeSwitch, error, herror, hvalue, hswitch⟩ := houtput
  refine switch_gen (by norm_num) decoding_modulus (by norm_num [decodeQuotient,
    Dio2NoiseCertificate.quotient0]) (by norm_num [decodePrime, W_Stage_decode.modulus_0])
    hswitch hvalue (fun column coefficient ↦ ?_) 0 index
  have hbound := herror 0 column coefficient
  have hmargin := decoding_margin
  rw [Int.abs_eq_natAbs]
  exact_mod_cast lt_of_le_of_lt (Nat.mul_le_mul_left 2 hbound) hmargin

/-- The stage facts still to be assembled from the existing conditional v2 modules. -/
structure CorrectInputs where
  /-- Step-0 imported state encoding, chosen by the initial/transition orchestrator. -/
  State0 : HashModel → GeneratedClaim.ExternalInputs → GeneratedClaim.Execution →
    ErrorPoly $N → Prop
  /-- Step-1 imported state encoding, including the refreshed-root error envelope. -/
  State1 : HashModel → GeneratedClaim.ExternalInputs → GeneratedClaim.Execution →
    ErrorPoly $N → Prop
  /-- Actual imported payload and label-row interpretation for either online step. -/
  Label : HashModel → GeneratedClaim.ExternalInputs → GeneratedClaim.Execution → Fin 2 →
    ErrorPoly $N → Prop
  /-- InitialTargets and Import0 must establish the initial monomial state. -/
  initial : ∀ {model external execution}, W_GeneratedClaim.Runs model external execution →
    State0 model external execution (Xe (n := $N) ($STRIDE * external.$INITIAL.toNat))
  /-- Initial/import/requirement assembly must establish both actual bit labels. -/
  labels : ∀ {model external execution}, W_GeneratedClaim.Runs model external execution →
    ∀ step : Fin 2, Label model external execution step
      (Xe (n := $N) ($STRIDE * (external.$BITS step).toNat))
  /-- The first state LUT, refreshed rows/keys and Import1 implement table0. -/
  step0 : ∀ {model external execution}, W_GeneratedClaim.Runs model external execution →
    ∀ (state bit : Nat), state ≤ 1 → bit ≤ 1 →
    Label model external execution 0 (Xe (n := $N) ($STRIDE * bit)) →
    State0 model external execution (Xe (n := $N) ($STRIDE * state)) →
    State1 model external execution
      (Xe (n := $N) ($STRIDE * (entry table0 ((state + bit : Nat) : Int)).toNat))
  /-- The second state LUT, smudge, solved preimage and output-key agreement
  establish the bounded unmasking witness, not an assumed successful decoder. -/
  step1 : ∀ {model external execution}, W_GeneratedClaim.Runs model external execution →
    ∀ (state bit : Nat), state ≤ 1 → bit ≤ 1 →
    Label model external execution 1 (Xe (n := $N) ($STRIDE * bit)) →
    State1 model external execution (Xe (n := $N) ($STRIDE * state)) →
    FinalOutput execution
      (Xe (n := $N) ($STRIDE * (entry table1 ((state + 1 + bit : Nat) : Int)).toNat))

/-- The two modular coefficient casts preserve an in-range monomial's zero/one values. -/
theorem coeff_val_Xe {value : Nat} (hvalue : $STRIDE * value < $N) (index : Fin $N) :
    (((((reducePoly ciphertextModulus $N (Xe (n := $N) ($STRIDE * value))).coeff
      index).val : Nat) : ZMod decodePrime).val : Int) =
      if index.val = $STRIDE * value then 1 else 0 := by
  haveI : Fact (1 < ciphertextModulus) := ⟨by norm_num [ciphertextModulus,
    W_Stage_online_1.modulus_0]⟩
  haveI : Fact (1 < decodePrime) := ⟨by norm_num [decodePrime, W_Stage_decode.modulus_0]⟩
  have hcoeff : (Xe (n := $N) ($STRIDE * value)).coeff index =
      if (⟨$STRIDE * value, hvalue⟩ : Fin $N) = index then 1 else 0 :=
    Negacyclic.coeff_root_pow (R := Int) (n := $N) (by norm_num)
      ⟨$STRIDE * value, hvalue⟩ index
  rw [reducePoly_coeff (by norm_num [ciphertextModulus, W_Stage_online_1.modulus_0])
    (by norm_num), hcoeff]
  by_cases hequal : index.val = $STRIDE * value
  · have heq : (⟨$STRIDE * value, hvalue⟩ : Fin $N) = index := Fin.ext hequal.symm
    simp [heq, hequal, ZMod.val_one]
  · have hne : ¬ (⟨$STRIDE * value, hvalue⟩ : Fin $N) = index :=
      fun heq ↦ hequal (by rw [← heq])
    simp [hne, hequal]

/-- An integer validity bit has a natural representative at most one. -/
theorem bit_nat {value : Int} (hzero : 0 ≤ value) (hone : value ≤ 1) :
    value = (value.toNat : Int) ∧ value.toNat ≤ 1 :=
  ⟨(Int.toNat_of_nonneg hzero).symm, by omega⟩

/-- Every worst-case run decodes its ideal output, conditional only on the stage contract. -/
theorem correct (inputs : CorrectInputs) {model : HashModel}
    {external : GeneratedClaim.ExternalInputs} {execution : GeneratedClaim.Execution}
    (hrun : W_GeneratedClaim.Runs model external execution) :
    execution.«$DECODE_OUTPUT» = execution.«ideal» := by
  have hvalid := hrun.1
  have hinitial := $VALID_INITIAL
  have hbits := $VALID_BITS
  obtain ⟨hinitialNat, hinitialBound⟩ := bit_nat hinitial.1 hinitial.2
  obtain ⟨hbit0Nat, hbit0Bound⟩ := bit_nat (hbits 0).1 (hbits 0).2
  obtain ⟨hbit1Nat, hbit1Bound⟩ := bit_nat (hbits 1).1 (hbits 1).2
  set initial := external.$INITIAL.toNat
  set bit0 := (external.$BITS 0).toNat
  set bit1 := (external.$BITS 1).toNat
  have hstate := inputs.step0 hrun initial bit0 hinitialBound hbit0Bound
    (inputs.labels hrun 0) (inputs.initial hrun)
  set state := (entry table0 ((initial + bit0 : Nat) : Int)).toNat
  have hstateBound : state ≤ 1 := by
    simp only [state]
    interval_cases initial <;> interval_cases bit0 <;> decide
  have houtput := inputs.step1 hrun state bit1 hstateBound hbit1Bound
    (inputs.labels hrun 1) hstate
  set finalState := (entry table1 ((state + 1 + bit1 : Nat) : Int)).toNat
  have hfinalBound : finalState ≤ 1 := by
    simp only [finalState]
    interval_cases state <;> interval_cases bit1 <;> decide
  have hdecode := decode_monomial W_GeneratedClaim.$DECODE_PARAMS _ finalState (by omega)
    (fun index ↦ by rw [final_output_residues houtput index]; exact coeff_val_Xe (by omega) index)
    _ ($RUN_DECODE)
  rw [hdecode, ideal_value W_GeneratedClaim.ideal_params _ _ _ ($RUN_IDEAL),
    hinitialNat, hbit0Nat, hbit1Nat]
  simp only [finalState, state]
  interval_cases initial <;> interval_cases bit0 <;> interval_cases bit1 <;> decide

/-- The exact exported average-case claim: the failure set is empty and has measure zero. -/
theorem certificate (inputs : CorrectInputs) : GeneratedClaim.CorrectnessClaim := by
  intro model external
  have hempty : {tape | ∃ execution, GeneratedClaim.Runs model external tape execution ∧
      ¬ execution.«$DECODE_OUTPUT» = execution.«ideal»} = ∅ := by
    ext tape
    simp only [Set.mem_setOf_eq, Set.mem_empty_iff_false, iff_false]
    rintro ⟨execution, hruns, hne⟩
    exact hne (correct inputs (GeneratedClaim.runs_bridge hruns))
  rw [hempty, MeasureTheory.measure_empty]
  exact zero_le _

end Dio2Proof
''')


def projection(base, index, count):
    return base + '.2' * index + ('.1' if index < count - 1 else '')


def conjunction_pattern(atoms, names):
    return ', '.join(names.get(index, '-') for index in range(len(atoms)))


def render(package, data):
    for relative, digest in data['sources'].items():
        meta.require(hashlib.sha256((package / relative).read_bytes()).hexdigest() == digest,
                     f'export changed since metadata extraction: {relative}')
    view = data['views']['worst']
    dimension = view['ring_dimension']
    directory = package / 'worst'
    decode = meta.Module(directory, 'W_Stage_decode', {})
    ideal = meta.Module(directory, 'W_Ideal', {})
    decode_input = meta.one((wire for wire in decode.root.wires.values()
                            if wire.term == 'inputs'), 'decode matrix input')
    shape = decode.dimension(decode.root, decode_input.name)
    meta.require(shape == dict(modulus=view['primes'][0], n=dimension, rows=1, columns=1),
                 'decode shape does not match metadata first prime')
    loop = meta.one(decode.root.loops, 'decode coefficient loop').loop
    meta.require(loop.count == dimension, 'decode loop is not coefficient-sized')
    child = decode.scopes[loop.child]
    get = meta.one((atom for atom in child.atoms if atom.kind == 'familyGetDynamic'),
                   'decode coefficient selection')
    values = meta.one((atom for atom in decode.root.atoms if atom.kind == 'polynomialValues'),
                      'decode coefficient family')
    meta.require(values.args[0] == 'false', 'decoder requires unsigned canonical coefficients')
    result = meta.one(meta.output_wires(decode.root), 'decode result')
    division = meta.xmodel.strip_parens(decode.root.wires[result].term).split(' / ')
    meta.require(len(division) == 2, 'decode final operation must be division')
    stride = meta.scalar(decode.root, division[1], 0)
    meta.require(0 < stride < dimension, 'invalid decode stride')
    family = values.args[-1]
    root_names = {decode.root.atoms.index(values): 'hvalues',
                  decode.root.atoms.index(meta.one(decode.root.loops, 'decode loop')): 'hiter',
                  len(decode.root.atoms) - 1: 'hout'}
    child_names = {child.atoms.index(get): '⟨position, hposition, hvalue⟩',
                   len(child.atoms) - 1: 'hnext'}
    selects = [atom for atom in ideal.root.atoms if atom.kind == 'select']
    bit_gets = [atom for atom in ideal.root.atoms if atom.kind == 'familyGetStatic']
    meta.require(len(selects) == len(bit_gets) == 2, 'only the exported two-step claim is supported')
    tables = [[meta.scalar(ideal.root, wire, 0) for wire in meta.xmodel.WIRE.findall(atom.args[1])]
              for atom in selects]
    meta.require(tables == [[1, 0, 1, 0], [0, 1, 1, 0]], 'ideal Boolean function changed')
    for step, table in enumerate(tables):
        meta.require(any(entry['values'] == table
                         for entry in view['lut_tables'][f'preprocess_{step}_{step}']),
                     'ideal state table is absent from preprocessed metadata')
    ideal_names = {len(ideal.root.atoms) - 1: 'hout'}
    for step, (select, bit_get) in enumerate(zip(selects, bit_gets)):
        meta.require(meta.integer(bit_get.args[1]) == step, 'ideal bit order changed')
        ideal_names[ideal.root.atoms.index(bit_get)] = (
            f'⟨position{step}, hposition{step}, hbit{step}⟩')
        ideal_names[ideal.root.atoms.index(select)] = f'hselect{step}'
    worst_claim = (directory / 'W_Claim.lean').read_text()
    runs = worst_claim.split('def Runs ', 1)[1].split(': Prop :=', 1)[1].split('\nend ', 1)[0]
    clauses = [part.strip() for part in runs.split(' ∧\n')]
    decode_index, decode_clause = meta.one(((index, clause) for index, clause in enumerate(clauses)
                                           if clause.startswith('W_Stage_decode.generatedRoot')),
                                          'claim decoder connection')
    ideal_index, ideal_clause = meta.one(((index, clause) for index, clause in enumerate(clauses)
                                         if clause.startswith('W_Ideal.generatedRoot')),
                                        'claim ideal connection')
    decode_connection = re.fullmatch(
        r'W_Stage_decode.generatedRoot (\w+) \(execution\.«(\w+)»\.1\) execution\.«(\w+)»',
        decode_clause)
    ideal_connection = re.fullmatch(
        r'W_Ideal.generatedRoot ideal_params \(\(external\.(\w+), external\.(\w+), \(\)\)\) execution\.«ideal»',
        ideal_clause)
    meta.require(decode_connection and ideal_connection, 'unsupported claim endpoint wiring')
    initial, bits = ideal_connection.groups()
    claim = (package / 'generated/Claim.lean').read_text()
    validity = claim.split('def ValidExternals ', 1)[1].split(': Prop :=', 1)[1].split(
        '\nstructure Execution', 1)[0]
    conditions = [part.strip() for part in validity.split(' ∧\n')]
    initial_index = meta.one((index for index, clause in enumerate(conditions)
                              if f'external.{initial}' in clause), 'initial validity bit')
    bits_index = meta.one((index for index, clause in enumerate(conditions)
                           if f'external.{bits} ' in clause), 'payload validity bits')
    meta.require(f'Fin 2 → Int' in meta.one((line for line in claim.splitlines()
                 if re.match(rf'  {bits} :', line)), 'claim bit type'), 'not a two-step bit family')
    failure = meta.one(re.findall(r'≤ \(2 : ENNReal\)⁻¹ \^ (\d+)', claim), 'failure exponent')
    online = view['claim_stages'][-2]
    meta.require(online == 'W_Stage_online_1', 'unexpected final online stage')
    values = dict(N=dimension, STRIDE=stride, LOOP=loop.child, FAMILY=family,
                  LOOP_PATTERN=conjunction_pattern(child.atoms, child_names),
                  ROOT_PATTERN=conjunction_pattern(decode.root.atoms, root_names),
                  TABLE0=str(tables[0]), TABLE1=str(tables[1]),
                  PATTERN=conjunction_pattern(ideal.root.atoms, ideal_names),
                  ROOT=dimension + 2, INITIAL=initial, BITS=bits, FAILURE=failure,
                  DECODE_PARAMS=decode_connection[1], ONLINE_OUTPUT=decode_connection[2],
                  DECODE_OUTPUT=decode_connection[3],
                  VALID_INITIAL=projection('hvalid', initial_index, len(conditions)),
                  VALID_BITS=projection('hvalid', bits_index, len(conditions)),
                  RUN_DECODE=projection('hrun', decode_index, len(clauses)),
                  RUN_IDEAL=projection('hrun', ideal_index, len(clauses)))
    return {'Dio2Decode.lean': DECODE.substitute(values),
            'Dio2Ideal.lean': IDEAL.substitute(values),
            'Dio2Correct.lean': CORRECT.substitute(values)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('package', type=Path)
    parser.add_argument('--metadata', type=Path)
    parser.add_argument('--output-dir', type=Path)
    args = parser.parse_args()
    data = json.loads(args.metadata.read_text()) if args.metadata else meta.extract(args.package)
    files = render(args.package, data)
    output = args.output_dir or args.package / 'proof'
    output.mkdir(parents=True, exist_ok=True)
    for name, source in files.items():
        (output / name).write_text(source)
    print(f'{data["package"]}: generated {", ".join(files)} in {output}', flush=True)


if __name__ == '__main__':
    main()
