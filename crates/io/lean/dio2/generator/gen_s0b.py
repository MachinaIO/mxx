def certificate_source(package, metadata):
    view = metadata['views']['worst']
    n, columns = view['ring_dimension'], view['columns']
    anchor, parts = view['anchor_columns'], view['refresh']['parts']
    primes = view['refresh']['primes']
    prime_count = len(primes)
    source = '''import Dio2Online0Assembly
import Dio2Online0Label

''' + HEADER + f'''namespace Online0Assembly

open Dio2NoiseCertificate W_Stage_online_0

/-- Quotients in exactly the exported CRT-term order. -/
def primeQuotient : Fin {prime_count} → Nat :=
  ![{', '.join(f'quotient{prime["index"]}' for prime in primes)}]

/-- The certificate bounds the error of every part at every prime. -/
theorem noise_margin (part : Fin {parts}) (prime : Fin {prime_count}) :
    2 * ({anchor} * {n} * 1 * cutoff +
      ({columns} * {n} * b1_g * half + {columns} * {n} * b1_one * half +
        {columns} * {n} * targetBudget part * half) + b1_fresh + b1_smudge +
      b1_residue) < primeQuotient prime := by
  fin_cases prime
'''
    source += ''.join(f'  · exact noise_margin{prime["index"]} part\n' for prime in primes)
    source += f'''
/-- Real semantic budgets need only be dominated by the checked class budgets. -/
theorem noise_margin_of_bounds (part : Fin {parts}) (prime : Fin {prime_count})
    {{Beb BP Beg Be1 Bex Bf Bs BM : Nat}}
    (hBeb : Beb ≤ 1) (hBP : BP ≤ cutoff)
    (hBeg : Beg ≤ b1_g) (hBe1 : Be1 ≤ b1_one)
    (hBex : Bex ≤ targetBudget part) (hBf : Bf ≤ b1_fresh)
    (hBs : Bs ≤ b1_smudge) (hBM : BM ≤ b1_residue) :
    2 * ({anchor} * {n} * Beb * BP +
      ({columns} * {n} * Beg * half + {columns} * {n} * Be1 * half +
        {columns} * {n} * Bex * half) + Bf + Bs + BM) < primeQuotient prime :=
  lt_of_le_of_lt
    (noise_expression_mono part hBeb hBP hBeg hBe1 hBex hBf hBs hBM)
    (noise_margin part prime)

'''
    label_source = (package / 'proof/Dio2Online0Label.lean').read_text()
    label_signature = re.search(
        r'theorem online0_label_target\b(.*?) := by', label_source, re.S)
    meta.require(label_signature is not None, 'missing symbolic label target theorem')
    signature = label_signature[1]
    bound_definitions = re.findall(r'^def (online0_label_bound_\d+) .*$', label_source, re.M)
    meta.require(bound_definitions, 'missing label forest bounds')
    result_bound = re.search(r'\!\[outputs\.1, outputs\.2\.1\] \((.*?)\)\s*$', signature, re.S)
    meta.require(result_bound is not None, 'unexpected label target result')
    expression = result_bound[1].replace('Bs', 'b1_public').replace(' B ', ' 1 ')
    expression = re.sub(r'\bB\b', '1', expression)
    source += f'''/-- The sharp symbolic forest/retarget bound fits the label certificate. -/
theorem label_target_budget :
    {expression} ≤ b1_label := by
  norm_num [{', '.join(bound_definitions)}, b1_label, b1_public]

end Online0Assembly

open W_Stage_online_0 Dio2NoiseCertificate

'''
    certified_signature = signature.replace('{B Bs : Nat}', '')
    certified_signature = re.sub(r'\bB\b', '1', certified_signature)
    certified_signature = re.sub(r'\bBs\b', 'b1_public', certified_signature)
    certified_signature = certified_signature.replace(f'({expression})', 'b1_label')
    meta.require('b1_label' in certified_signature, 'label result bound replacement failed')
    source += f'''/-- A complete label forest uses the certified sharp budget for each member. -/
theorem online0_label_target_certified{certified_signature} := by
  obtain ⟨plaintext, hpayload, hgain, hrel⟩ :=
    online0_label_target member ctx F hn hq layout hlayout hexact hG hleaves hs
  exact ⟨plaintext, hpayload, hgain, hrel.mono Online0Assembly.label_target_budget⟩

end Dio2Proof
'''
    return source


def prime_source(package, metadata):
    view = metadata['views']['worst']
    parts = view['refresh']['parts']
    original = (package / 'proof/Dio2Online0PartPrimes.lean').read_text()
    source = 'import Dio2Step0Certificate\n\n' + HEADER
    source += 'open W_Stage_online_0 Dio2NoiseCertificate\n\n'
    source += '''/-- Inverse CRT corrections preserve any symbolic plaintext polynomial. -/
theorem online0_scalar_inverse_gen {n q Q : Nat} (hn : 0 < n)
    (hq : 1 < q) (hQ : 1 < Q) (hqQ : q ∣ Q) (scalar correction : Int)
    (hinverse : ((scalar * correction : Int) : ZMod q) = 1) (plaintext : ErrorPoly n) :
    reducePoly q n ((scalar : ErrorPoly n) * plaintext) * (1 : ExactPoly q n) *
      (correction : ExactPoly q n) = rho q (reducePoly Q n plaintext) := by
  rw [rho_reduce hn hq hQ hqQ, map_mul, reducePoly_intCast, mul_one]
  calc
    (scalar : ExactPoly q n) * reducePoly q n plaintext * (correction : ExactPoly q n) =
        ((scalar * correction : Int) : ExactPoly q n) * reducePoly q n plaintext := by
      push_cast
      ring
    _ = reducePoly q n plaintext := by
      rw [intCast_eq_algebraMap, hinverse, map_one, one_mul]

'''
    for prime in view['refresh']['primes']:
        index = prime['index']
        match = re.search(
            rf'theorem online0_part_prime{index}\b(.*?) := by', original, re.S)
        meta.require(match is not None, f'missing prime kernel {index}')
        signature = match[1]
        start = signature.index('    (hnoise :')
        stop = signature.index(' :\n    TermOf', start)
        signature = signature[:start] + f'''    (index : Fin {parts}) (hindex : index.val = i)
    (hBeb : Beb ≤ 1) (hBP : BP ≤ cutoff)
    (hBeg : Beg ≤ b1_g) (hBe1 : Be1 ≤ b1_one)
    (hBex : Bex ≤ Online0Assembly.targetBudget index)
    (hBf : Bf ≤ b1_fresh) (hBs : Bs ≤ b1_smudge) (hBM : BM ≤ b1_residue)''' + signature[stop:]
        source += f'''/-- Prime {index}: the strict margin is proved from the certificate.
The remaining hypotheses are actual row, source-key and preimage equations. -/
theorem online0_part_prime{index}_certified{signature} := by
  subst i
  have hnoise := Online0Assembly.noise_margin_of_bounds index
    ({index} : Fin {len(view['refresh']['primes'])})
    hBeb hBP hBeg hBe1 hBex hBf hBs hBM
  exact online0_part_prime{index} ctx F L hL hLx hc heg he1 hex hg hc₁ hcx hscalar
    hb heb hP hPd hpre hf hef hs hes hTH hM hnoise

'''
        meta.require(prime['s9'] == 1, 'CRT scalar generator requires unit first correction')
        scalar, remainder = divmod(prime['cprime'], prime['quotient'])
        meta.require(remainder == 0, 'nonintegral CRT scalar')
        qname = f'modulus_{index + 1}'
        n = view['ring_dimension']
        source += f'''/-- Prime {index}: the exported correction is an exact inverse for every plaintext. -/
theorem online0_scalar_inverse{index} (plaintext : ErrorPoly {n}) :
    reducePoly {qname} {n} (({scalar} : ErrorPoly {n}) * plaintext) *
      ((1 : Int) : ExactPoly {qname} {n}) *
      (({prime['s10']} : Int) : ExactPoly {qname} {n}) =
        rho {qname} (reducePoly modulus_0 {n} plaintext) := by
  exact online0_scalar_inverse_gen (by decide) (by norm_num [{qname}])
    (by norm_num [modulus_0])
    (by norm_num [modulus_0, {qname}]) {scalar} {prime['s10']}
    (by decide) plaintext

'''
        canonical = re.sub(r'    \{k : Int\} \(hc :.*?\n(?=    \{s β)', '', signature,
                           count=1, flags=re.S)
        canonical = re.sub(r'    \{T : ExactPoly.*?\n(?=    \{Bk)', '', canonical,
                           count=1, flags=re.S)
        canonical = re.sub(r'\bT\b', f'(reducePoly modulus_0 {n} x)', canonical)
        source += f'''/-- Prime {index}: neither the scalar identity nor the strict noise margin is assumed. -/
theorem online0_part_prime{index}_canonical{canonical} := by
  exact online0_part_prime{index}_certified ctx F L hL hLx
    (k := {scalar}) (by norm_num) heg he1 hex hg hc₁ hcx
    (online0_scalar_inverse{index} x) hb heb hP hPd hpre hf hef hs hes hTH hM
    index hindex hBeb hBP hBeg hBe1 hBex hBf hBs hBM

'''
    return source + 'end Dio2Proof\n'


def label_source(package, metadata):
    view = metadata['views']['worst']
    n, columns = view['ring_dimension'], view['columns']
    base = meta.one(metadata['backend_layouts'], 'backend layout')['base']
    stages = initial.claim_stages(package)
    online = meta.Module(package / 'worst', 'W_Stage_online_0', {})
    supplied = dict(zip(
        (wire.name for wire in online.root.wires.values() if wire.src == 'input'),
        support.claim_tuple(package, 'online_0', stages)))
    targets = (package / 'proof/Dio2InitialTargets.lean').read_text()
    source = 'import Dio2Online0Inputs\nimport Dio2Step0Certificate\n\n' + HEADER
    source += '''namespace Online0Labels

/-- Selection transports every component of a symbolic node together. -/
theorem select_node {n q columns : Nat} {sm : ErrorPoly n}
    {gadget : ExactMatrix q n 1 columns} {bound : Nat} {flag : Bool}
    {left0 left1 left00 left01 left10 left11 : ExactMatrix q n 1 columns}
    {right0 right1 right00 right01 right10 right11 : ExactMatrix q n 1 columns}
    {out0 out1 out00 out01 out10 out11 : ExactMatrix q n 1 columns}
    {leftPayload rightPayload outPayload : ExactMatrix q n 1 1}
    (left : Node sm gadget bound left0 left1 left00 left01 left10 left11 leftPayload)
    (right : Node sm gadget bound right0 right1 right00 right01 right10 right11 rightPayload)
    (cipher0 : select (if flag then 1 else 0) [left0, right0] out0)
    (cipher1 : select (if flag then 1 else 0) [left1, right1] out1)
    (key00 : select (if flag then 1 else 0) [left00, right00] out00)
    (key01 : select (if flag then 1 else 0) [left01, right01] out01)
    (key10 : select (if flag then 1 else 0) [left10, right10] out10)
    (key11 : select (if flag then 1 else 0) [left11, right11] out11)
    (payload : select (if flag then 1 else 0) [leftPayload, rightPayload] outPayload) :
    Node sm gadget bound out0 out1 out00 out01 out10 out11 outPayload := by
  rw [select_pair cipher0, select_pair cipher1, select_pair key00,
    select_pair key01, select_pair key10, select_pair key11, select_pair payload]
  cases flag
  · exact left
  · exact right

end Online0Labels

open W_Stage_online_0

'''
    for suffix, stem, count in [
            ('label', 'label', view['labels']['members']),
            ('label_0', 'label0', view['labels']['root_members'])]:
        match = re.search(rf'theorem initial_rel_row_dio2_{suffix}\b(.*?) :=\n',
                          targets, re.S)
        meta.require(match is not None, f'missing initial {suffix} relation')
        signature = match[1]
        key_match = re.search(r'Rel sm (\(rootKey .*?\))\n', signature)
        meta.require(key_match is not None, f'missing initial {suffix} keys')
        key = key_match[1].replace('inputs', '(Claim0.initialInputs external execution)')
        gain = re.search(rf'theorem initial_gain_row_dio2_{suffix}\b.*? : '
                         rf'SmulGain \(n := {n}\) (.*?) 1 := by', targets, re.S)
        meta.require(gain is not None, f'missing initial {suffix} gain')
        alpha = gain[1].replace('inputs', '(Claim0.initialInputs external execution)')
        rows = re.search(r'!\[(.*?)\] 1$', signature, re.S)
        meta.require(rows is not None, f'missing initial {suffix} rows')
        initial_rows = meta.xmodel.split_top(rows[1], ',')
        meta.require(len(initial_rows) == 2, 'initial label must have two rows')
        online_rows = []
        proofs = []
        for row in initial_rows:
            exported = meta.xmodel.strip_parens(row).replace(
                'outputs', f'execution.«stage_{stages["initial"][0]}»')
            family = exported.removesuffix(' member')
            name = meta.one((name for name, value in supplied.items()
                             if meta.xmodel.strip_parens(value) == family),
                            f'actual online input for {suffix} row')
            online_rows.append(f'generatedRoot.{name} state.context.online member')
            field = online.root.wires[name].term
            proofs.append(f'''  have wire_{name} : {online_rows[-1]} = {exported} := by
    change state.context.online.{field} member = _
    simp only [state.context.online_inputs, Claim0.onlineInputs]
''')
        source += f'''/-- The actual initial {suffix} plaintext, indexed symbolically. -/
noncomputable def initial_{stem}_value (external : GeneratedClaim.ExternalInputs)
    (execution : GeneratedClaim.Execution) (member : Fin {count}) : ErrorPoly {n} :=
  {alpha}

noncomputable def initial_{stem}_keys (model : HashModel)
    (external : GeneratedClaim.ExternalInputs) (execution : GeneratedClaim.Execution)
    (member : Fin {count}) : Fin 2 → Fin 2 → ExactMatrix modulus_0 {n} 1 {columns} :=
  {key}

/-- Every real imported {suffix} root is a gain-one forest node; no member is expanded. -/
theorem online0_initial_{stem}_nodes {{model : HashModel}}
    {{external : GeneratedClaim.ExternalInputs}} {{execution : GeneratedClaim.Execution}}
    {{value : ErrorPoly {n}}} (hrun : W_GeneratedClaim.Runs model external execution)
    (state : State0Witness model external execution value)
    {{gadget : ExactMatrix modulus_0 {n} 1 {columns}}}
    (hG : gadgetMatrixRuns Backend.backend {base} {columns} gadget)
    (member : Fin {count}) :
    Online0Labels.Node state.mask gadget 1
      ({online_rows[0]}) ({online_rows[1]})
      (initial_{stem}_keys model external execution member 0 0)
      (initial_{stem}_keys model external execution member 0 1)
      (initial_{stem}_keys model external execution member 1 0)
      (initial_{stem}_keys model external execution member 1 1)
      (fun _ _ ↦ reducePoly modulus_0 {n} (initial_{stem}_value external execution member)) := by
{''.join(proofs)}  refine ⟨initial_{stem}_value external execution member, rfl, ?_, ?_⟩
  · exact initial_gain_row_dio2_{suffix}
      (inputs := Claim0.initialInputs external execution)
      (sm := state.mask) (tp := state.payload) member
  · have keys_eta :
        ![![initial_{stem}_keys model external execution member 0 0,
            initial_{stem}_keys model external execution member 0 1],
          ![initial_{stem}_keys model external execution member 1 0,
            initial_{stem}_keys model external execution member 1 1]] =
          initial_{stem}_keys model external execution member := by
      funext key component
      fin_cases key <;> fin_cases component <;> rfl
    rw [keys_eta]
    simpa only [{', '.join('wire_' + meta.xmodel.WIRE.findall(row)[0] for row in online_rows)},
      initial_{stem}_keys, initial_{stem}_value] using
      initial_rel_row_dio2_{suffix} (Claim0.initial_runs hrun)
        state.mask_eq state.payload_eq hG member

'''
    return source + 'end Dio2Proof\n'


def leaf_source(package, metadata):
    import gen_adapters as adapters
    view = metadata['views']['worst']
    n, columns = view['ring_dimension'], view['columns']
    forest = meta.one((entry for entry in view['label_forest_scopes']['online_0']
                       if entry['children']), 'label forest')
    online = meta.Module(package / 'worst', 'W_Stage_online_0', {})
    scope = online.scopes[forest['children'][0]]
    binders, call, _ = adapters.header(scope)
    term = lambda wire: adapters.wire_term(scope, wire)
    flow = meta.Flow(scope)
    selections = [atom for atom in scope.atoms if atom.kind == 'select']
    meta.require(len(selections) == 7, 'forest leaf must select seven node fields')
    pairs = [[entry.strip() for entry in
              meta.xmodel.split_top(meta.xmodel.strip_parens(atom.args[1])[1:-1], ',')]
             for atom in selections]
    left = [pair[0] for pair in pairs]
    right = [pair[1] for pair in pairs]
    reads = {atom.args[-1]: atom for atom in scope.atoms if atom.kind == 'familyGetDynamic'}
    samples = {atom.args[-1]: atom for atom in scope.atoms if atom.kind == 'hashSample'}
    read0, read1 = reads[right[0]], reads[right[1]]
    index = read0.args[1]
    meta.require(read1.args[1] == index, 'forest ciphertext indices differ')
    index_wire = scope.wires[index]
    index_parts = meta.xmodel.WIRE.findall(index_wire.term)
    meta.require(len(index_parts) == 2, 'label index must be row offset plus column')
    column = index_parts[1]
    first_sample = samples[right[2]]
    prefix = first_sample.args[1]
    tags = meta.xmodel.split_top(meta.xmodel.strip_parens(first_sample.args[2])[1:-1], ',')
    meta.require(len(tags) == 4, 'label sample must have member and component tags')
    seed = term(meta.xmodel.WIRE.findall(first_sample.args[3])[0])
    tag_member = f'[{tags[0]}, .u64Le (member.val : Int)]'
    key = f'rootKey hashModel {seed} {prefix} {tag_member} modulus_0 {columns}'
    plaintext = flow.op(right[6], 'multiplyMonomial')
    meta.require(len(plaintext) == 2, 'label payload must be a monomial')
    payload_reads = [atom for atom in reads.values() if atom is not read0 and atom is not read1]
    payload_read = meta.one(payload_reads, 'label payload index')
    payload_family, payload_index, payload_value = payload_read.args
    width = view['labels']['columns']
    full_width = width + 1
    normalized = f'((member.val : Int) / {width} * {full_width} + '
    normalized += f'(member.val : Int) % {width} + 1)'
    alpha = f'message 1 (intFamilyValue ({term(payload_family)}) {normalized})'
    per, flat = adapters.atom_names(scope)
    per = adapters.use_rfl_out(per, flat)
    factmap = {atom.field: name for atom, (name, _) in zip(scope.atoms, flat)}
    proof = [f'  obtain {adapters.pattern(scope, per)} := h']
    proof += [f'  obtain ⟨member, memberIndex, row0⟩ := {factmap[read0.field]}',
              f'  have row1 := Online0Labels.read_at member memberIndex {factmap[read1.field]}']
    column_dependencies = set()

    def visit(name):
        if name in column_dependencies:
            return
        column_dependencies.add(name)
        wire = scope.wires[name]
        if wire.src == 'let':
            for dependency in meta.xmodel.WIRE.findall(wire.term):
                visit(dependency)

    visit(column)
    bit_wires = [wire for wire in scope.wires.values()
                 if wire.name in column_dependencies and wire.src == 'let'
                 and wire.term.startswith('if ')]
    meta.require(bit_wires, 'missing label column bit selections')
    for index_bit, wire in enumerate(bit_wires):
        proof.append(f'''  have bit_bound_{index_bit} : 0 ≤ ({term(wire.name)} : Int) ∧
      ({term(wire.name)} : Int) ≤ 1 := by split <;> omega''')
    proof += [f'''  have column_bound : 0 ≤ ({term(column)} : Int) ∧
      ({term(column)} : Int) < {width} := by omega''',
              f'''  have normalized_index : {normalized} = {term(payload_index)} := by omega''']
    for key_index, name in enumerate(right[2:6]):
        sample = samples[name]
        key_row, key_column = divmod(key_index, 2)
        proof.append(f'''  have key_{key_index} : {name} = ({key}) {key_row} {key_column} := by
    have sampled := hashSample_eq {factmap[sample.field]}
    change {name} = hashModel.sample modulus_0 {n} 1 {columns} {seed}
      (completeHashTag {prefix} [{tags[0]}, .u64Le (member.val : Int),
        {tags[2]}, .u64Le ({key_index})])
    simpa only [memberIndex] using sampled''')
    proof += [f'''  have payload_value := int_family_value {factmap[payload_read.field]}''',
              f'''  have payload_eq : {term(right[6])} =
      (fun _ _ ↦ reducePoly modulus_0 {n} ({alpha})) := by
    funext row column
    have row_zero : row = 0 := Subsingleton.elim _ _
    have column_zero : column = 0 := Subsingleton.elim _ _
    subst row column
    rw [normalized_index]
    simpa only [payload_value, Int.mul_one, one_mul] using
      (mono_entry (one_entry (q := modulus_0) (n := {n})) ({term(plaintext[1])}))''',
              '  have selected := labels member',
              '  rw [← row0, ← row1, ← key_0, ← key_1, ← key_2, ← key_3, ← payload_eq] at selected',
              '  exact Online0Labels.select_node unit selected ' +
              ' '.join(factmap[atom.field] for atom in selections)]
    output = ' '.join(f'(outputs{'.2' * index}.1)' for index in range(7))
    return 'import Dio2Step0Labels\n\n' + HEADER + f'''open W_Stage_online_0

/-- Every exported leaf reads one common label member, including its exact
payload exponent, and selects all seven node fields consistently. -/
theorem online0_forest_leaf {binders}
    {{sm : ErrorPoly {n}}} {{gadget : ExactMatrix modulus_0 {n} 1 {columns}}}
    (unit : Online0Labels.Node sm gadget 1 {' '.join(f'({term(wire)})' for wire in left)})
    (labels : ∀ member : Fin {view['labels']['members']},
      Online0Labels.Node sm gadget 1 ({term(read0.args[0])} member) ({term(read1.args[0])} member)
        (({key}) 0 0) (({key}) 0 1) (({key}) 1 0) (({key}) 1 1)
        (fun _ _ ↦ reducePoly modulus_0 {n} ({alpha})))
    (h : {call}) : Online0Labels.Node sm gadget 1 {output} := by
''' + '\n'.join(proof) + '\n\nend Dio2Proof\n'


def forest_source(package, metadata):
    view = metadata['views']['worst']
    forest = meta.one((entry for entry in view['label_forest_scopes']['online_0']
                       if entry['children']), 'label forest')
    online = meta.Module(package / 'worst', 'W_Stage_online_0', {})
    scope = online.scopes[forest['scope']]
    leaf = online.scopes[forest['children'][0]]
    loop = meta.one((atom for atom in scope.loops
                     if atom.loop.child == leaf.name), 'label leaf loop')
    source = certificate_source(package, metadata)
    signature = re.search(r'theorem online0_label_target_certified\b(.*?) := by',
                          source, re.S)[1]
    leaf_signature = re.search(r'    \(unit : (.*?)\n    \(h :',
                               leaf_source(package, metadata), re.S)[0]
    leaf_signature = leaf_signature[:leaf_signature.rfind('\n    (h :')]
    input_wires = [wire for wire in leaf.wires.values() if wire.src == 'input']
    replacements = {wire.term: initial.replace_wires(argument,
        lambda name: f'({scope.name}.{name} ctx)')
        for wire, argument in zip(input_wires, loop.loop.args)}
    leaf_signature = re.sub(r'\binputs(?:\.2)*\.1',
                            lambda match: replacements[match[0]], leaf_signature)
    gadget = re.search(r'\(hG : gadgetMatrixRuns.*?\((.*?)\)\)', signature)[1]
    leaf_signature = re.sub(r'\bgadget\b', f'({gadget})', leaf_signature)
    leaves_start = signature.index('    (hleaves :')
    leaves_stop = signature.index('    (hs :', leaves_start)
    leaves_type = signature[leaves_start:leaves_stop].strip()
    meta.require(leaves_type.endswith(')'), 'unbalanced forest leaves premise')
    leaves_type = leaves_type.removeprefix('(hleaves :').removesuffix(')')
    signature = signature[:leaves_start] + leaf_signature + '\n' + signature[leaves_stop:]
    actual_inputs = '(' + ', '.join(replacements.values()) + ', ())'
    actual_outputs = '(' + ', '.join(
        f'({scope.name}.{output.split()[0]} ctx index)' for output in loop.loop.outs) + ', ())'
    return 'import Dio2Step0Leaves\n\n' + HEADER + f'''open W_Stage_online_0 Dio2NoiseCertificate

/-- The symbolic forest and its certified target bound follow from the initial
label family and inactive unit node, not an assumed family of processed leaves. -/
theorem online0_label_target_from_roots{signature} := by
  have hleaves : {leaves_type} := by
    intro index
    exact online0_forest_leaf (backend := backend) (hashModel := hashModel)
      (params := params) (x_0 := member.val) (i_1 := index.val)
      (inputs := {actual_inputs}) (outputs := {actual_outputs})
      (sm := sm) (gadget := {gadget}) unit labels ({initial.atom_fact(loop, 'F')} index)
  exact online0_label_target_certified member ctx F hn hq layout hlayout hexact hG hleaves hs

end Dio2Proof
'''


def transport_source(package, metadata):
    view = metadata['views']['worst']
    n, columns = view['ring_dimension'], view['columns']
    stages = initial.claim_stages(package)
    online = meta.Module(package / 'worst', 'W_Stage_online_1', {})
    imported = meta.Module(package / 'worst', 'W_Stage_import_1', {})
    inputs = [wire for wire in imported.root.wires.values() if wire.src == 'input']
    values = {wire.name: argument for wire, argument in zip(
        inputs, support.claim_tuple(package, 'import_1', stages))}
    for atom in imported.root.loops:
        for output, argument in zip(atom.loop.outs[:2], atom.loop.args[:2]):
            values[output.split()[0]] = initial.replace_wires(
                argument, values.__getitem__).removesuffix(' i')
    for wire in imported.root.wires.values():
        if wire.src == 'let' and all(
                source in values for source in meta.xmodel.WIRE.findall(wire.term)):
            values[wire.name] = initial.replace_wires(wire.term, values.__getitem__)
    import_values = {projection: values[wire] for projection, wire in zip(
        support.output_projections(imported.root,
            f'execution.«stage_{stages["import_1"][0]}»'),
        meta.output_wires(imported.root)) if wire in values}
    root_inputs = [wire for wire in online.root.wires.values() if wire.src == 'input']
    supplied = dict(zip((wire.name for wire in root_inputs),
        support.claim_tuple(package, 'online_1', stages)))
    actual = {name: import_values.get(meta.xmodel.strip_parens(value), value)
        for name, value in supplied.items()}
    state_source = (package / 'proof/Dio2Online1Inputs.lean').read_text()
    match = re.search(r'structure Online1Roots\b(.*?) : Prop where\n(.*?)\n/--',
                      state_source, re.S)
    meta.require(match is not None, 'missing shared Online1Roots interface')
    body = match[2]
    payload = re.search(r'  payload :.*?(?=\n  \w+ :)', body, re.S)
    meta.require(payload is not None, 'missing imported payload field')
    body = body[:payload.start()] + body[payload.end():]
    referenced = list(dict.fromkeys(re.findall(r'generatedRoot\.(w_\d+_\d+) online', body)))
    samples = {meta.xmodel.WIRE.findall(atom.args[-1])[0]: atom
        for atom in online.root.atoms if atom.kind == 'hashSample'}
    equations = []
    for name in referenced:
        if name in samples:
            atom = samples[name]
            prefix, tags, key = atom.args[1:4]
            key = initial.replace_wires(key, actual.__getitem__)
            value = f'(model.sample modulus_0 {n} 1 {columns} {key} ' \
                    f'(completeHashTag {prefix} {tags}))'
            actual[name] = value
            proof = f'''  have wire_{name} : generatedRoot.{name} online = {value} := by
    have sampled := hashSample_eq {initial.atom_fact(atom, 'facts')}
    simpa only [wire_{meta.xmodel.WIRE.findall(atom.args[3])[0]}] using sampled
'''
        else:
            meta.require(name in actual, f'unresolved refreshed root input {name}')
            wire = online.root.wires[name]
            proof = f'''  have wire_{name} : generatedRoot.{name} online = {actual[name]} := by
    change online.{wire.term} = _
'''
            if actual[name] != supplied[name]:
                proof += f'''    rw [hinputs]
    change {supplied[name]} = _
    rw [import1_spec (import1_claim_runs hrun)]
    rfl
'''
            else:
                proof += '    simp only [hinputs, online1ClaimInputs]\n'
        equations.append((name, proof))
    key_names = {meta.xmodel.WIRE.findall(atom.args[3])[0]
        for name, atom in samples.items() if name in referenced}
    equations.sort(key=lambda entry: (entry[0] not in key_names, entry[0] in samples))
    for name in referenced:
        body = body.replace(f'generatedRoot.{name} online', actual[name])
    body = body.replace('labelValue', '(online1Labels external)')
    anchor = meta.one(re.findall(
        r'Online1Roots online (execution\.\S+) sm sp state', state_source),
        'shared step-one anchor matrix')
    body = re.sub(r'\banchor\b', f'({anchor})', body)
    payload_name = meta.one(re.findall(r'generatedRoot\.(w_\d+_\d+) online',
                                      payload[0]), 'imported payload wire')
    payload_wire = online.root.wires[payload_name]
    import_payload = meta.one([atom for atom in imported.root.loops
        if len(atom.loop.outs) == 3], 'imported label payload loop')
    payload_source = f'''  have imported_payload : ∀ member,
      generatedRoot.{payload_name} online member =
        fun _ _ ↦ reducePoly modulus_0 {n} (online1Labels external member) := by
    intro member
    change online.{payload_wire.term} member = _
    rw [hinputs]
    exact import1_payload_{import_payload.loop.child} (import1_claim_runs hrun) member
'''
    field_names = re.findall(r'^  (\w+) :', body, re.M)
    rewrites = ', '.join(f'wire_{name}' for name in referenced)
    fields = '\n'.join(f'''  · simpa only [{rewrites}] using roots.{name}'''
        if name not in ('labels', 'stateHelpers', 'smudgeHelpers') else
        f'''  · intro member
    simpa only [{rewrites}] using roots.{name} member'''
        for name in field_names)
    field_order = re.findall(r'^  (\w+) :', match[2], re.M)
    constructors = ', '.join('imported_payload' if name == 'payload' else '?_'
                             for name in field_order)
    base = meta.one(metadata['backend_layouts'], 'backend layout')['base']
    return 'import Dio2StepTransition\nimport Dio2Online1Inputs\n\n' + HEADER + f'''
open W_Stage_online_1

/-- Refreshed stage-zero exports, before import-one copies them to online one.
These are row equations, not an assumed State1 or decoding conclusion.
The label payload is deliberately absent: import-one constructs it exactly. -/
structure Online0RefreshedRoots (model : HashModel)
    (external : GeneratedClaim.ExternalInputs) (execution : GeneratedClaim.Execution)
    (sm sp value : ErrorPoly {n}) (gadget : ExactMatrix modulus_0 {n} 1 {columns}) : Prop where
{body}

/-- Transport every refreshed root and the hint through the actual import-one run. -/
theorem online0_import1_roots {{model : HashModel}}
    {{external : GeneratedClaim.ExternalInputs}} {{execution : GeneratedClaim.Execution}}
    (hrun : W_GeneratedClaim.Runs model external execution)
    {{sm sp value : ErrorPoly {n}}} {{gadget : ExactMatrix modulus_0 {n} 1 {columns}}}
    (roots : Online0RefreshedRoots model external execution sm sp value gadget)
    (online : generatedRoot.Ctx Backend.backend model W_GeneratedClaim.stage_{stages['online_1'][0]}_params)
    (hinputs : online.inputs = online1ClaimInputs external execution)
    (facts : generatedRoot.Facts online execution.«stage_{stages['online_1'][0]}») :
    Online1Roots online ({anchor}) sm sp value (online1Labels external) gadget := by
{''.join(proof for name, proof in equations)}
{payload_source}
  refine ⟨{constructors}⟩
{fields}

/-- The certified refreshed exports construct the full shared step-one invariant. -/
theorem state1_of_refreshed_roots {{model : HashModel}}
    {{external : GeneratedClaim.ExternalInputs}} {{execution : GeneratedClaim.Execution}}
    (hrun : W_GeneratedClaim.Runs model external execution)
    {{sm sp value : ErrorPoly {n}}} {{gadget : ExactMatrix modulus_0 {n} 1 {columns}}}
    (hsm : polyNorm sm ≤ 1) (hsp : polyNorm sp ≤ 1)
    (hG : gadgetMatrixRuns Backend.backend {base} {columns} gadget)
    (hpay : execution.«stage_{stages['payload'][0]}» =
      fun _ _ ↦ reducePoly modulus_0 {n} sp)
    (roots : Online0RefreshedRoots model external execution sm sp value gadget) :
    State1 model external execution value :=
  ⟨sm, sp, gadget, hsm, hsp, hG, hpay, online0_import1_roots hrun roots⟩

end Dio2Proof
'''


def residue_source(package, metadata):
    view = metadata['views']['worst']
    dimension, columns = view['ring_dimension'], view['columns']
    refresh = view['refresh']
    parts, digits = refresh['parts'], view['smudge_digits']
    cells = view['prfs']['smudge']['packed_members']
    stride = len(refresh['primes']) * columns
    meta.require(digits > 0 and cells == parts * stride * digits,
                 'smudge residue cell geometry mismatch')
    per_digit = parts * stride
    online = meta.Module(package / 'worst', 'W_Stage_online_0', {})
    scope = online.scopes[refresh['scope']]
    part_loop = meta.one((atom for atom in online.root.loops
                         if atom.loop.child == scope.name), 'refresh part loop')
    supplied = dict(zip((wire.name for wire in scope.wires.values()
                         if wire.src == 'input'), part_loop.loop.args))
    first = refresh['primes'][0]
    half_wire = first['wires']['half']
    half_root = meta.one(meta.xmodel.WIRE.findall(supplied[half_wire]), 'half input')
    half_term = online.root.wires[half_root].term
    half_match = re.search(r'allCoefficients\s+\((\d+)\)', half_term)
    meta.require(half_match is not None, 'smudge offset is not coefficientwise')
    half = int(half_match[1])
    original = (package / 'proof/Dio2Online0PartFresh.lean').read_text()
    target_match = re.search(r'noncomputable def smudgePartTarget0\b(.*?)\n/--',
                             original, re.S)
    meta.require(target_match is not None, 'missing symbolic smudge summand')
    weights_type = re.search(r'weights : Fin \d+ → ExactMatrix.*?\)', target_match[1])
    meta.require(weights_type is not None, 'missing smudge weight type')
    smudge_loop = meta.one((atom for atom in scope.loops
                           if atom.loop.kind == 'seq' and
                           first['wires']['smudge'] in atom.loop.final),
                          'prime-zero smudge digit loop')
    weights_wire = meta.one(meta.xmodel.WIRE.findall(smudge_loop.loop.args[4]),
                            'digit weights input')
    weights_root = meta.one(meta.xmodel.WIRE.findall(supplied[weights_wire]),
                            'digit weights root')
    weights_loop = meta.one((atom for atom in online.root.loops
                            if any(weights_root in out for out in atom.loop.outs)),
                           'digit weights loop')
    weight_scope = online.scopes[weights_loop.loop.child]
    weight_input = meta.one(weights_loop.loop.args, 'weight half scalar')
    weight_argument = online.root.wires[weight_input].term
    weight_output = meta.one(meta.output_wires(weight_scope), 'weight result')
    weight_expression = weight_scope.wires[weight_output].term
    meta.require('matrixMulScalarLeft' in weight_expression,
                 'unsupported digit weight multiplication')
    scalar_wire = meta.xmodel.WIRE.findall(weight_expression)[0]
    scalar_expression = weight_scope.wires[scalar_wire].term
    radix_match = re.search(r'liftInteger\s+\(\((\d+)\)\s*\^', scalar_expression)
    meta.require(radix_match is not None, 'missing digit-weight radix')
    radix = int(radix_match[1])
    meta.require(radix % 2 == 0 and 2 * half % view['Q0'] == 1,
                 'invalid centered-smudge radix or half')
    meta.require('matrixPolynomial' in weight_argument and str(half) in weight_argument,
                 'smudge half scalar and offset disagree')
    weights_fact = initial.atom_fact(weights_loop, 'facts')
    source = 'import Dio2StepTransition\nimport Dio2Online0PartFresh\nimport Dio2Noise\n' \
        'import Dio2SmudgeHalf\n\n' + HEADER
    source += f'''open W_Stage_online_0
open scoped BigOperators

/-- Every actual step-zero smudge digit uses its own exported radix power. -/
theorem online0_smudge_weights {{backend : BackendContext}} {{hashModel : HashModel}}
    {{params : Params}} (ctx : generatedRoot.Ctx backend hashModel params)
    {{outputs : _}} (facts : generatedRoot.Facts ctx outputs)
    (digit : Fin {digits}) :
    generatedRoot.{weights_root} ctx digit = fun _ _ ↦
      ({half} : ExactPoly modulus_0 {dimension}) *
        ({radix} : ExactPoly modulus_0 {dimension}) ^ digit.val := by
  have equation := ({weights_fact} digit).2.2
  change generatedRoot.{weights_root} ctx digit = matrixMulScalarLeft
    (liftInteger (({radix} : Int) ^ digit.val)) {weight_argument} at equation
  rw [equation]
  funext row column
  simp only [matrixMulScalarLeft, liftInteger, matrixPolynomial_single,
    Int.cast_pow]
  ring

'''
    for prime in refresh['primes']:
        index = prime['index']
        half_input = prime['wires']['half']
        meta.require(half_input == half_wire, 'primes use different half offsets')
        name = f'smudgePartTarget{index}'
        match = re.search(rf'noncomputable def {name}\b(.*?)\n/--', original, re.S)
        meta.require(match is not None, f'missing prime-{index} smudge summand')
        weight_input_match = re.search(rf'theorem online0_part_smudge{index}\b(.*?) := by',
                                       original, re.S)
        meta.require(weight_input_match is not None, 'missing smudge loop contract')
        weight_names = re.findall(rf'{name} hi t \({scope.name}\.(w_\d+_\d+) ctx\)',
                                  weight_input_match[1])
        meta.require(weight_names and set(weight_names) == {weights_wire},
                     'primes use different digit weights')
        cell_expression = f'{index * columns} + {stride} * part.val + ' \
            f'{per_digit} * digit.val + column.val'
        weights_term = scope.wires[weights_wire].term
        offset_term = scope.wires[half_input].term
        source += f'''/-- Prime {index}: the actual digit weights and coefficientwise offset
give the full centered residue. Readout oddness/support stay explicit; no digit,
part, column or coefficient family is expanded. -/
theorem online0_part_smudge_residue{index}
    {{backend : BackendContext}} {{hashModel : HashModel}} {{params : Params}}
    (ctx : generatedRoot.Ctx backend hashModel params) {{outputs : _}}
    (facts : generatedRoot.Facts ctx outputs) (part : Fin {parts})
    (localCtx : {scope.name}.Ctx backend hashModel params part.val)
    (hinputs : localCtx.inputs = StepTransition.partInputs ctx part)
    (readout : Fin {cells} → ErrorPoly {dimension})
    (hodd : ∀ cell coefficient, (readout cell).coeff coefficient % 2 = 1)
    (hbound : ∀ cell coefficient,
      |(readout cell).coeff coefficient| ≤ ({radix} : Int) - 1) :
    ∃ error : ErrorMatrix {dimension} 1 {columns},
      CoeffBound error ({radix} ^ {digits} / 2) ∧
      (∑ digit ∈ Finset.range {digits}, {name} part.isLt readout
        ({scope.name}.{weights_wire} localCtx) digit) -
        {scope.name}.{half_input} localCtx =
          reduceMatrix modulus_0 {dimension} 1 {columns} error := by
  have weights_eq : {scope.name}.{weights_wire} localCtx =
      generatedRoot.{weights_root} ctx := by
    change localCtx.{weights_term} = _
    rw [hinputs]
    rfl
  have half_eq : {scope.name}.{half_input} localCtx =
      (allCoefficients {half} : ExactMatrix modulus_0 {dimension} 1 {columns}) := by
    change localCtx.{offset_term} = _
    rw [hinputs]
    rfl
  let packed (digit : Fin {digits}) (column : Fin {columns}) : ErrorPoly {dimension} :=
    readout ⟨{cell_expression}, by omega⟩
  let coefficients (digit : Fin {digits}) (column : Fin {columns})
      (coefficient : Fin {dimension}) : Int := (packed digit column).coeff coefficient
  have packed_eq (digit : Fin {digits}) (column : Fin {columns}) :
      reducePoly modulus_0 {dimension} (packed digit column) =
        reducePoly modulus_0 {dimension} (intPoly (coefficients digit column)) := by
    congr 1
    apply negacyclic_ext (by omega)
    intro coefficient
    rw [intPoly_coeff (by omega)]
  apply smudge_hTH (d := {digits - 1}) (by omega) (by norm_num)
    (half := {half}) (by
      apply (ZMod.intCast_eq_intCast_iff (2 * {half}) 1 {view['Q0']}).2
      norm_num [Int.ModEq]) coefficients packed packed_eq
    (fun digit column coefficient ↦ hodd _ coefficient)
    (fun digit column coefficient ↦ hbound _ coefficient) ?_ half_eq
  rw [← Fin.sum_univ_eq_sum_range]
  funext row column
  simp only [Matrix.sum_apply]
  apply Finset.sum_congr rfl
  intro digit _
  rw [{name}, dif_pos digit.isLt]
  change reducePoly modulus_0 {dimension} (packed digit column) *
    ({scope.name}.{weights_wire} localCtx digit) 0 0 = _
  rw [weights_eq, online0_smudge_weights ctx facts digit]
  norm_cast

'''
    source += 'open Dio2NoiseCertificate\n\n'
    for prime in refresh['primes']:
        index = prime['index']
        for operation, budget in [('fresh', 'b1_fresh'), ('smudge', 'b1_smudge')]:
            kernel = f'online0_part_{operation}{index}'
            signature = re.search(rf'theorem {kernel}\b(.*?) := by', original, re.S)
            meta.require(signature is not None, f'missing {kernel} contract')
            signature = signature[1].replace(' {B : Nat}', '')
            signature = re.sub(r'\bB\b', 'b1_packed', signature)
            bound = re.search(r'CoeffBound (e[fs]) \((.*?)\) ∧', signature, re.S)
            meta.require(bound is not None, f'missing {kernel} error envelope')
            signature = signature[:bound.start()] + \
                f'CoeffBound {bound[1]} {budget} ∧' + signature[bound.end():]
            call = 'ctx F hi hq L hL hLx hG hz he'
            if operation == 'smudge':
                call += ' hk0 hk1'
            source += f'''/-- Prime {index}: the symbolic {operation} action fits the exact certificate
envelope. The numerical comparison is proved, not supplied as a premise. -/
theorem {kernel}_budgeted{signature} := by
  obtain ⟨error, herror, hrow⟩ := {kernel} {call}
  refine ⟨error, fun row column coefficient ↦ (herror row column coefficient).trans ?_, hrow⟩
  norm_num [{budget}, b1_packed]

'''
    return source + 'end Dio2Proof\n'


def checked_metadata(package, metadata_path):
    if metadata_path is None:
        return meta.extract(package)
    metadata = json.loads(metadata_path.read_text())
    meta.require(metadata['package'] == package.name, 'metadata package mismatch')
    meta.require(metadata['sources'], 'metadata has no source fingerprints')
    for relative, expected in metadata['sources'].items():
        path = Path(relative)
        meta.require(not path.is_absolute() and '..' not in path.parts,
                     f'unsafe metadata source path: {relative}')
        actual = hashlib.sha256((package / path).read_bytes()).hexdigest()
        meta.require(actual == expected, f'metadata source changed: {relative}')
    meta.check(metadata)
    return metadata


def main():
    generators = {
        'Dio2Step0Certificate': certificate_source,
        'Dio2Step0Primes': prime_source,
        'Dio2Step0Transport': transport_source,
        'Dio2Step0Labels': label_source,
        'Dio2Step0Leaves': leaf_source,
        'Dio2Step0Forest': forest_source,
        'Dio2Step0Residue': residue_source,
    }
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('package', type=Path)
    parser.add_argument('--metadata', type=Path)
    parser.add_argument('--output-dir', type=Path)
    parser.add_argument('--modules', nargs='+', choices=list(generators),
                        help='Generate a bounded module group; defaults to all modules.')
    args = parser.parse_args()
    package = args.package.resolve()
    metadata = checked_metadata(package, args.metadata)
    selected = list(dict.fromkeys(args.modules or generators))
    sources = {name: generators[name](package, metadata) for name in selected}
    output = args.output_dir or package / 'proof'
    output.mkdir(parents=True, exist_ok=True)
    for name, source in sources.items():
        (output / (name + '.lean')).write_text(source)
    print(json.dumps({'package': package.name, 'modules': list(sources)}))


if __name__ == '__main__':
    main()
