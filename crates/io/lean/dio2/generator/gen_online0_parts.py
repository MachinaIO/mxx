FRESH_EXTRA = r'''
/-- Reading one block of packed cell keys recovers that cell's key. -/
theorem blk_cellsKey {q C m : Nat}
    (K : Fin C → Fin 2 → ExactMatrix q n 1 m) (component : Fin 2) (cell : Fin C) :
    blk (cellsKey K component) cell = K cell component := by
  funext row column
  have hr : row = 0 := Subsingleton.elim _ _
  subst hr
  have hm : 0 < m := Nat.pos_of_ne_zero (by rintro rfl; exact column.elim0)
  have hd : (cell.val * m + column.val) / m = cell.val := by
    rw [Nat.add_comm, Nat.add_mul_div_right _ _ hm, Nat.div_eq_of_lt column.isLt, zero_add]
  have hmd : (cell.val * m + column.val) % m = column.val := by
    rw [Nat.add_comm, Nat.add_mul_mod_self_right, Nat.mod_eq_of_lt column.isLt]
  simp only [blk, cellsKey, divFin, modFin]
  congr 2

/-- A fused block-diagonal node has exactly the generic diagonal layout.
This proof is uniform in the number and size of blocks. -/
theorem blockDiagonal_isDiag {q rows columns count : Nat}
    (hr : 0 < rows) (hc : 0 < columns)
    {input : ExactMatrix q n rows columns}
    {output : ExactMatrix q n (rows * count) (columns * count)}
    (h : blockDiagonalRuns count input output) : IsDiag input output := by
  intro row column innerRow innerColumn hrow hcolumn
  let blockRow : Fin count := ⟨row.val / rows, by
    apply (Nat.div_lt_iff_lt_mul hr).mpr
    simpa [Nat.mul_comm] using row.isLt⟩
  let blockColumn : Fin count := ⟨column.val / columns, by
    apply (Nat.div_lt_iff_lt_mul hc).mpr
    simpa [Nat.mul_comm] using column.isLt⟩
  have rowIndex : blockRow.val * rows + innerRow.val = row.val := by
    rw [hrow]
    simpa only [blockRow, Nat.mul_comm] using Nat.div_add_mod row.val rows
  have columnIndex : blockColumn.val * columns + innerColumn.val = column.val := by
    rw [hcolumn]
    simpa only [blockColumn, Nat.mul_comm] using Nat.div_add_mod column.val columns
  have entry := h.2 blockRow blockColumn innerRow innerColumn
  simpa only [Fin.ext_iff, rowIndex, columnIndex, blockRow, blockColumn] using entry

/-- The slice of a packed key family is the corresponding packed subfamily. -/
theorem slice_cellsKey {q C count m : Nat}
    {keys : Fin C → Fin 2 → ExactMatrix q n 1 m} {component : Fin 2}
    {start stop : Int} {output : ExactMatrix q n 1 (count * m)}
    (h : sliceMatrix (cellsKey keys component) 0 1 start stop output)
    (offset : Nat) (hs : start = (m : Int) * (offset : Int)) (ho : offset + count ≤ C) :
    output = cellsKey (fun cell : Fin count ↦ keys ⟨offset + cell.val, by omega⟩) component := by
  apply row_eq_of_blk
  intro cell
  rw [slice_blocks h offset hs cell (by omega), blk_cellsKey]
  exact (blk_cellsKey (fun cell : Fin count ↦ keys ⟨offset + cell.val, by omega⟩)
    component cell).symm

/-- Add an arbitrary number of weighted smudge digits, with the actual key states.
The plaintext summands already contain their digit weights. No weight is discarded,
and the worst-case error is the sum of all digit errors, not one digit's bound. -/
theorem smudge_loop_gen {q m digits B : Nat} {State : Type}
    (row : State → ExactMatrix q n 1 m)
    (keys : State → Fin 2 → ExactMatrix q n 1 m)
    (s : ExactPoly q n) (target : Nat → ExactMatrix q n 1 m)
    {body : Nat → State → State → Prop} {initial final : State}
    (hrow : row initial = 0) (hkeys : keys initial = 0)
    (hstep : ∀ digit current next, body digit current next →
      ∃ error : ErrorMatrix n 1 m, CoeffBound error B ∧
        row next = row current + maskPart s (keys next - keys current) - target digit +
          reduceMatrix q n 1 m error)
    (runs : MxxIR.IterRuns body digits initial final) :
    ∃ error : ErrorMatrix n 1 m, CoeffBound error (digits * B) ∧
      row final = maskPart s (keys final) - ∑ digit ∈ Finset.range digits, target digit +
        reduceMatrix q n 1 m error := by
  apply MxxIR.IterRuns.invariant
    (Invariant := fun count state ↦ ∃ error : ErrorMatrix n 1 m,
      CoeffBound error (count * B) ∧ row state = maskPart s (keys state) -
        ∑ digit ∈ Finset.range count, target digit + reduceMatrix q n 1 m error) ?_ ?_ runs
  · refine ⟨0, by simpa using (coeffBound_zero (n := n) (rows := 1) (columns := m)), ?_⟩
    simp only [hrow, hkeys, Finset.range_zero, Finset.sum_empty, maskPart,
      Pi.zero_apply, smul_zero, add_zero, sub_zero]
    funext rowIndex column
    simp [reduceMatrix]
  · intro digit current next ih step
    obtain ⟨previousError, previousBound, previousRow⟩ := ih
    obtain ⟨newError, newBound, nextRow⟩ := hstep digit current next step
    refine ⟨previousError + newError, ?_, ?_⟩
    · simpa [Nat.add_mul] using coeffBound_add previousBound newBound
    · rw [nextRow, previousRow, reduceMatrix_add, Finset.sum_range_succ]
      simp only [maskPart, Pi.sub_apply, smul_sub]
      abel
'''


def loop_field(facts_source, scope, atom, variable="F"):
    block = re.search(rf"^structure {re.escape(scope.name)}\.Facts_{atom.frag}\b.*?\n"
                      r"(.*?)(?=^structure |^theorem |\Z)", facts_source, re.M | re.S)
    meta.require(block is not None, f"Missing Facts fragment for {scope.name}")
    fields = re.findall(r"^  (\w+) : (.*)$", block[1], re.M)
    field = meta.one((name for name, ty in fields if
                      "MxxIR.IterRuns" in ty and atom.loop.child + " backend" in ty),
                     f"Loop fact {scope.name}/{atom.loop.child}")
    return f"{variable}.c{atom.frag}.{field}"


