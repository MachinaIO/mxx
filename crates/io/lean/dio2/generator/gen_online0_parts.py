def row_module(view, module):
    refresh = view["refresh"]
    scope = module.scopes[refresh["scope"]]
    primes = refresh["primes"]
    count = len(primes)
    n, columns = view["ring_dimension"], view["columns"]
    vector = lambda values: "![" + ", ".join(values) + "]"
    prime_names = [next(name for name, value in module.moduli.items() if value == p["prime"])
                   for p in primes]
    def finite_proof(proofs):
        result = '(fun impossible ↦ Fin.elim0 impossible)'
        for proof in reversed(proofs):
            result = f'(Fin.cases {proof}\n    {result})'
        return result
    pair_rows = []
    row_declarations = []
    for left, left_prime in enumerate(primes):
        pair_checks = []
        basis = left_prime['crt_basis']
        for right, right_prime in enumerate(primes):
            modulus = right_prime['prime']
            if left == right:
                scalar_check = (f'decide (1 < ({modulus} : Nat)) && '
                                f'decide ((({basis} : Int) - 1) % ({modulus} : Int) = 0)')
            else:
                scalar_check = (f'decide (({basis} : Int) % ({modulus} : Int) = 0) && '
                                f'(Nat.gcd {left_prime["prime"]} {modulus} == 1)')
            pair_checks.append(f'(by\n      change ({scalar_check}) = true\n      norm_num)')
        row_name = f'crt0_pair_row_{left}'
        row_declarations.append(f'''private theorem {row_name} :
    ∀ right, crtPairOk primes0 crt0 ⟨{left}, by decide⟩ right = true := by
  exact {finite_proof(pair_checks)}
''')
        pair_rows.append(row_name)
    pair_proof = finite_proof(pair_rows)
    row_proofs = '\n'.join(row_declarations)
    result = header(["Dio2Online0PartPrimes", "Dio2Generic"],
                    "# CRT recombination with a kernel-checked prime certificate")
    result += f'''open W_Stage_online_0

attribute [local irreducible] Mxx.Primitives.negacyclicModulus

/-- Refresh primes in exported CRT-term order. -/
def primes0 : Fin {count} → Nat := {vector(prime_names)}

/-- Exported CRT basis in matching order. -/
def crt0 : Fin {count} → Int := {vector([str(p['crt_basis']) for p in primes])}

{row_proofs}
/-- Each prime pair is checked independently; no monolithic nested-list reduction is needed. -/
private theorem crt0_pairs : ∀ left right, crtPairOk primes0 crt0 left right = true := by
  exact {pair_proof}

theorem crt0_certificate : crtCertificate primes0 crt0 = true := by
  unfold crtCertificate
  simp only [List.all_eq_true]
  intro left _ right _
  exact crt0_pairs left right

theorem primes0_gt : ∀ index, 1 < primes0 index :=
  (crt_hyps_of_certificate crt0_certificate).1

theorem crt0_basis : ∀ left right,
    crt0 left ≡ (if left = right then 1 else 0) [ZMOD (primes0 right : Int)] :=
  (crt_hyps_of_certificate crt0_certificate).2.1

theorem primes0_coprime : ∀ left right, left ≠ right →
    Nat.Coprime (primes0 left) (primes0 right) :=
  (crt_hyps_of_certificate crt0_certificate).2.2

theorem primes0_prod_list : modulus_0 = (List.ofFn primes0).prod := by decide +kernel

theorem primes0_prod : modulus_0 = ∏ index, primes0 index := by
  rw [prod_eq_listProd]
  exact primes0_prod_list

/-- The exported CRT terms as a finite family; only primes are enumerated. -/
noncomputable def partTerms0 {{backend : BackendContext}} {{hashModel : HashModel}}
    {{params : W_Stage_online_0.Params}} {{part : Nat}}
    (ctx : {scope.name}.Ctx backend hashModel params part) :
    Fin {count} → ExactMatrix modulus_0 {n} 1 {columns} :=
  {vector([wire(scope, p['wires']['term']) for p in primes])}

/-- Any common intended row is recovered from its quantified per-prime terms. -/
theorem online0_part_row {{backend : BackendContext}} {{hashModel : HashModel}}
    {{params : W_Stage_online_0.Params}} {{part : Nat}}
    (ctx : {scope.name}.Ctx backend hashModel params part)
    {{value : ExactMatrix modulus_0 {n} 1 {columns}}}
    (terms : ∀ index, TermOf (primes0 index) (crt0 index) (partTerms0 ctx index) value) :
    {wire(scope, refresh['result_wire'])} = value := by
  exact part_row_gen (n := {n}) (Q := modulus_0) (m := {columns}) (k := {count - 1})
    (by decide) (by decide) primes0 primes0_gt crt0 crt0_basis
    primes0_coprime primes0_prod (v := value) (t := partTerms0 ctx) terms

end Dio2Proof
'''
    return result


