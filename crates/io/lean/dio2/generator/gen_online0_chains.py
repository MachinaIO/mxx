def declaration(source, name):
    start = re.search(r"^theorem " + re.escape(name) + r"\b", source, re.M)
    meta.require(start is not None, f"Missing generic template: {name}")
    rest = source[start.start():]
    stop = re.search(r"\n(?:set_option|/--|/-!|end |theorem |def |abbrev |noncomputable )", rest)
    result = rest[:stop.start()] if stop else rest
    return re.sub(r"^\s*--[^\n]*\n", "", result, flags=re.M).rstrip() + "\n"


