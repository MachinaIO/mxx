def tuple_term(items):
    term = '()'
    for item in reversed(items):
        term = f'({item}, {term})'
    return term


def projection(index):
    return '.2' * index + '.1'


class Geometry:
    """Package geometry and the parsed online/key modules."""

    def __init__(self, package, metadata):
        self.package = package
        self.view = metadata['views']['worst']
        view = self.view
        self.n = view['ring_dimension']
        self.columns = view['columns']
        self.anchor = view['anchor_columns']
        refresh = view['refresh']
        self.parts = refresh['parts']
        self.targets = refresh['targets']
        self.primes = refresh['primes']
        self.part_scope = refresh['scope']
        self.part_args = refresh['arguments']
        self.keys = view['keys']
        self.digits = view['smudge_digits']
        meta.require(len(self.keys) == len(self.primes), 'key/prime count mismatch')
        worst = package / 'worst'
        self.online = meta.Module(worst, ONLINE, {})
        self.keymod = meta.Module(worst, KEYS, {})
        self.fresh_cells = self.parts * self.columns
        self.smudge_cells = self.parts * self.columns * self.digits * len(self.primes)
        part = self.online.scopes[self.part_scope]
        self.part_inputs = self.scope_inputs(ONLINE, self.part_scope)
        meta.require(len(self.part_inputs) == len(self.part_args), 'part input arity')
        self.part_frag = {a.args[-1]: a.frag for a in part.atoms
                          if a.args and meta.xmodel.WIRE.fullmatch(a.args[-1])}
        self.key_inputs = {}
        for key in self.keys:
            self.key_inputs[key['scope']] = self.scope_inputs(KEYS, key['scope'])
        self.key_root_frag = {}
        for atom in self.keymod.root.atoms:
            if atom.args and meta.xmodel.WIRE.fullmatch(atom.args[-1]):
                self.key_root_frag.setdefault(atom.args[-1], atom.frag)
        for atom in self.keymod.root.loops:
            if atom.loop.child in self.key_inputs:
                for out in atom.loop.outs:
                    wire = out.split()[0].strip('()')
                    self.key_root_frag[wire] = atom.frag
        self.online_root_frag = {}
        for atom in self.online.root.loops:
            if atom.loop.child == self.part_scope:
                self.online_root_frag['part'] = atom.frag

    def scope_inputs(self, module, scope):
        source = '\n'.join(text for _, text in meta.module_sources(self.package / 'worst', module))
        body = source[source.index(f'abbrev {scope}.body'):]
        body = body[:body.index('\n\n')]
        found = re.findall(r'^  let (w_\d+_\d+) : .*? := inputs((?:\.[12])*)$', body, re.M)
        if not found:
            # Record scopes read their inputs through context projections.
            facts = '\n'.join(text for _, text in meta.module_sources(self.package / 'worst', module + '_Facts'))
            facts += '\n' + source
            found = re.findall(r'^(?:noncomputable )?def ' + re.escape(scope) +
                               r'\.(w_\d+_\d+) +\(ctx : [^\n]*:=\n  ctx\.inputs((?:\.[12])*)$', facts, re.M)
            found = list(dict.fromkeys(found))
        # Leaves of a (right-nested or balanced) input tuple, in depth-first order.
        ordered = sorted(found, key=lambda item: [int(c) for c in item[1][1::2]])
        paths = [p for _, p in ordered]
        for a, b in zip(paths, paths[1:]):
            meta.require(not b.startswith(a + '.'), f'{scope}: input {a} is not a leaf')
        if all(re.fullmatch(r'(?:\.2)*\.1', p) for p in paths):
            for index, p in enumerate(paths):
                meta.require(p.count('.2') == index, f'{scope}: non-sequential input {p}')
        return [w for w, _ in ordered]


def checked_metadata(package, metadata_path):
    if metadata_path is None:
        return meta.extract(package)
    metadata = json.loads(metadata_path.read_text())
    meta.require(metadata['package'] == package.name, 'metadata package mismatch')
    meta.require(metadata['sources'], 'metadata has no source fingerprints')
    for relative, expected in metadata['sources'].items():
        path = Path(relative)
        meta.require(not path.is_absolute() and '..' not in path.parts,
                     f'unsafe metadata source path: {relative}')
        actual = hashlib.sha256((package / path).read_bytes()).hexdigest()
        meta.require(actual == expected, f'metadata source changed: {relative}')
    meta.check(metadata)
    return metadata


