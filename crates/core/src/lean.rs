//! Lean export of RV64IM code in the form of mathcal-A's program logic.
//!
//! [`code_module`] writes a module that defines a binary (`bin : MathcalA.Bytes`), its decoded
//! instructions (`instrs`), and `prog (mem : Nat) : MathcalA.Prog`, whose `decodes` field the
//! kernel checks by `decide` against mathcal-A's loader. It serves both a whole proof image and the
//! code of one leaf, whose specification is then proved about `prog` from instruction `0`.

use crate::rv64::isa::{AluOp, BranchOp, ImmOp, Instr, ShiftOp, Width};
use std::fmt::Write;

/// An instruction in the syntax of `RiscvZkvm.Rv64.Instr`.
pub fn instr_source(instr: Instr) -> String {
    let r = |reg: crate::rv64::isa::Reg| format!(".x{}", reg.0);
    let bits =
        |value: i64, width: u32| format!("0x{:x}#{width}", (value as u64) & ((1u64 << width) - 1));
    match instr {
        Instr::Alu { op, rd, rs1, rs2 } => {
            let name = match op {
                AluOp::Add => "ADD",
                AluOp::Sub => "SUB",
                AluOp::Sll => "SLL",
                AluOp::Srl => "SRL",
                AluOp::Sra => "SRA",
                AluOp::And => "AND",
                AluOp::Or => "OR",
                AluOp::Xor => "XOR",
                AluOp::Slt => "SLT",
                AluOp::Sltu => "SLTU",
                AluOp::Mul => "MUL",
                AluOp::Mulh => "MULH",
                AluOp::Mulhsu => "MULHSU",
                AluOp::Mulhu => "MULHU",
                AluOp::Div => "DIV",
                AluOp::Divu => "DIVU",
                AluOp::Rem => "REM",
                AluOp::Remu => "REMU",
            };
            format!(".{name} {} {} {}", r(rd), r(rs1), r(rs2))
        }
        Instr::Imm { op, rd, rs1, imm } => {
            let name = match op {
                ImmOp::Addi => "ADDI",
                ImmOp::Slti => "SLTI",
                ImmOp::Sltiu => "SLTIU",
                ImmOp::Xori => "XORI",
                ImmOp::Ori => "ORI",
                ImmOp::Andi => "ANDI",
            };
            format!(".{name} {} {} {}", r(rd), r(rs1), bits(imm.into(), 12))
        }
        Instr::Shift { op, rd, rs1, shamt } => {
            let name = match op {
                ShiftOp::Slli => "SLLI",
                ShiftOp::Srli => "SRLI",
                ShiftOp::Srai => "SRAI",
            };
            format!(".{name} {} {} {}", r(rd), r(rs1), bits(shamt.into(), 6))
        }
        Instr::Addiw { rd, rs1, imm } => {
            format!(".ADDIW {} {} {}", r(rd), r(rs1), bits(imm.into(), 12))
        }
        Instr::Lui { rd, imm } => format!(".LUI {} {}", r(rd), bits(imm.into(), 20)),
        Instr::Auipc { rd, imm } => format!(".AUIPC {} {}", r(rd), bits(imm.into(), 20)),
        Instr::Load { width, unsigned, rd, rs1, imm } => {
            let name = match (width, unsigned) {
                (Width::B, false) => "LB",
                (Width::H, false) => "LH",
                (Width::W, false) => "LW",
                (Width::D, _) => "LD",
                (Width::B, true) => "LBU",
                (Width::H, true) => "LHU",
                (Width::W, true) => "LWU",
            };
            format!(".{name} {} {} {}", r(rd), r(rs1), bits(imm.into(), 12))
        }
        Instr::Store { width, rs1, rs2, imm } => {
            let name = match width {
                Width::B => "SB",
                Width::H => "SH",
                Width::W => "SW",
                Width::D => "SD",
            };
            format!(".{name} {} {} {}", r(rs1), r(rs2), bits(imm.into(), 12))
        }
        Instr::Branch { op, rs1, rs2, offset } => {
            let name = match op {
                BranchOp::Beq => "BEQ",
                BranchOp::Bne => "BNE",
                BranchOp::Blt => "BLT",
                BranchOp::Bge => "BGE",
                BranchOp::Bltu => "BLTU",
                BranchOp::Bgeu => "BGEU",
            };
            format!(".{name} {} {} {}", r(rs1), r(rs2), bits(offset.into(), 13))
        }
        Instr::Jal { rd, offset } => format!(".JAL {} {}", r(rd), bits(offset.into(), 21)),
        Instr::Jalr { rd, rs1, imm } => {
            format!(".JALR {} {} {}", r(rd), r(rs1), bits(imm.into(), 12))
        }
        Instr::Ecall => ".ECALL".into(),
        Instr::Ebreak => ".EBREAK".into(),
        Instr::Fence => ".FENCE".into(),
    }
}

/// A Lean module defining `bin`, `instrs`, and `prog` for `words` in namespace `namespace`, with
/// `bytes` appended to the code (read-only data of an image; empty for leaf code).
pub fn code_module(namespace: &str, doc: &str, words: &[u32], bytes: &[u8]) -> String {
    let mut image: Vec<u8> = words.iter().flat_map(|w| w.to_le_bytes()).collect();
    image.extend_from_slice(bytes);
    let mut out = String::new();
    writeln!(out, "-- Generated by mxx-core. Do not edit.").unwrap();
    writeln!(out, "import MathcalA.Lib.Prog\n").unwrap();
    writeln!(out, "/-! {doc} -/\n").unwrap();
    writeln!(out, "namespace {namespace}\n").unwrap();
    writeln!(out, "open MathcalA RiscvZkvm.Rv64\n").unwrap();
    writeln!(out, "def bin : MathcalA.Bytes := [").unwrap();
    for chunk in image.chunks(16) {
        let line: Vec<String> = chunk.iter().map(|b| format!("0x{b:02x}")).collect();
        writeln!(out, "  {},", line.join(", ")).unwrap();
    }
    if out.ends_with(",\n") {
        out.truncate(out.len() - 2);
        out.push('\n');
    }
    writeln!(out, "]\n").unwrap();
    writeln!(out, "def instrs : List Instr := [").unwrap();
    let decoded: Vec<String> = words
        .iter()
        .map(|w| instr_source(Instr::decode(*w).expect("checked code decodes")))
        .collect();
    writeln!(out, "  {}]\n", decoded.join(",\n  ")).unwrap();
    writeln!(
        out,
        "set_option maxRecDepth 100000 in\n/-- The code loaded in a machine of `mem` bytes; the \
         kernel checks the decoding. -/"
    )
    .unwrap();
    writeln!(out, "def prog (mem : Nat) : Prog := ⟨bin, mem, instrs, by decide⟩\n").unwrap();
    writeln!(
        out,
        "/-- The code at instruction `c` of a program `P`, one fact per instruction, so that a \
         specification proved from it holds wherever an image places the code. -/"
    )
    .unwrap();
    writeln!(out, "structure At (P : Prog) (c : Nat) : Prop where").unwrap();
    for (k, word) in words.iter().enumerate() {
        let instr = instr_source(Instr::decode(*word).expect("checked code decodes"));
        let index = if k == 0 { "c".to_owned() } else { format!("c + {k}") };
        writeln!(out, "  i{k} : P.instrs[{index}]? = some ({instr})").unwrap();
    }
    writeln!(out).unwrap();
    writeln!(out, "set_option maxRecDepth 100000 in\ntheorem prog_at (mem : Nat) : At (prog mem) 0 := by constructor <;> rfl\n")
        .unwrap();
    writeln!(out, "end {namespace}").unwrap();
    out
}

/// The instructions of the longest prefix of `image` whose words all decode: the glue, the copy
/// routine, and the code of the libraries placed before the first word that does not decode (such
/// as read-only data).
pub fn code_prefix(image: &[u8]) -> Vec<Instr> {
    image
        .chunks_exact(4)
        .map(|w| u32::from_le_bytes(w.try_into().expect("four bytes")))
        .map_while(|w| if w == 0 { None } else { Instr::decode(w) })
        .collect()
}

/// A Lean definition `name : MathcalA.Prog`, documented by `doc`, over the image `image` (a Lean
/// term of type `MathcalA.Bytes`) loaded in `mem` bytes, with the instructions `instrs`, whose
/// decoding the kernel checks by `decide`.
pub fn prog_definition(name: &str, doc: &str, image: &str, mem: u64, instrs: &[Instr]) -> String {
    let decoded: Vec<String> = instrs.iter().map(|i| instr_source(*i)).collect();
    format!(
        "set_option maxRecDepth 1000000 in\nset_option maxHeartbeats 0 in\n/-- {doc} -/\ndef {name} : Prog :=\n  ⟨{image}, {mem},\n   [{}],\n   by decide⟩\n",
        decoded.join(",\n    ")
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::rv64::isa::Reg;

    #[test]
    fn test_instr_source_matches_riscv_zkvm_syntax() {
        assert_eq!(instr_source(Instr::Lui { rd: Reg(8), imm: 0x11 }), ".LUI .x8 0x11#20");
        assert_eq!(
            instr_source(Instr::Branch {
                op: BranchOp::Bgeu,
                rs1: Reg(5),
                rs2: Reg(20),
                offset: 16
            }),
            ".BGEU .x5 .x20 0x10#13"
        );
        assert_eq!(instr_source(Instr::Jal { rd: Reg(0), offset: -12 }), ".JAL .x0 0x1ffff4#21");
        assert_eq!(
            instr_source(Instr::Store { width: Width::B, rs1: Reg(8), rs2: Reg(6), imm: 72 }),
            ".SB .x8 .x6 0x48#12"
        );
    }
}
