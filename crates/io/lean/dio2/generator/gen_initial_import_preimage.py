def initial_basic(initial):
    gadget = initial.gadgets[0]
    scope = initial.root
    concat = next(a for a in scope.atoms if a.kind == 'concatColumns')
    noises = [a for a in scope.atoms if a.kind == 'uniformIntervalSample'][:2]
