def claim_stages(package):
    text = (package / 'worst/W_Claim.lean').read_text()
    stages = {}
    for line in text.splitlines():
        match = re.match(r'  W_Stage_(\w+)\.generatedRoot .* execution\.«stage_(\d+)»(?: ∧)?$', line)
        if match:
            stages[match[1]] = (int(match[2]), line)
    meta.require(stages, 'no claim stages found')
    return stages


def claim_hypothesis(stage, stages):
    index = stages[stage][0] + 1
    return 'h' + '.2' * index + ('.1' if index < len(stages) else '')


def preimage_modules(package, view, modules):
    text = ['import W_Stage_anchors_Facts\nimport W_Stage_preimages_0_0_Facts\n',
            'import W_Stage_preimages_1_1_Facts\nimport W_Claim\nimport GenKey\n\n',
            '/-! Generated sampled-anchor and bounded exact-preimage contracts.\n'
            'Members stay quantified; only the exported prime families are specialized. -/\n\n',
            HEADER, PREIMAGE_GENERIC]
    anchors = modules['anchors']
    anchor_atoms = [a for a in anchors.root.atoms if a.kind == 'trapdoorSample']
    anchor_outputs = meta.output_wires(anchors.root)
    anchor_contracts = []
    for atom in anchor_atoms:
        args = [projection(anchor_outputs.index(w)) if w in anchor_outputs else w for w in atom.args]
        anchor_contracts.append('trapdoorSample ' + ' '.join(args))
    text.append('''theorem anchors_trapdoor {backend : BackendContext} {params : W_Stage_anchors.Params}
    {u : Unit} {outputs : _} (h : W_Stage_anchors.generatedRoot backend params u outputs) :
    ''' + ' ∧\n    '.join(anchor_contracts) + ''' := by
  obtain ⟨witness, hbody⟩ := h
  let ctx : W_Stage_anchors.generatedRoot.Ctx backend params := ⟨u, witness⟩
  have F := W_Stage_anchors.generatedRoot.facts ctx hbody
  rw [''' + atom_fact(next(a for a in anchors.root.atoms if a.kind == 'out')) + ''']
  exact ⟨''' + ', '.join(atom_fact(a) for a in anchor_atoms) + '''⟩

''')
    n, anchor_columns = view['ring_dimension'], view['anchor_columns']
    parts = view['refresh']['parts']
    cuts = {}
    for stage in ['preimages_0_0', 'preimages_1_1']:
        module = modules[stage]
