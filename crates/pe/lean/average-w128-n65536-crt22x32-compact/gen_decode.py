        lines.append(f"    show matrixAdd ({prev}) (Stage_decode.generatedRoot.w_{12 + 4 * j}_0 ctx) = _")
        lines.append(f"    rw [e{j}]")
        lines.append(f"    simp only [G, dif_pos (show {j} < 128 by norm_num){', Finset.sum_range_zero' if j == 0 else ''}]")
        lines.append(f"    rfl")
