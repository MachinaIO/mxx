SIGMA_TOTAL = r'''
/-- Compose readout and sampling at each member, then place and total all members.
The readout and sampler obligations are supplied by the LUT bundle theorems;
neither a member nor a coefficient is enumerated. -/
theorem online0_sigma_total (hn : 1 < n) {q m M : Nat}
    {sm sp Δr Δs : ErrorPoly n} {read sample : Fin M → ErrorPoly n}
    {readG sampleG : ExactMatrix q n 1 m}
    {readKeys sampleKeys : Fin M → Fin 2 → Fin 2 → ExactMatrix q n 1 m}
    {readRows sampleRows : Fin M → Fin 2 → ExactMatrix q n 1 m}
    {Br Bs : Nat}
    (hread : ∀ member, Rel sm (readKeys member)
      (fun port ↦ reducePoly q n (Δr * read member * unitPair sp port) • readG)
      (readRows member) Br)
    (hsample : ∀ member, Rel sm (readKeys member)
      (fun port ↦ reducePoly q n (Δr * read member * unitPair sp port) • readG)
      (readRows member) Br → Rel sm (sampleKeys member)
      (fun port ↦ reducePoly q n (Δs * sample member * unitPair sp port) • sampleG)
      (sampleRows member) Bs)
    (placement : Fin M → Nat) (hplacement : ∀ member, placement member < 2 * n) :
    Rel sm (fun key port ↦ ∑ member,
      multiplyMonomial (sampleKeys member key port) (placement member : Int))
      (fun port ↦ reducePoly q n
        (Δs * (∑ member, Xe (n := n) (placement member) * sample member) * unitPair sp port) • sampleG)
      (fun port ↦ ∑ member, multiplyMonomial (sampleRows member port) (placement member : Int))
      (M * Bs) := by
  exact sampler_flat hn sample placement hplacement (fun member ↦ hsample member (hread member))
'''


DIGIT_TOTAL = r'''
/-- A digit loop adds its indexed, already weighted encodings. The error budget
is the sum over all digits, never the support of just one digit. Block-diagonal
assembly and scalar-weight lifting are explicit iteration obligations. -/
theorem online0_smudge_digit_total {q m digits : Nat} {sm : ErrorPoly n}
    {body : Nat → Tup (ExactMatrix q n 1 m) 6 → Tup (ExactMatrix q n 1 m) 6 → Prop}
    {initial final : Tup (ExactMatrix q n 1 m) 6}
    (target : Nat → Fin 2 → ExactMatrix q n 1 m) (budget : Nat → Nat)
    (hzero : EncRel sm initial 0 0)
    (hstep : ∀ digit current next,
      EncRel sm current (fun port ↦ ∑ previous ∈ Finset.range digit, target previous port)
        (∑ previous ∈ Finset.range digit, budget previous) →
      body digit current next →
      EncRel sm next
        (fun port ↦ (∑ previous ∈ Finset.range digit, target previous port) + target digit port)
        ((∑ previous ∈ Finset.range digit, budget previous) + budget digit))
    (hrun : MxxIR.IterRuns body digits initial final) :
    EncRel sm final (fun port ↦ ∑ digit ∈ Finset.range digits, target digit port)
      (∑ digit ∈ Finset.range digits, budget digit) := by
  apply MxxIR.IterRuns.invariant
    (Invariant := fun digit current ↦ EncRel sm current
      (fun port ↦ ∑ previous ∈ Finset.range digit, target previous port)
      (∑ previous ∈ Finset.range digit, budget previous)) ?_ ?_ hrun
  · simpa using hzero
  · intro digit current next hcurrent hbody
    simpa only [Finset.sum_range_succ] using hstep digit current next hcurrent hbody

/-- Componentwise addition of complete encodings adds their error budgets. -/
theorem smudge_encoding_add {q m : Nat} {sm : ErrorPoly n}
    {left right output : Tup (ExactMatrix q n 1 m) 6}
    {leftTarget rightTarget : Fin 2 → ExactMatrix q n 1 m} {leftBudget rightBudget : Nat}
    (hleft : EncRel sm left leftTarget leftBudget)
    (hright : EncRel sm right rightTarget rightBudget)
    (hadd : ∀ component, output.get component = left.get component + right.get component) :
    EncRel sm output (leftTarget + rightTarget) (leftBudget + rightBudget) := by
  have hkey : Enc.A output = Enc.A left + Enc.A right := by
    funext key port
    fin_cases key <;> fin_cases port
    · exact hadd 0
    · exact hadd 1
    · exact hadd 2
    · exact hadd 3
  have hrow : Enc.c output = Enc.c left + Enc.c right := by
    funext port
    fin_cases port
    · exact hadd 4
    · exact hadd 5
  unfold EncRel
  rw [hkey, hrow]
  exact hleft.add hright

/-- Fold the independently weighted digit encodings produced by the actual
body. Scalar retargeting and block-diagonal packing must establish `hweighted`;
no invariant for an already accumulated state is assumed here. -/
theorem online0_smudge_digit_total_of_add {q m digits : Nat} {sm : ErrorPoly n}
    {body : Nat → Tup (ExactMatrix q n 1 m) 6 → Tup (ExactMatrix q n 1 m) 6 → Prop}
    {initial final : Tup (ExactMatrix q n 1 m) 6}
    (target : Nat → Fin 2 → ExactMatrix q n 1 m) (budget : Nat → Nat)
    (hzero : EncRel sm initial 0 0)
    (hweighted : ∀ digit current next, body digit current next →
      ∃ increment : Tup (ExactMatrix q n 1 m) 6,
        EncRel sm increment (target digit) (budget digit) ∧
        ∀ component, next.get component = current.get component + increment.get component)
    (hrun : MxxIR.IterRuns body digits initial final) :
    EncRel sm final (fun port ↦ ∑ digit ∈ Finset.range digits, target digit port)
      (∑ digit ∈ Finset.range digits, budget digit) := by
  apply online0_smudge_digit_total target budget hzero ?_ hrun
  intro digit current next hcurrent hbody
  obtain ⟨increment, hincrement, hadd⟩ := hweighted digit current next hbody
  exact smudge_encoding_add hcurrent hincrement hadd

/-- The actual finite geometric sum, without expanding the digit count. -/
theorem smudge_digit_weight_sum (radix digits : Nat) :
    (radix - 1) * (∑ digit ∈ Finset.range digits, radix ^ digit) + 1 = radix ^ digits
      + (if radix = 0 then (if digits = 0 then 0 else 1) else 0) := by
  by_cases hradix : radix = 0
  · subst radix
    cases digits <;> simp
  · have hpos : 0 < radix := Nat.pos_of_ne_zero hradix
    simp only [hradix, ↓reduceIte, add_zero]
    induction digits with
    | zero => simp
    | succ digits ih =>
      rw [Finset.sum_range_succ, Nat.mul_add, pow_succ]
      have heq : radix - 1 + 1 = radix := by omega
      calc
        _ = ((radix - 1) * (∑ digit ∈ Finset.range digits, radix ^ digit) + 1)
            + (radix - 1) * radix ^ digits := by omega
        _ = radix ^ digits + (radix - 1) * radix ^ digits := by rw [ih]
        _ = radix ^ digits * (radix - 1 + 1) := by ring
        _ = _ := by rw [heq]
'''


GATHER_PLACEMENT = r'''
/-- Extensionality for the fixed-size tuple representation. -/
theorem tuple_ext {α : Type} {size : Nat} {left right : Tup α size}
    (heq : ∀ component, left.get component = right.get component) : left = right := by
  induction size with
  | zero => exact (show Subsingleton Unit from inferInstance).elim _ _
  | succ size ih =>
    apply Prod.ext
    · exact heq 0
    · exact ih (fun component ↦ heq component.succ)

/-- A fused gather/placement selects the same member in every component and
preserves its noise bound under a monomial. The family size is arbitrary. -/
theorem gather_monomial_place_rel (hn : 1 < n) {q m members : Nat}
    {sm : ErrorPoly n} {families : Tup (Fin members → ExactMatrix q n 1 m) 6}
    {gathered output : Tup (ExactMatrix q n 1 m) 6} {index : Int} {exponent : Nat}
    (hexponent : exponent < 2 * n)
    (hgather : GatherUnpack.Spec families index gathered)
    (hplace : ∀ component, output.get component =
      multiplyMonomial (gathered.get component) (exponent : Int))
    {target : Fin members → Fin 2 → ExactMatrix q n 1 m} {budget : Nat}
    (hmember : ∀ member, EncRel sm (Tup.ev families member) (target member) budget) :
    ∃ member : Fin members, EncRel sm output
      (fun port ↦ reducePoly q n (Xe (n := n) exponent) • target member port) budget := by
  obtain ⟨hbound, hnonneg, hgather⟩ := hgather
  let member : Fin members := ⟨index.toNat, hbound⟩
  have hsource : gathered = Tup.ev families member := by
    apply tuple_ext
    intro component
    simpa only [Tup.get_ev] using hgather component
  have hout : output =
      (multiplyMonomial gathered.1 (exponent : Int),
      (multiplyMonomial gathered.2.1 (exponent : Int),
      (multiplyMonomial gathered.2.2.1 (exponent : Int),
      (multiplyMonomial gathered.2.2.2.1 (exponent : Int),
      (multiplyMonomial gathered.2.2.2.2.1 (exponent : Int),
      (multiplyMonomial gathered.2.2.2.2.2.1 (exponent : Int), ())))))) := by
    apply tuple_ext
    intro component
    fin_cases component <;> exact hplace _
  refine ⟨member, monomial_place_rel hn hexponent hout ?_⟩
  simpa only [hsource] using hmember member

/-- A generated row-sum scope adds all cell errors, including zero-selector
cells. One-hotness may subsequently simplify the target, not the budget. -/
theorem online0_bucket_sum {q m members width : Nat} {sm : ErrorPoly n}
    {families : Tup (Fin (members * width) → ExactMatrix q n 1 m) 6}
    {output : Tup (ExactMatrix q n 1 m) 6} (member : Fin members)
    (hrow : RowSum.Spec families width member output)
    {target : Fin (members * width) → Fin 2 → ExactMatrix q n 1 m} {budget : Nat}
    (hcell : ∀ cell, EncRel sm (Tup.ev families cell) (target cell) budget) :
    EncRel sm output (∑ column : Fin width, target (cellAt member column))
      (width * budget) := by
  have hget : ∀ component, output.get component =
      ∑ column : Fin width, (Tup.ev families (cellAt member column)).get component := by
    intro component
    simpa only [Tup.get_ev] using rowSum_get hrow component
  have hsum := Rel.sum (Finset.univ : Finset (Fin width))
    (A := fun column ↦ Enc.A (Tup.ev families (cellAt member column)))
    (t := fun column ↦ target (cellAt member column))
    (c := fun column ↦ Enc.c (Tup.ev families (cellAt member column)))
    (B := fun _ ↦ budget) (fun column _ ↦ hcell (cellAt member column))
  unfold EncRel
  rw [enc_sum_A (fun column ↦ Tup.ev families (cellAt member column)) output hget,
    enc_sum_c (fun column ↦ Tup.ev families (cellAt member column)) output hget]
  exact hsum.mono (le_of_eq (by simp))
'''


RHS_NOISY = r'''
/-- Selector cancellation with its sampled error retained. -/
theorem selector_rhs_noisy {q n columns : Nat} {sp unit : ErrorPoly n}
    {secret unitMatrix : ExactMatrix q n 1 1}
    (hs : secret = fun _ _ ↦ reducePoly q n sp)
    (hu : unitMatrix = fun _ _ ↦ reducePoly q n unit)
    (coefficient exponent : Int) (gadget top : ExactMatrix q n 1 columns)
    {noise : ExactMatrix q n 1 columns} {error : ErrorMatrix n 1 columns}
    (hnoise : noise = reduceMatrix q n 1 columns error) :
    reducePoly q n sp • top +
        matrixAdd (matrixSub (matrixMulScalarRight
          (matrixMulScalarRight (matrixMulScalarLeft unitMatrix gadget) (matrixPolynomial [1]))
          (multiplyMonomial (liftInteger coefficient) exponent))
          (matrixMulScalarLeft secret top)) noise =
      reducePoly q n (message coefficient exponent * unit) • gadget +
        reduceMatrix q n 1 columns error := by
  rw [hs, hu, hnoise, multiplyMonomial_liftInteger]
  simp only [matrixMulScalarRight_eq, matrixMulScalarLeft_eq, matrixPolynomial_reduceG]
  funext row column
  simp only [matrixAdd, matrixSub, Matrix.add_apply, Matrix.sub_apply, Matrix.smul_apply,
    smul_eq_mul, map_mul, Int.cast_one, map_one]
  ring
'''


