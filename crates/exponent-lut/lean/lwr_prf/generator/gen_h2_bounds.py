"""LwrH2Bounds.lean: the bounds of the H2 decomposition.

Usage: gen_h2_bounds.py <parameter dir>

Writes, for every tape: the `l1` norms of the weights entering every block, the remainder of the
decoded coefficient, the energy of the row sites, the mask forms of the key sites and their
energy. Every bound is a rational constant computed here and checked by `norm_num`.

`h2_constants(I)` is shared with `gen_h2_cert.py`.
"""
