                args = list(map(strip_parens, args))
                if head == 'MxxRuntime.matrixMulScalarLeft':
                    left, right = args
                    value = f'({polynomial(left)} * {polynomial(right)})'
                    proof = f'msl_entry P_{left} P_{right}'
                elif head == 'MxxRuntime.multiplyMonomial':
                    source, exponent = args
                    value = f'({polynomial(source)} * message 1 ({integer(exponent)}))'
                    proof = f'(mono_entry P_{source} _).trans (by rw [I_{exponent}])'
                else:
                    raise meta.MetadataError(f'unsupported scalar {entry.term}')
