def selector_theorem(scope):
    binders, call, _ = adapters.header(scope)
    per, atoms = adapters.atom_names(scope)
    gadgets = [(name, atom) for name, atom in atoms if atom.startswith("MxxRuntime.gadgetMatrixRuns ")]
    rebases = [(name, atom) for name, atom in atoms if atom.startswith("MxxRuntime.centeredRebaseRuns ")]
    gaussian = [(name, atom) for name, atom in atoms if atom.startswith("MxxRuntime.gaussianSample ")]
    meta.require(len(gadgets) == len(rebases) == 1 and len(scope.output) in (4, 8),
                 f"Unsupported selector {scope.name}")
    meta.require(len(gaussian) in (0, 2), f"Unsupported selector sampling {scope.name}")
    base, digits, source = gadgets[0][1].split()[-3:]
    gadget = rebases[0][1].split()[-1]
    modulus, n, rows, columns = meta.dims(scope.output[0])
    meta.require(rows == 1, "Selector row width")
    cutoff = 0
    if gaussian:
        _, args = meta.xmodel.app_split(gaussian[0][1])
        cutoff = meta.integer(args[1])
        meta.require(cutoff >= 0, "Negative selector cutoff")
    def arguments(wire, operation):
        head, values = meta.xmodel.app_split(scope.wires[wire].term)
        meta.require(head == "MxxRuntime." + operation,
                     f"Unexpected selector expression: {scope.name}.{wire}")
        return values

    output_wires = meta.output_wires(scope)
    top_positions, bot_positions = ((0, 1), (2, 3)) if len(scope.output) == 4 else ((4, 5), (6, 7))
    bot0, bot1 = [output_wires[index] for index in bot_positions]
    expression0, noise0 = arguments(bot0, "matrixAdd")
    expression1, noise1 = arguments(bot1, "matrixAdd")
    payload0, secret_top = arguments(expression0, "matrixSub")
    payload1, _ = arguments(expression1, "matrixSub")
    secret, _ = arguments(secret_top, "matrixMulScalarLeft")
    unit_gadget0, monomial = arguments(payload0, "matrixMulScalarRight")
    unit_gadget1, _ = arguments(payload1, "matrixMulScalarRight")
    unit_gadget0, _ = arguments(unit_gadget0, "matrixMulScalarRight")
    unit_gadget1, _ = arguments(unit_gadget1, "matrixMulScalarRight")
    _, _ = arguments(unit_gadget0, "matrixMulScalarLeft")
    one, _ = arguments(unit_gadget1, "matrixMulScalarLeft")
    lifted, exponent_wire = arguments(monomial, "multiplyMonomial")
    coefficient_wire, = arguments(lifted, "liftInteger")
    hs = adapters.wire_term(scope, secret)
    hone = adapters.wire_term(scope, one)
    coefficient = adapters.wire_term(scope, coefficient_wire)
    exponent = adapters.wire_term(scope, exponent_wire)

    def project(index):
        return "outputs." + "2." * index + "1"

    tops = ", ".join(project(index) for index in top_positions)
    bots = ", ".join(project(index) for index in bot_positions)
    text = f'''/-- The exported selector scope; the error is bounded by its actual cutoff. -/
theorem {scope.name}.selector_rhs {binders}
    (h : {call}) {{sp : ErrorPoly {n}}}
    (hs : {hs} = fun _ _ ↦ reducePoly {modulus} {n} sp)
    (hone : {hone} = fun _ _ ↦ reducePoly {modulus} {n} 1) :
    ∃ (source gadget : ExactMatrix {modulus} {n} 1 {columns}),
      gadgetMatrixRuns backend {base} {digits} source ∧ centeredRebaseRuns source gadget ∧
      ∃ error : Fin 2 → ErrorMatrix {n} 1 {columns},
        (∀ port, CoeffBound (error port) {cutoff}) ∧
        ∀ port, reducePoly {modulus} {n} sp • ![{tops}] port +
            ![{bots}] port =
          reducePoly {modulus} {n}
            (message {coefficient} {exponent} * unitPair sp port) • gadget +
            reduceMatrix {modulus} {n} 1 {columns} (error port) := by
  obtain {adapters.pattern(scope, per, witness=scope.kind == 'record')} := h
'''
    output_name = meta.one((name for name, atom in atoms if atom.startswith("outputs = ")),
                           "selector output equation")
    if gaussian:
        for index, (name, _) in enumerate(gaussian):
            text += f"  obtain ⟨error{index}, herror{index}, hbound{index}⟩ := gaussian_bound {name}\n"
    else:
        for index in range(2):
            text += f"  let error{index} : ErrorMatrix {n} 1 {columns} := 0\n"
            text += f"  have herror{index} : (0 : ExactMatrix {modulus} {n} 1 {columns}) = reduceMatrix {modulus} {n} 1 {columns} error{index} := by funext row column; simp [error{index}, reduceMatrix]\n"
            text += f"  have hbound{index} : CoeffBound error{index} 0 := by simp [error{index}, CoeffBound]\n"
    text += f'''  refine ⟨{source}, {gadget}, {gadgets[0][0]}, {rebases[0][0]},
    ![error0, error1], ?_, ?_⟩
  · intro port
    fin_cases port
    · exact hbound0
    · exact hbound1
  · rw [{output_name}]
    intro port
    fin_cases port
    · exact selector_rhs_noisy hs hs _ _ _ _ herror0
    · exact selector_rhs_noisy hs hone _ _ _ _ herror1

'''
    return qualify_witness(scope, text)


def metadata_declarations(view):
    result = "namespace Online0Shape\n\n"
    result += f"abbrev ringDimension : Nat := {view['ring_dimension']}\n"
    result += f"abbrev columns : Nat := {view['columns']}\n"
    result += f"abbrev smudgeDigits : Nat := {view['smudge_digits']}\n"
    result += f"abbrev primeCount : Nat := {len(view['primes'])}\n"
    for role, prf in view["prfs"].items():
        for key in ("members", "packed_members", "blocks"):
            result += f"abbrev {role}_{key} : Nat := {prf[key]}\n"
    return result + "\nend Online0Shape\n\n"


def lean_tuple(values):
    result = "()"
    for value in reversed(values):
        result = f"({value}, {result})"
    return result


def root_fact(root, atom, wire):
    fragments = [index for index, (_, body) in root.frag_src.items() if atom.text in body]
    index = meta.one(fragments, "root fact fragment")
    return f"F.c{index}.h{wire[2:]}"


def sum_inputs(module, loop_atom):
    root = module.root
    loop = loop_atom.loop
    initial = meta.flat_tuple(loop.init)
    families = loop.args[-6:]
    reads0, reads1 = [], []
    for value, family in zip(initial, families):
        head, args = meta.xmodel.app_split(root.wires[value].term)
        meta.require(head == "MxxRuntime.matrixAdd" and len(args) == 2, "member total initializer")
        for index, reads in enumerate((reads0, reads1)):
            atom = meta.one((atom for atom in root.atoms if atom.kind == "familyGetStatic"
                             and atom.args[0] == family and atom.args[-1] == args[index]),
                            "member static read")
            reads.append(root_fact(root, atom, args[index]))
    return families, initial, reads0, reads1


