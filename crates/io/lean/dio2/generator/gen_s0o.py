#!/usr/bin/env python3
"""Generate the step-zero transition assembly (s0o).

Modules (all in the package's proof directory):

* ``Dio2Step0Rows``: every refresh part's CRT row from the actual source
  relations, per-part target relations and root-level key links.  Primes are
  specialized; parts, cells, digits and coefficients remain quantified.
* ``Dio2Step0Agree`` (with ``s0o_agree.py``): the key-stage/online agreement of
  every refresh part's key inputs, by generic determinism of the exported graph.
* ``Dio2Step0Payload`` (``s0o_payload.py``): label-forest payloads; the forest
  root of a non-constant next label member is the next external label.
* ``Dio2Step0Targets`` (``s0o_targets.py``): the actual refresh targets of every
  part (``Step0Rows.TargetRows``) at the certified budgets.
* ``Dio2Step0`` (``s0o_step0.py``): the refreshed roots, the hint, and the closed
  ``Dio2Proof.Complete.step0_transition``.

Geometry, wire names, Facts fragments and prime-specific names are read from
``dio2_meta`` metadata and the exported producer graphs; no toy constant is
substituted.  All requested sources are built before any file is written.
"""

