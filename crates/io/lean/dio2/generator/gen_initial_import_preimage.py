            if wire == parts['mask']:
                value, proof = 'sm', 'hmask'
            elif wire == parts['unit']:
                value, proof = '1', 'one_entry'
                if parent:
                    proof = 'by rw [hunit]; exact one_entry'
            elif entry.src == 'input':
                meta.require(entry.term == 'inputs.2.2.2.2.1', 'unexpected scalar input')
                value, proof = 'tp', 'hpay'
            elif entry.term and re.match(r'\(1\s*:', entry.term):
                value, proof = '1', 'one_entry'
