def claim_tuple(package, stage, stages):
    _, line = stages[stage]
    _, arguments = meta.xmodel.app_split(line.strip().removesuffix(' ∧'))
    return meta.flat_tuple(arguments[-2])


def output_projections(scope, value):
    expression = meta.one((atom.args[0] for atom in scope.atoms if atom.kind == 'out'),
                          f'{scope.name} output')
    pending = [(expression, value)]
    leaves = []
    while pending:
        expression, path = pending.pop()
        expression = meta.xmodel.strip_parens(expression)
        if not expression:
            continue
        items = meta.xmodel.split_top(expression, ',')
        if len(items) == 1:
            leaves.append(path)
            continue
        pending.extend((item, path + '.2' * position +
                        ('.1' if position < len(items) - 1 else ''))
                       for position, item in reversed(list(enumerate(items))))
    meta.require(len(leaves) == len(meta.output_wires(scope)), 'output projection arity')
    return leaves


def imported_sources(package, stages):
    imported = meta.Module(package / 'worst', 'W_Stage_import_0', {})
    supplied = claim_tuple(package, 'import_0', stages)
    inputs = [wire for wire in imported.root.wires.values() if wire.src == 'input']
    meta.require(len(inputs) == len(supplied), 'import-zero input arity')
    values = {wire.name: value for wire, value in zip(inputs, supplied)}
    for atom in imported.root.loops:
        for out, argument in zip(atom.loop.outs[:2], atom.loop.args[:2]):
            values[out.split()[0]] = initial.replace_wires(argument, values.__getitem__).removesuffix(' i')
    for wire in imported.root.wires.values():
        if wire.src == 'let' and all(source in values for source in meta.xmodel.WIRE.findall(wire.term)):
            values[wire.name] = initial.replace_wires(wire.term, values.__getitem__)
    outputs = meta.output_wires(imported.root)
    projections = output_projections(imported.root,
                                    f'execution.«stage_{stages["import_0"][0]}»')
    output_values = {projection: values[wire] for projection, wire in zip(projections, outputs)
                     if wire in values}
    online = meta.Module(package / 'worst', 'W_Stage_online_0', {})
    supplied_online = claim_tuple(package, 'online_0', stages)
    online_inputs = [wire for wire in online.root.wires.values() if wire.src == 'input']
    meta.require(len(online_inputs) == len(supplied_online), 'online-zero input arity')
    return online, [(wire, value, output_values[meta.xmodel.strip_parens(value)])
                    for wire, value in zip(online_inputs, supplied_online)
                    if meta.xmodel.strip_parens(value) in output_values]


def input_source_lemmas(stages, sources):
    rows = []
    for wire, supplied, source in sources:
        rows.append(f'''
/-- Actual imported input `{wire.name}` is copied from the initial artifact. -/
theorem imported_{wire.name} {{model : HashModel}} {{external : GeneratedClaim.ExternalInputs}}
    {{execution : GeneratedClaim.Execution}} (h : W_GeneratedClaim.Runs model external execution)
    (ctx : W_Stage_online_0.generatedRoot.Ctx Backend.backend model
      W_GeneratedClaim.stage_{stages['online_0'][0]}_params)
    (hinputs : ctx.inputs = Claim0.onlineInputs external execution) :
    W_Stage_online_0.generatedRoot.{wire.name} ctx = {source} := by
  change ctx.{wire.term} = _
  rw [hinputs]
  change {supplied} = _
  rw [import0_spec (Claim0.imported_runs h)]
  rfl
''')
    return ''.join(rows)


def imported_root_lemmas(view, stages, initializer, sources):
    rows = []
    projections = output_projections(initializer.root,
                                    f'execution.«stage_{stages["initial"][0]}»')
    for group, ports in initializer.groups.items():
        components = []
        matches = []
        for side in range(2):
            binding = ports[side]
            parent = next((atom for atom in initializer.root.loops
                           if atom.loop.outs[0].split()[0] == binding['wire']), None)
            scope = initializer.module.scopes[parent.loop.child] if parent else initializer.root
            components.append(initializer.component(group, side, scope, parent, binding))
            output = projections[list(initializer.bindings).index(next(
                key for key, value in initializer.bindings.items() if value is binding))]
            matches.append([wire for wire, _, source in sources
                            if meta.xmodel.strip_parens(source) == output])
        if not all(matches):
            continue
        meta.require(len(matches[0]) == len(matches[1]), f'imported root pairing: {group}')
        name = initial.identifier(group)
        left = components[0]
        member = f' (member : Fin {ports[0]["members"]})' if left['parent'] else ''
        suffix = ' member' if member else ''

        def external(expression):
            value = expression.replace('inputs', '(Claim0.initialInputs external execution)')
            return re.sub(r'\b(sm|tp)\b', lambda match:
                          'state.mask' if match[0] == 'sm' else 'state.payload', value)

        for index, (first, second) in enumerate(zip(*matches)):
            rows.append(f'''
/-- Initial `{group}` roots reach the actual online-zero input unchanged. -/
theorem imported_rel_{name}_{index} {{model : HashModel}}
    {{external : GeneratedClaim.ExternalInputs}} {{execution : GeneratedClaim.Execution}}
    {{value : ErrorPoly {view['ring_dimension']}}}
    (h : W_GeneratedClaim.Runs model external execution)
    (state : State0Witness model external execution value)
    {{gadget : ExactMatrix W_Stage_online_0.modulus_0 {view['ring_dimension']} 1 {view['columns']}}}
    (hG : gadgetMatrixRuns Backend.backend {initializer.base} {initializer.digits} gadget){member} :
    Rel state.mask
      (rootKey model (Claim0.initialInputs external execution).2.2.1
        {left['prefix']} {external(left['components'])} W_Stage_online_0.modulus_0 {view['columns']})
      (fun port ↦ reducePoly W_Stage_online_0.modulus_0 {view['ring_dimension']}
        (({external(left['alpha'])}) * unitPair ({external(left['payload'])}) port) • gadget)
      ![W_Stage_online_0.generatedRoot.{first.name} state.context.online{suffix},
        W_Stage_online_0.generatedRoot.{second.name} state.context.online{suffix}] 1 := by
  rw [imported_{first.name} h state.context.online state.context.online_inputs,
    imported_{second.name} h state.context.online state.context.online_inputs]
  exact initial_rel_{name} (Claim0.initial_runs h) state.mask_eq state.payload_eq hG{suffix}
''')
    return ''.join(rows)


