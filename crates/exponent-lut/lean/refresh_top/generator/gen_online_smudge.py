"""Generate `Gen_Online_Smudge.lean` (WP F for D/G): the online summand forms of the final combination
(`GenFinalInst.final_inst`, PART_IFACE.md "Final combination (G)") that come from key-side facts.

* `smudge_<field>` (the online column loop over the smudge members — role `sum.columns.step` whose
  member family is the output of a `smudge.member` par loop): from per-member encodings
  `EncRel s (member i) (t i) B` (the conclusion of `SmudgeMember.rel`, a hypothesis here), the
  member-sum and column-loop closed forms (`memsum_*` / `colsum_*` of the online instance, generated
  as for the preprocessing), conclude `c1 = maskPart s ![A01, A11] - Tsm + reduce es`, `|es| ≤ W B`,
  `Tsm = ∑ i, colPlace i (∑ j < W, t_{W i + j} 1)` — `final_inst`'s `hs` with `Ks = ![A01, A11]`.
* `hint_<field>` (encrypt instance: `[s, 1] A + e` with a Gaussian `e`, `Gen.hint_gen`):
  `c = maskPart s (rowOf A) + reduce eb`, `|eb| ≤ cutoff`; `hint_online`: the same for the online
  hint input given the stage link `online = encrypt` (`final_inst`'s `hb`, `Bk k = rowOf A k`).
* `hpre_<field>` (preprocessing `target_*` + `comb_*`): for the online decomposition `D`, action
  digits `Y` and preimage `P` equal to the preprocessing ones (`GenFinalInst.pre_link`) and `A` the
  preprocessing public matrix, `rowOf A k * P = (Kg k * topRows D + K1 k * bottomRows D - Kx k * Y)
  + Kf k + Ks k` — `final_inst`'s `hpre`.
Recognition by role / atom kind / data flow (never wire ids); reuses `gen_instance_pre`'s instance
context and loop emitters.

Usage: gen_online_smudge.py <generated dir> <out file> <param dir (adapters, bridges)> roles.json
"""
