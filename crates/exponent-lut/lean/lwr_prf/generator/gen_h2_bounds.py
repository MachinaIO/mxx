def elim_chain(k, total, x='x'):
    """A proof that `Sum.elim` at the `k`-th injection reduces to the `k`-th function."""
    steps = ['Sum.elim_inr _ _ _'] * k + (['Sum.elim_inl _ _ _'] if k < total - 1 else [])
    t = f'({steps[-1]})'
    for st in reversed(steps[:-1]):
        t = f'(({st}).trans {t})'
    return t


def add_chain(names):
    t = names[-1]
    for nm in reversed(names[:-1]):
        t = f'(add_le_add {nm} {t})'
    return t


def ctor(k, total, x='x'):
    """The `k`-th injection into a right-nested sum of `total` classes."""
    t = x if k == total - 1 else f'(Sum.inl {x})'
    for _ in range(k):
        t = f'(Sum.inr {t})'
    return t


def sum_elim_str(fs):
    s = fs[-1]
    for f in reversed(fs[:-1]):
        s = f'Sum.elim {f} ({s})' if not s.startswith('(') else f'Sum.elim {f} {s}'
    return s


