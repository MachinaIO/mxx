def tuple_expr(entries):
    return '(' + ', '.join(entries + ['()']) + ')'


def projection(name, index):
    return name + '.2' * index + '.1'


def vector(entries):
    return '![' + ', '.join(entries) + ']'


def forall_slots(proofs):
    result = '(by intro index; exact Fin.elim0 index)'
    for proof in reversed(proofs):
        result = f'Fin.cases ({proof}) ({result})'
    return result


def scope_data(scope):
    source = translate((HERE / 'generated/Stage_preprocess.lean').read_text(),
                       'Stage_preprocess', reverse=True)
    source = rename_roots(source, 'pre', reverse=True)
    start = re.search(r'(?:abbrev ' + scope + r'\.body|def ' + scope + r' )', source).start()
    body = re.split(r'\n(?:def|abbrev|set_option)', source[start:], maxsplit=1)[0]
    witnesses = re.findall(r'∃ \((w_\d+_\d+) :', body)
    constraints = {}
    for match in re.finditer(r'abbrev ' + scope + r'\.constraints_(\d+) .*? : Prop :=\n(.*?)(?=\n\n)', source, re.S):
        constraints[int(match[1])] = match[2].splitlines()
    facts = {}
    for chunk, lines in sorted(constraints.items()):
        root = projection('hbody', chunk) if chunk < len(constraints) - 1 else 'hbody' + '.2' * chunk
        for index, line in enumerate(lines):
            facts[line.strip().removesuffix(' ∧')] = (projection(root, index)
                if index < len(lines) - 1 else root + '.2' * index)
    return body, witnesses, facts


