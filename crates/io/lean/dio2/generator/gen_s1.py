def smudge_certified_source(package, metadata, header, arguments, budget):
    n = metadata["views"]["worst"]["ring_dimension"]
    source = smudge_root(package, metadata, header, arguments, budget)
    source = source[source.index("theorem online1_smudge_root "):]
    statement = source.split(" := by", 1)[0]
    statement = statement.replace("theorem online1_smudge_root", "theorem online1_smudge_certified", 1)
    for parameter in ["Ba", "Bs", "Bh", "Bswitch"]:
        statement = statement.replace("{" + parameter + " : Nat}", "")
    statement, count = re.subn(r"\(BB : Fin \d+ → Nat\)", "", statement)
    require(count == 1, "changed smudge RHS error-family binder")
    replacements = {
        "Ba": f"({n} + 2)",
        "Bs": f"({n} + 2)",
        "Bh": f"({n} + 2)",
        "Bswitch": "Dio2NoiseCertificate.F",
        "BB": "(fun _ ↦ Dio2NoiseCertificate.F)",
    }
    substitute = lambda text: re.sub(
        r"\b(?:Ba|Bs|Bh|Bswitch|BB)\b", lambda match: replacements[match[0]], text
    )
    statement = substitute(statement)
    statement, count = re.subn(
        r"CoeffBound es \(.*?\) ∧ CoeffBound M \(.*?\) ∧",
        "CoeffBound es Dio2NoiseCertificate.b10_smudge ∧ "
        "CoeffBound M Dio2NoiseCertificate.b10_residue ∧",
        statement,
        flags=re.S,
    )
    require(count == 1, "changed root smudge/residual bound pair")
    return f'''/-- The complete digit-loop smudge relation and residual fit the certificate.
The public selector, label-product and odd bounded readout premises are explicit;
no intermediate PRF, packing, smudge output or final noise margin is assumed. -/
{statement} := by
  obtain ⟨es, residual, hes, hresidual, hs, htarget⟩ := online1_smudge_root
    {substitute(arguments)} hgq digit hreadout hodd hbound
  refine ⟨es, residual, coeffBound_mono hes online1_smudge_budget, ?_, hs, htarget⟩
  exact coeffBound_mono hresidual (by norm_num [Dio2NoiseCertificate.b10_residue])
'''


def native_fourier_source():
    return '''/-- A small exponent table retains the native negacyclic period in every term. -/
theorem online1_native_walsh_terms {n q native width stride : Nat}
    (hq : 1 < q) (hn : 0 < n) {sigma : Nat} (hodd : Odd sigma)
    (hperiod : n = stride * native) (hwidth : width ≤ native)
    (inverse : ExactPoly q n) (outputStride : Nat) (table : Fin width → Nat) :
    inverse * ∑ index : Fin width,
      (multiplyMonomial (ringAutomorphism sigma
        (multiplyMonomial (matrixPolynomial [1] : ExactMatrix q n 1 1)
          ((index : Nat) * -(stride : Int))))
        ((table index : Int) * (outputStride : Int))) 0 0 =
      lutFourierCoefficient native (X q ^ stride) inverse
        (fun index ↦ reducePoly q n (Xe (n := n) (outputStride * table index))) sigma := by
  unfold lutFourierCoefficient
  congr 1
  apply Finset.sum_congr rfl
  intro index _
  simp only [multiplyMonomial]
  rw [show ringAutomorphism sigma
      (multiplyMonomial (matrixPolynomial [1] : ExactMatrix q n 1 1)
        ((index : Nat) * -(stride : Int))) 0 0 =
        (X q ^ stride) ^ (sigma * (2 * native - index)) from
      term_root hq hn hodd hperiod ⟨index.val, index.isLt.trans_le hwidth⟩]
  rw [reducePoly_Xe, mul_comm]
  congr 1
  rw [root_pow_mod2n (outputStride * table index)]
  congr 1
  have hexponent : (((table index : Int) * (outputStride : Int)) %
      (2 * (n : Int))).toNat = (outputStride * table index) % (2 * n) := by
    rw [show (table index : Int) * (outputStride : Int) =
        ((outputStride * table index : Nat) : Int) by push_cast; ring,
      show 2 * (n : Int) = ((2 * n : Nat) : Int) by push_cast; ring]
    rw [← Int.natCast_mod, Int.toNat_natCast]
  rw [hexponent]

/-- The generated finite table sum is Fourier-normalized at its native width. -/
theorem online1_exponent_coefficient_native {n q native width stride outputStride : Nat}
    (hq : 1 < q) (hn : 0 < n) (hperiod : n = stride * native)
    (hwidth : width ≤ native) {sigma : Int} (hodd : Odd sigma.toNat)
    (inverse : Int) (table : Fin width → Int) (hnonnegative : ∀ index, 0 ≤ table index) :
    PreprocessSwitch.exponentCoefficient (q := q) (n := n) sigma stride outputStride
      inverse table = lutFourierCoefficient native (X q ^ stride)
        (inverse : ExactPoly q n)
        (fun index ↦ reducePoly q n (Xe (n := n) (outputStride * (table index).toNat)))
        sigma.toNat := by
  have hcast : ∀ index, ((table index).toNat : Int) = table index :=
    fun index ↦ Int.toNat_of_nonneg (hnonnegative index)
  have hterms := online1_native_walsh_terms hq hn hodd hperiod hwidth
    (inverse : ExactPoly q n) outputStride (fun index ↦ (table index).toNat)
  simp only [hcast] at hterms
  unfold PreprocessSwitch.exponentCoefficient keyTableG keyTermE
  rw [range_dite_sum (fun index : Fin width ↦
    multiplyMonomial (ringAutomorphism sigma.toNat
      (multiplyMonomial (matrixPolynomial [1] : ExactMatrix q n 1 1)
        (Int.ofNat index.val * -(stride : Int))))
      (table index * (outputStride : Int)))]
  simpa only [matrixMulScalarLeft, matrixPolynomial_single, Int.cast_one, one_mul,
    Matrix.sum_apply] using hterms
'''


def state_walsh_source(metadata, preprocessing):
    view = metadata["views"]["worst"]
    n = view["ring_dimension"]
    coefficient = re.search(r"exponentCoefficient \(sigmaOf stateSigmas branch\) (\d+) (\d+) (\d+)",
                            preprocessing)
    require(coefficient is not None, "state Fourier normalization")
    stride, output_stride, inverse = map(int, coefficient.groups())
