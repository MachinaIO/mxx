fn normalized_protocol(protocol: &ProtocolDecl) -> Result<Value, serde_json::Error> {
    let mut stages = Vec::new();
    for stage in &protocol.stages {
        let mut graph = serde_json::to_value(&stage.graph)?;
        strip_runtime_identity(&mut graph);
        stages.push(json!({
            "id": stage.id,
            "graph": graph,
            "bindings": stage.bindings,
        }));
    }
    let mut ideal = serde_json::to_value(&protocol.correctness.ideal.graph)?;
    strip_runtime_identity(&mut ideal);
    let mut requirements = Vec::new();
    for requirement in &protocol.correctness.requires {
        let mut graph = serde_json::to_value(&requirement.graph)?;
        strip_runtime_identity(&mut graph);
        requirements.push(graph);
    }
    let comparator = match &protocol.correctness.comparator {
        Comparator::Equal => json!({"kind": "equal"}),
        Comparator::EqualAfterMap { map } => {
            let mut graph = serde_json::to_value(&map.graph)?;
            strip_runtime_identity(&mut graph);
            json!({"kind": "equal_after_map", "map": graph})
        }
        Comparator::NormWithin { bound } => json!({"kind": "norm_within", "bound": bound}),
    };
    Ok(json!({
        "version": GENERATOR_VERSION,
        "params": protocol.params,
        "stages": stages,
        "entrypoint": protocol.entrypoint,
        "semantic_certificate": protocol.semantic_certificate,
        "correctness": {
            "protocol_inputs": protocol.correctness.protocol_inputs,
            "requires": requirements,
            "ideal": ideal,
            "compared_outputs": protocol.correctness.compared_outputs,
            "comparator": comparator,
            "checker_signature": "Params -> Bool",
        }
    }))
}

fn strip_runtime_identity(value: &mut Value) {
    match value {
        Value::Object(map) => {
            map.remove("production_id");
            map.remove("production");
            map.remove("execution_nonce");
            for value in map.values_mut() {
                strip_runtime_identity(value);
            }
        }
        Value::Array(values) => values.iter_mut().for_each(strip_runtime_identity),
        _ => {}
    }
}

fn lean_identifier(value: &str) -> String {
    let mut output = String::new();
    let mut upper = true;
    for character in value.chars() {
        if character.is_ascii_alphanumeric() {
            output.push(if upper { character.to_ascii_uppercase() } else { character });
            upper = false;
        } else {
            upper = true;
        }
    }
    if output.is_empty() { "Protocol".to_owned() } else { output }
}

fn lower_identifier(value: &str) -> String {
    let value = lean_identifier(value);
    let mut characters = value.chars();
    characters
        .next()
        .map(|first| first.to_ascii_lowercase().to_string() + characters.as_str())
        .unwrap_or_else(|| "protocol".to_owned())
}

fn lean_field_identifier(value: &str) -> String {
    let value = lean_identifier(value);
    let mut characters = value.chars();
    characters
        .next()
        .map(|first| first.to_ascii_lowercase().to_string() + characters.as_str())
        .unwrap_or_else(|| "value".to_owned())
}

fn lean_string(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\"").replace('\n', "\\n"))
}

fn lean_wire_type(wire_type: &WireType) -> Result<String, EmitError> {
    Ok(match wire_type {
        WireType::Matrix(_) | WireType::Preimage(_) => "Mxx.Matrix".to_owned(),
        WireType::ConstantInt | WireType::Int => "Int".to_owned(),
        WireType::ConstantBool | WireType::Bool => "Bool".to_owned(),
        WireType::Bytes { .. } => "ByteArray".to_owned(),
        WireType::ConstantReal | WireType::Real => "Rat".to_owned(),
        WireType::IndexedFamily { element, .. }
            if matches!(element.as_ref(), WireType::ConstantInt | WireType::Int) =>
        {
            "List Int".to_owned()
        }
        WireType::Trapdoor { .. } => return Err(EmitError::UnsupportedWireType("Trapdoor")),
        WireType::TypedBlob { .. } => return Err(EmitError::UnsupportedWireType("TypedBlob")),
        WireType::IndexedFamily { .. } => {
            return Err(EmitError::UnsupportedWireType("IndexedFamily"));
        }
    })
}

fn ensure_supported_wire_types(protocol: &ProtocolDecl) -> Result<(), EmitError> {
    for (_, destinations) in &protocol.correctness.protocol_inputs {
        lean_wire_type(protocol_input_wire_type(protocol, destinations))?;
    }
    Ok(())
}

fn lean_constraint(
    constraint: &ParamConstraint,
    protocol: &ProtocolDecl,
) -> Result<String, EmitError> {
    let proposition = match constraint {
        ParamConstraint::IntPositive { value, .. } => {
            format!("0 < {}", lean_int_expr(value, protocol))
        }
        ParamConstraint::IntNonnegative { value, .. } => {
            format!("0 ≤ {}", lean_int_expr(value, protocol))
        }
        ParamConstraint::IntGreaterThan { left, right, .. } => {
            format!("{} > {}", lean_int_expr(left, protocol), lean_int_expr(right, protocol))
        }
        ParamConstraint::IntLessEqual { left, right, .. } => {
            format!("{} ≤ {}", lean_int_expr(left, protocol), lean_int_expr(right, protocol))
        }
        ParamConstraint::IntEqual { left, right, .. } => {
            format!("{} = {}", lean_int_expr(left, protocol), lean_int_expr(right, protocol))
        }
        ParamConstraint::RealPositive { value, .. } => {
            format!("(0 : Rat) < {}", lean_real_expr(value, protocol)?)
        }
        ParamConstraint::RealNonnegative { value, .. } => {
            format!("(0 : Rat) ≤ {}", lean_real_expr(value, protocol)?)
        }
    };
    Ok(format!("decide ({proposition})"))
}

fn lean_int_expr(expression: &IntExpr, protocol: &ProtocolDecl) -> String {
    match expression {
        IntExpr::Const(value) => format!("({value} : Int)"),
        IntExpr::Var(name) => {
            let field = format!("p.{}", lean_field_identifier(name));
            match protocol.params.iter().find(|parameter| parameter.name == *name).map(|p| &p.kind)
            {
                Some(crate::ParameterKind::Dimension) => format!("Int.ofNat {field}"),
                _ => field,
            }
        }
        IntExpr::LoopIndex(slot) => format!("(0 : Int) /* loop index {slot} is runtime-bound */"),
        IntExpr::Add(left, right) => {
            format!("({} + {})", lean_int_expr(left, protocol), lean_int_expr(right, protocol))
        }
        IntExpr::Sub(left, right) => {
            format!("({} - {})", lean_int_expr(left, protocol), lean_int_expr(right, protocol))
        }
        IntExpr::Mul(left, right) => {
            format!("({} * {})", lean_int_expr(left, protocol), lean_int_expr(right, protocol))
        }
        IntExpr::Div(left, right) => {
            format!("({} / {})", lean_int_expr(left, protocol), lean_int_expr(right, protocol))
        }
        IntExpr::RoundDiv(left, right) => format!(
            "Mxx.Ir.roundDiv {} {}",
            lean_int_expr(left, protocol),
            lean_int_expr(right, protocol)
        ),
        IntExpr::Log2Ceil(value) => {
            format!("Mxx.Ir.log2Ceil {}", lean_int_expr(value, protocol))
        }
    }
}

fn lean_real_expr(expression: &RealExpr, protocol: &ProtocolDecl) -> Result<String, EmitError> {
    Ok(match expression {
        RealExpr::Rational(value) => {
            format!("(({} : Rat) / ({} : Rat))", value.numerator(), value.denominator())
        }
        RealExpr::Var(name) => format!("p.{}", lean_field_identifier(name)),
        RealExpr::FromInt(value) => format!("({} : Rat)", lean_int_expr(value, protocol)),
        RealExpr::Add(left, right) => {
            format!("({} + {})", lean_real_expr(left, protocol)?, lean_real_expr(right, protocol)?)
        }
        RealExpr::Sub(left, right) => {
            format!("({} - {})", lean_real_expr(left, protocol)?, lean_real_expr(right, protocol)?)
        }
        RealExpr::Mul(left, right) => {
            format!("({} * {})", lean_real_expr(left, protocol)?, lean_real_expr(right, protocol)?)
        }
        RealExpr::Div(left, right) => {
            format!("({} / {})", lean_real_expr(left, protocol)?, lean_real_expr(right, protocol)?)
        }
        RealExpr::Sqrt(_) => {
            return Err(EmitError::IrrationalConstraint(format!("{expression:?}")));
        }
    })
}

