def assembly_module(view):
    n, columns = view['ring_dimension'], view['columns']
    parts = view['refresh']['parts']
    prime_count = len(view['primes'])
    kinds = [('private', 'private'), ('public', 'public'), ('state', 'stateTarget'),
             ('labels', 'label'), ('sigma', 'sigma'), ('Aut', 'automorphism')]
    ranges = view['target_classes']
    conditions = []
    previous_stop = 0
    for kind, certificate in kinds:
        intervals = sorted((entry['start'], entry['stop']) for entry in ranges
                           if entry['kind'] == kind)
        for start, stop in intervals:
            meta.require(start == previous_stop and start < stop,
                         f'noncontiguous certificate class: {kind}')
            previous_stop = stop
        if intervals:
            conditions.append((2 * previous_stop, certificate))
    anchors = [(entry['start'], entry['stop']) for entry in ranges if entry['kind'] == 'anchor']
    meta.require(anchors == [(previous_stop, parts // 2)], 'remaining targets must be anchor parts')
    tables = view['lut_tables']['preprocess_0_0']
    state_table = tables[0]['values']
    width = len(state_table)
    log_width = width.bit_length() - 1
    meta.require(width == 2 ** log_width, 'state table width must be a power of two')
    sigmas = meta.one([entry['values'] for entry in tables
                       if len(entry['values']) == width
                       and len(set(entry['values'])) == width
                       and all(value % 2 == 1 for value in entry['values'])],
                      'state table automorphisms')
    native = n // 2
    quotient = native // width
    meta.require(native == quotient * width and quotient > 0,
                 'state LUT native width and automorphism quotient')
    budget = ''.join(f'  if part.val < {stop} then b1_{name} else\n'
                     for stop, name in conditions) + '  b1_anchor'
    margins = []
    for prime in range(prime_count):
        cases = []
        for _, name in conditions + [(parts, 'anchor')]:
            cases.append(f'''  · calc
      _ = b1_left_{name} := by
        rw [b1_left_{name}_eval, b1_error_{name}_eval, b1_hint_eval,
          b1_root_eval, C_eval, n_eval, m_eval, anchor_eval, half_eval, base_eval]
        ring
      _ < _ := b1_{name}_p{prime}''')
        margins.append(f'''
/-- Prime {prime}: every target class satisfies the certificate's exact margin. -/
theorem noise_margin{prime} (part : Fin {parts}) :
    2 * ({view['anchor_columns']} * {n} * 1 * cutoff +
      ({columns} * {n} * b1_g * half + {columns} * {n} * b1_one * half +
        {columns} * {n} * targetBudget part * half) + b1_fresh + b1_smudge +
      b1_residue) < quotient{prime} := by
  unfold targetBudget
  split_ifs
{chr(10).join(cases)}
''')
    return 'import Dio2Online0Inputs\nimport Dio2StepTransition\nimport Dio2Noise\nimport Dio2Ideal\nimport Dio2PreprocessSwitch\n\n' + HEADER + f'''
namespace Online0Assembly

open Dio2NoiseCertificate

/-- The certificate budget of one component/target part, not a sum over targets. -/
def targetBudget (part : Fin {parts}) : Nat :=
{budget}

{''.join(margins)}

/-- Semantic error budgets may be smaller than the certified class budgets. -/
theorem noise_expression_mono (part : Fin {parts})
    {{Beb BP Beg Be1 Bex Bf Bs BM : Nat}}
    (hBeb : Beb ≤ 1) (hBP : BP ≤ cutoff)
    (hBeg : Beg ≤ b1_g) (hBe1 : Be1 ≤ b1_one)
    (hBex : Bex ≤ targetBudget part) (hBf : Bf ≤ b1_fresh)
    (hBs : Bs ≤ b1_smudge) (hBM : BM ≤ b1_residue) :
    2 * ({view['anchor_columns']} * {n} * Beb * BP +
      ({columns} * {n} * Beg * half + {columns} * {n} * Be1 * half +
        {columns} * {n} * Bex * half) + Bf + Bs + BM) ≤
    2 * ({view['anchor_columns']} * {n} * 1 * cutoff +
      ({columns} * {n} * b1_g * half + {columns} * {n} * b1_one * half +
        {columns} * {n} * targetBudget part * half) + b1_fresh + b1_smudge +
      b1_residue) := by
  gcongr

/-- The actual exported state-zero automorphism table, not a toy-width substitute. -/
def stateAutomorphism (branch : Fin {width}) : Nat :=
  (MxxIR.selectInt (branch.val : Int) {sigmas}).toNat

/-- Table-zero Walsh interpolation for the Boolean state and bit in the native ring.
Only its fixed automorphism table is specialized; no plaintext coefficient is expanded. -/
theorem table0_walsh {{R : Type}} [CommRing R]
    (root inverse : R) (state bit : Nat) (hstate : state ≤ 1) (hbit : bit ≤ 1)
    (hroot : root ^ {native} = -1) (hinverse : inverse * ({width} : R) = 1) :
    (∑ branch : Fin {width}, root ^ (stateAutomorphism branch * (state + bit)) *
      lutFourierCoefficient {native} root inverse
        (fun index : Fin {width} ↦ root ^ (entry table0 (index.val : Int)).toNat)
        (stateAutomorphism branch)) =
      root ^ (entry table0 ((state + bit : Nat) : Int)).toNat := by
  have hindex : ∀ branch : Fin {width},
      stateAutomorphism branch % {n} = 1 + 2 * {quotient} * branch.val := by
    decide
  exact lut_fourier_table_value {log_width} {native} {quotient} root inverse
    (fun index : Fin {width} ↦ root ^ (entry table0 (index.val : Int)).toNat)
    ⟨state + bit, by omega⟩ (by norm_num) (by norm_num) hroot hinverse
    stateAutomorphism (Equiv.refl _) hindex

/-- Public state and bit monomials multiply at their sum exponent without enumeration. -/
theorem state_input (state bit : Nat) :
    Xe (n := {n}) (2 * state) * Xe (n := {n}) (2 * bit) =
      Xe (n := {n}) (2 * (state + bit)) := by
  simp only [Xe, ← pow_add, Nat.mul_add]

end Online0Assembly

end Dio2Proof
'''


def route_lemmas(module, view):
    family = meta.xmodel.WIRE.findall(view['refresh']['family_output'][0])[0]
    loops = {atom.loop.child: atom for atom in module.root.loops}
    roots = meta.Flow(module.root)
    rows = []
    for name, route in view['root_routes'].items():
        binding = view['bindings']['online_0'][name]
        identifier = initial.identifier(name)
        wire = binding['wire']
        if 'scope' not in route:
            atom = roots.producers.get(wire)
            if atom is not None and atom.kind == 'familyGetStatic':
                index = meta.integer(atom.args[1])
                rows.append(f'''
/-- Exact static placement of `{name}` in the refreshed family. -/
theorem route_{identifier} {{backend : BackendContext}} {{model : HashModel}} {{params : Params}}
    (ctx : generatedRoot.Ctx backend model params) {{outputs : _}}
    (facts : generatedRoot.Facts ctx outputs) :
    generatedRoot.{wire} ctx = generatedRoot.{family} ctx ⟨{index}, by omega⟩ := by
  obtain ⟨position, hposition, hvalue⟩ := {initial.atom_fact(atom, 'facts')}
  have heq : position = ⟨{index}, by omega⟩ := by
    apply Fin.ext
    change position.val = {index}
    omega
  simpa only [heq] using hvalue
''')
            continue
        scope = module.scopes[route['scope']]
        read = meta.one([atom for atom in scope.atoms if atom.kind == 'familyGetDynamic'],
                        f'{scope.name} dynamic read')
        selects = {atom.args[-1]: atom for atom in scope.atoms if atom.kind == 'select'}

        def expression(term, keep_selected=False):
            def expand_wire(current):
                entry = scope.wires[current]
                if current in selects:
                    if keep_selected:
                        return current
                    atom = selects[current]
                    return '(MxxIR.selectInt ' + expression(atom.args[0]) + ' ' + expression(atom.args[1]) + ')'
                meta.require(entry.term is not None, f'unknown index producer {scope.name}.{current}')
                return '(' + expression(entry.term, keep_selected) + ')'
            return initial.replace_wires(term, expand_wire).replace('i_0', 'member.val')

        index_expression = expression(read.args[1])
        meta.require({atom.frag for atom in scope.atoms} == {0},
                     f'root route has multiple constraint fragments: {scope.name}')
        witnesses = [wire for wire, entry in scope.wires.items() if entry.term is None]
        names = [f'fact{index}' for index in range(len(scope.atoms))]
        statements = [f"  obtain ⟨{', '.join(witnesses + names)}⟩ := "
                      f"{initial.atom_fact(loops[scope.name], 'facts')} member"]
        for selected, atom in selects.items():
            statements.append(f'''  have selected_{selected} : {selected} =
      MxxIR.selectInt {expression(atom.args[0])} {expression(atom.args[1])} :=
    select_value fact{scope.atoms.index(atom)}''')
        read_fact = f'fact{scope.atoms.index(read)}'
        output = meta.one([atom for atom in scope.atoms if atom.kind == 'out'], 'root route output')
        statements.extend([f'  have selectedValue := {read_fact}',
                           f'  rw [fact{scope.atoms.index(output)}]',
                           f'''  change familyGetDynamic (generatedRoot.{family} ctx)
    {expression(read.args[1], True)} {read.args[-1]} at selectedValue'''])
        if selects:
            statements.append('  rw [' + ', '.join('selected_' + wire for wire in selects) + '] at selectedValue')
        statements.append('  exact selectedValue')
        rows.append(f'''
/-- Exact dynamic placement of every `{name}` member; no family is expanded. -/
theorem route_{identifier} {{backend : BackendContext}} {{model : HashModel}} {{params : Params}}
    (ctx : generatedRoot.Ctx backend model params) {{outputs : _}}
    (facts : generatedRoot.Facts ctx outputs) (member : Fin {binding['members']}) :
    familyGetDynamic (generatedRoot.{family} ctx) {index_expression}
      (generatedRoot.{wire} ctx member) := by
{chr(10).join(statements)}
''')
    return ''.join(rows)


def transition_module(view, module):
    n, columns = view['ring_dimension'], view['columns']
    count, targets = view['refresh']['parts'], view['refresh']['targets']
    result = meta.one(meta.xmodel.WIRE.findall(meta.one(view['refresh']['family_output'], 'part family')),
                      'part family wire')
    scope = view['refresh']['scope']
    loop = meta.one([atom for atom in module.root.loops if atom.loop.child == scope],
                    'refresh part loop')
    part_args = []
    for argument in view['refresh']['arguments']:
        part_args.append(initial.replace_wires(argument, lambda wire: f'(generatedRoot.{wire} ctx)')
                         .replace(' i', ' index'))
    input_tuple = '(' + ', ('.join(part_args) + ', ()' + ')' * len(part_args)
    out_fact = initial.atom_fact(meta.one([atom for atom in module.scopes[scope].atoms
                                          if atom.kind == 'out'], 'part output'), 'partFacts')
    return 'import Dio2Online0Row\nimport Dio2Import\nimport Dio2Sharp\n\n' + HEADER + ALGEBRA + f'''
namespace StepTransition

open W_Stage_online_0
open GenDecode

/-- The checked exported target/component packing; no target is enumerated. -/
def partIndex (target : Fin {targets}) (component : Fin 2) : Fin {count} :=
  ⟨2 * target.val + component.val, by omega⟩

/-- The actual root-to-part argument tuple, including all weighted smudge inputs. -/
noncomputable def partInputs {{backend : BackendContext}} {{model : HashModel}} {{params : Params}}
    (ctx : generatedRoot.Ctx backend model params) (index : Fin {count}) :=
  {input_tuple}

/-- Pointwise successful CRT terms close the actual exported part loop. -/
theorem part_family {{backend : BackendContext}} {{model : HashModel}} {{params : Params}}
    (ctx : generatedRoot.Ctx backend model params) {{outputs : _}}
    (facts : generatedRoot.Facts ctx outputs)
    (value : Fin {count} → ExactMatrix modulus_0 {n} 1 {columns})
    (terms : ∀ (index : Fin {count})
      (part : {scope}.Ctx backend model params index.val),
      part.inputs = partInputs ctx index →
      {scope}.Facts part (generatedRoot.{result} ctx index) →
      ∀ prime, TermOf (primes0 prime) (crt0 prime) (partTerms0 part prime) (value index)) :
    ∀ index, generatedRoot.{result} ctx index = value index := by
  intro index
  obtain ⟨witness, partBody⟩ := {initial.atom_fact(loop, 'facts')} index
  let part : {scope}.Ctx backend model params index.val :=
    ⟨partInputs ctx index, witness⟩
  have partFacts := {scope}.facts part partBody
  exact {out_fact}.trans (online0_part_row part (terms index part rfl partFacts))

/-- Pair the actual CRT-recombined output family of online zero. -/
noncomputable def nextRows {{backend : BackendContext}} {{model : HashModel}} {{params : Params}}
    (ctx : generatedRoot.Ctx backend model params) (target : Fin {targets}) :
    Fin 2 → ExactMatrix modulus_0 {n} 1 {columns} :=
  fun component ↦ generatedRoot.{result} ctx (partIndex target component)

/-- The complete family of CRT terms yields all paired next-root equations. -/
theorem paired_parts {{backend : BackendContext}} {{model : HashModel}} {{params : Params}}
    (ctx : generatedRoot.Ctx backend model params)
    {{next : ErrorPoly {n}}}
    {{keys : Fin {targets} → Fin 2 → Fin 2 → ExactMatrix modulus_0 {n} 1 {columns}}}
    {{target : Fin {targets} → Fin 2 → ExactPoly modulus_0 {n}}}
    {{gadget : ExactMatrix modulus_0 {n} 1 {columns}}}
    {{fresh : Fin {targets} → Fin 2 → ErrorMatrix {n} 1 {columns}}}
    {{bound : Fin {targets} → Nat}}
    (hfresh : ∀ index component, CoeffBound (fresh index component) (bound index))
    (hparts : ∀ index component,
      generatedRoot.{result} ctx (partIndex index component) =
        reducePoly modulus_0 {n} next • keys index 0 component + keys index 1 component -
          target index component • gadget +
            reduceMatrix modulus_0 {n} 1 {columns} (fresh index component)) :
    ∀ index, Rel next (keys index) (fun component ↦ target index component • gadget)
      (nextRows ctx index) (bound index) :=
  step_refresh_rel hfresh hparts

{route_lemmas(module, view)}

end StepTransition

end Dio2Proof
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('package', type=Path)
    parser.add_argument('--output-dir', type=Path)
    parser.add_argument('--metadata', type=Path,
                        help='Reuse dio2_meta.py JSON after checking all source fingerprints')
    args = parser.parse_args()
    package = args.package.resolve()
    if args.metadata:
        metadata = json.loads(args.metadata.read_text())
        meta.require(metadata['package'] == package.name, 'metadata package mismatch')
        meta.require(bool(metadata['sources']), 'metadata has no source fingerprints')
        for relative, expected in metadata['sources'].items():
            source = Path(relative)
            meta.require(not source.is_absolute() and '..' not in source.parts,
                         f'unsafe metadata source path: {relative}')
            actual = hashlib.sha256((package / source).read_bytes()).hexdigest()
            meta.require(actual == expected, f'metadata source changed: {relative}')
    else:
        metadata = meta.extract(package)
    meta.check(metadata)
    view = metadata['views']['worst']
    output = args.output_dir or package / 'proof'
    stages = initial.claim_stages(package)
    online, sources = imported_sources(package, stages)
    modules = {'Dio2Online0Inputs': inputs_module(package, view, metadata['backend_layouts'],
                                               stages, sources),
               'Dio2StepTransition': transition_module(view, online),
               'Dio2Online0Assembly': assembly_module(view)}
    output.mkdir(parents=True, exist_ok=True)
    for name, source in modules.items():
        (output / (name + '.lean')).write_text(source)
    print(json.dumps({'package': metadata['package'], 'modules': list(modules)}))


if __name__ == '__main__':
    main()
