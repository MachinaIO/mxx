def online_smudge(C, notes):
    """`memsum`/`colsum` of the smudge column loop and `smudge_<field>`."""
    out = []
    smem = [a for a in C.ij['atoms'] if a.get('loop') and a['loop']['kind'] == 'par'
            and C.roles.get(a['loop']['child'], {}).get('role') in ('smudge.member', 'sampler.placement')]
    seqs = [a for a in C.ij['atoms'] if a.get('loop') and a['loop']['kind'] == 'seq' and a['loop']['child'] in C.sad]
    memsums = {}
    for a in seqs:
        if not C.sad[a['loop']['child']][0].startswith('MemberStep.Spec '):
            continue
        try:
            txt, n, d = P.emit_memsum(C, a)
        except (KeyError, ValueError, IndexError, AttributeError) as e:
            continue
        if any(xsem.wire_of(x.split()[0]) in [xsem.wire_of(o.split()[0]) for m in smem for o in m['loop']['outs']]
               for x in a['loop']['args']):
            out.append(txt)
            memsums[n] = d
    for a in seqs:
        if not C.sad[a['loop']['child']][0].startswith('ColStep.Spec '):
            continue
        for m in smem:
            mouts = [xsem.wire_of(o.split()[0]) for o in m['loop']['outs']]
            fam = [xsem.wire_of(x.split()[0]) for x in a['loop']['args'] if xsem.wire_of(x.split()[0])]
            if fam != mouts:
                continue
            try:
                txt, cn = P.emit_colsum(C, a, memsums)
            except (KeyError, ValueError, IndexError, AttributeError) as e:
                notes.append(f'-- {a["field"]}: column sums not generated: {e!r}')
                continue
            out.append(txt)
            if C.roles.get(m['loop']['child'], {}).get('role') != 'smudge.member':
                continue
            out.append(smudge_thm(C, a, m, cn))
            try:
                mtxt, mk = P.emit_par(C, m, 'members')
                C._members_text = mtxt
                out.append(mtxt)
                out.append(smudge_half_thm(C, a, m, mk['concl'], notes))
            except (KeyError, ValueError, IndexError, StopIteration) as e:
                notes.append(f'-- {m["field"]}: member encodings not generated: {e!r}')
    return out


def half_wire(C):
    """The half row: the root of a `concatColumns` chain over one `allCoefficients` let (or the let)."""
    lets = [w for w, t in C.I.lets.items() if re.match(r'^\(MxxRuntime\.allCoefficients ', t)]
    for base in lets:
        chain, members = [], {base}
        progress = True
        while progress:
            progress = False
            for a in C.ij['atoms']:
                if a.get('loop') or not a['head'].endswith('concatColumns') or a in chain:
                    continue
                l, r, o = [xsem.wire_of(x) for x in a['args']]
                if l in members and r in members:
                    chain.append(a)
                    members.add(o)
                    progress = True
        outs = [xsem.wire_of(a['args'][2]) for a in chain]
        used = {xsem.wire_of(a['args'][i]) for a in chain for i in (0, 1)}
        roots = [o for o in outs if o not in used] or [base]
        return base, chain, roots[0]
    raise ValueError('no half row')


def smudge_half_thm(C, a, m, concl, notes):
    """`smudge_half_<field>`: `Tsm - H = reduce M`, `|M| ≤ P^d/2`, from the members' payload form."""
    try:
        mm = re.search(r'Xe \(n := \(?(\d+)\)?\) \(\(\(i : Nat\)\) / \(?(\d+)\)? % \(?(\d+)\)?\)', concl)
        nn, d, N = mm.group(1), int(mm.group(2)), mm.group(3)
        if nn != N:
            raise ValueError('the smudge does not cover every coefficient (N ≠ n)')
        k = concl.index(" * (Δ' * ν)")
        j = concl.rindex('reducePoly', 0, k)
        toks = xmodel.split_top(concl[j + len('reducePoly '):k], ' ')
        seg = ' '.join(toks[2:]).strip()
        seg = seg[1:] if seg.startswith('(') else seg  # the product's open parenthesis
        def unwrap(x):
            x = xmodel.strip_parens(x.strip())
            while True:
                parts = xmodel.split_top(x, ' : ')
                if len(parts) == 2:
                    x = xmodel.strip_parens(parts[0].strip())
                    continue
                return x
        wexpr = unwrap(seg)
        digit = re.compile(r'\(\(\(i : Nat\)\) % \(?' + str(d) + r'\)?\)')
        if not digit.search(wexpr):
            raise ValueError('weight does not depend on the digit')
        wfun = digit.sub('e', wexpr)
        w0 = digit.sub('0', wexpr)
        mp = re.search(r'\(\((\d+)\) : Int\) \^ ' + digit.pattern, wexpr)
        if mp:
            Pv = int(mp.group(1))
        else:
            lits = re.findall(r'\(\((\d+)\) : Int\)', wexpr)
            Pv = 2 * int(lits[0]) if lits else None
        if not Pv or Pv % 2:
            raise ValueError('digit base not found')
        Q = P.named(P.Seq(C, a).args, 'C')
        base, chain, H = half_wire(C)
        hval = re.match(r'^\(MxxRuntime\.allCoefficients \((.*)\) :', C.I.lets[base]).group(1)
    except (ValueError, AttributeError, KeyError, IndexError) as e:
        notes.append(f'-- {a["field"]}: smudge half not generated: {e!r}')
        return ''
    Qs = P.Seq(C, a)
    Cc, Wt = P.named(Qs.args, 'C'), Qs.pos[1]
    mouts = [xsem.wire_of(o.split()[0]) for o in m['loop']['outs']]
    q, n_, _, _ = P.elem_type(C, mouts[0])
    F = m['loop']['count']
    Pp = Pv // 2
    name = f'smudge_half_{a["field"]}'
    tsum = (f'∑ i ∈ Finset.range {Qs.count + 1}, colPlace {q} {n_} {Cc} 1 i '
            f'(∑ j ∈ Finset.range {Wt}, famAt (fun k ↦ t k 1) ({Wt} * i + j))')
    wo = wfun.replace('(e)', '(((o : Nat) % ' + str(d) + '))').replace(' e)', ' ((o : Nat) % ' + str(d) + '))')
    wo = re.sub(r'\be\b', f'((o : Nat) % {d})', wfun)
    txt = 'set_option maxHeartbeats 4000000 in\n' + (f'/-- `final_inst`\'s `hTH`: the smudge sum `Tsm` of `smudge_{a["field"]}` minus the half row `{H}` is a reduced matrix\n'
           f'with coefficients in `[-P^d/2, P^d/2)` (`P = {Pv}`, `d = {d}`), given the members\' payloads `X^(o/d mod n) w_(o mod d) (2 u_o - (P-1))`\n'
           f'(`target_payload` of `members_*` with `Δ\' ν = 2 u_o - (P-1)`, `u_o ∈ [0, P)`: the smudge PRF digits). -/\n')
    txt += P.HEAD.format(name=name, inst=C.inst).replace('[Fact (i_0 < S)]', '[h0 : Fact (i_0 < S)]')
    txt += (f'\n    {{t : Fin {F} → Fin 2 → ExactMatrix {q} {n_} 1 1}} {{u : Nat → Int}}'
            f'\n    (hu : ∀ o < {F}, 0 ≤ u o ∧ u o < ({Pv} : Int))'
            f'\n    (ht : ∀ o : Fin {F}, t o 1 = fun _ _ ↦ reducePoly {q} {n_} (Xe ((o : Nat) / {d} % {n_}) *'
            f'\n      (({wo} * (2 * u o - ({Pv} - 1)) : Int) : ErrorPoly {n_}))) :'
            f'\n    ∃ M : ErrorMatrix {n_} (1 * 1) ({Cc} * 1), CoeffBound M (({Pp} : Int) * ({Pv} : Int) ^ ({d} - 1)).toNat ∧'
            f'\n      ({tsum}) - {C.W(H)} = reduceMatrix {q} {n_} (1 * 1) ({Cc} * 1) M := by\n')
    txt += '  have hS := h0.out\n'
    txt += (f'  have h2 : 2 * ({hval} : Int) ≡ 1 [ZMOD (({q} : Nat) : Int)] := by\n    interval_cases i_0 <;> decide\n'
            f'  have hw : ∀ e < {d}, ({wfun} : Int) ≡ ({hval} : Int) * ({Pv} : Int) ^ e [ZMOD (({q} : Nat) : Int)] := by\n'
            f'    interval_cases i_0 <;> decide\n')
    txt += (f'  have hH : ∀ r p, {C.W(H)} r p = reducePoly {q} {n_} (intPoly (fun _ ↦ ({hval} : Int))) := by\n'
            f'    have e_{base} : ∀ r p, {C.W(base)} r p = reducePoly {q} {n_} (intPoly (fun _ ↦ ({hval} : Int))) :=\n'
            f'      fun r p ↦ allCoefficients_entry _ r p\n')
    for c in chain:
        l, r, o = [xsem.wire_of(x) for x in c['args']]
        txt += f'    have e_{o} := concat_const {C.I.F(c)} e_{l} e_{r}\n'
    txt += f'    exact e_{H}\n'
    txt += (f'  exact smudge_half_gen (by norm_num) (P\' := {Pp}) (h := ({hval} : Int)) (by norm_num) (by norm_num) h2 (by norm_num) (by norm_num)\n'
            f'    (w := fun e ↦ {wfun}) hw hu ht hH\n')
    C._Pp = Pp
    txt += digits_thms(C, a, concl, dict(name=name, q=q, n=n_, F=F, d=d, Pv=Pv, Pp=Pp, wo=wo, tsum_count=Qs.count + 1,
                                        Cc=Cc, Wt=Wt, H=H), notes)
    return txt


def digits_thms(C, a, concl, k, notes):
    """`smudge_digits_<f>`: every member's LUT value is a smudge digit `2 u - (P-1)` (coefficient LUT with the
    half-integer table on the PRF output `X^(s z)`; Walsh form `hC` and PRF form `hμ` from G, `hwalsh` from the
    member encodings / D's chain, `hΔ` the switch scale); `smudge_hTH_<f>`: `final_inst`'s `hTH` from the members'
    targets and these digits."""
    mt = re.search(r'Odd \((sig .*?) k\)\.toNat\)', concl) or re.search(r'Odd \((sig .*?) k\)\.toNat', concl)
    hodd_txt = None
    m = re.search(r'\(hodd : ∀ k, Odd \((sig \(\(\[.*?\]\) : List Int\) \((\d+)\)) k\)\.toNat\)', C._members_text)
    if not m:
        notes.append(f'-- {a["field"]}: smudge digits not generated (LUT keys not found)')
        return ''
    sigt, W = m.group(1), int(m.group(2))
    log = W.bit_length() - 1
    tab = [int(x) for x in re.findall(r'-?\d+', re.search(r'\[(.*?)\]', sigt).group(1))]
    n_ = int(k['n'])
    if (1 << log) != W or n_ % W:
        notes.append(f'-- {a["field"]}: LUT width {W} not a power of two dividing n')
        return ''
    res = [t % (2 * W) for t in tab]
    if any(r % 2 != 1 for r in res) or sorted((r - 1) // 2 for r in res) != list(range(W)):
        notes.append(f'-- {a["field"]}: LUT indices are not a permutation of the odd residues')
        return ''
    if all(r == 1 + 2 * i for i, r in enumerate(res)):
        perm = '(Equiv.refl _)'
    else:
        f = f'(fun i : Fin (2 ^ {log}) ↦ (⟨(({sigt} i).toNat % (2 * 2 ^ {log}) / 2) % 2 ^ {log}, Nat.mod_lt _ (by positivity)⟩ : Fin (2 ^ {log})))'
        perm = f'(Equiv.ofBijective {f} (by decide))'
    s_ = n_ // W
    q, Pp, Pv, d, F = k['q'], k['Pp'], k['Pv'], k['d'], k['F']
    name = k['name'].replace('smudge_half_', 'smudge_digits_')
    hname = k['name'].replace('smudge_half_', 'smudge_hTH_')
    U = f'halfU {Pp} (2 ^ {log}) (z o)'
    concl_d = (f'reducePoly {q} {n_} (Δ\' * ν o) = reducePoly {q} {n_} ((2 * {U} - (2 * {Pp} - 1) : Int) : ErrorPoly {n_}) ∧\n'
               f'      0 ≤ {U} ∧ {U} < 2 * {Pp}')
    txt = (f'/-- Every smudge member\'s LUT value is a smudge digit: `Δ\' ν_o ≡ 2 u_o - (P - 1)`, `u_o = halfU p\' n\' z_o ∈ [0, P)`\n'
           f'(`P = {Pv}`; the coefficient LUT `{sigt}` with the half-integer table `2 ⌊p\' k / n\'⌋ + 1`, `hC`, on the PRF output\n'
           f'`X^({s_} z_o)`, `hμ`). -/\n')
    txt += f'''theorem {name} {{i_0 : Nat}} {{μ ν : Fin {F} → ErrorPoly {n_}}} {{Δ' : ErrorPoly {n_}}}
    {{C : Fin {W} → ExactPoly {q} {n_}}} {{z : Nat → Nat}} {{inverse : Nat}}
    (hinverse : (inverse : ExactPoly {q} {n_}) * ((2 ^ {log} : Nat) : ExactPoly {q} {n_}) = 1)
    (hodd : ∀ k, Odd ({sigt} k).toNat)
    (hC : ∀ i, C i = lutFourierCoefficient (2 ^ {log}) (X {q} ^ {s_}) (inverse : ExactPoly {q} {n_})
      (fun k : Fin (2 ^ {log}) ↦ reducePoly {q} {n_} ((halfTable {Pp} (2 ^ {log}) k : Int) : ErrorPoly {n_})) ({sigt} i).toNat)
    (hμ : ∀ o, reducePoly {q} {n_} (μ o) = reducePoly {q} {n_} (Xe (n := {n_}) ({s_} * z o)))
    (hwalsh : ∀ o, ∑ k, reducePoly {q} {n_} (substitution ({sigt} k).toNat (hodd k) (μ o)) * C k = reducePoly {q} {n_} (ν o))
    (hΔ : reducePoly {q} {n_} Δ' = 1) :
    ∀ o, {concl_d} :=
  fun o ↦ smudge_digit_gen (s := {s_}) (log := {log}) rfl (by norm_num) hinverse (fun k ↦ ({sigt} k).toNat) hodd
    {perm} (by decide) hC (hμ o) (hwalsh o) hΔ (by norm_num)

'''
    wexpr = k['wo']
    tgt = (f'reducePoly {q} {n_} (Xe (n := {n_}) ((o : Nat) / {d} % {n_})) •\n'
           f'          reducePoly {q} {n_} ((({wexpr} : Int) : ErrorPoly {n_}) * (Δ\' * ν o) * unitPair sp j) •\n'
           f'          (1 : ExactMatrix {q} {n_} 1 1)')
    txt += (f'/-- `final_inst`\'s `hTH` from the smudge members\' targets (`members_*`, component 1) and their digits (`{name}`). -/\n')
    txt += P.HEAD.format(name=hname, inst=C.inst)
    txt += (f'\n    {{sp Δ\' : ErrorPoly {n_}}} {{ν : Fin {F} → ErrorPoly {n_}}} {{z : Nat → Nat}}'
            f'\n    (hdig : ∀ o : Fin {F}, {concl_d}) :'
            f'\n    ∃ M : ErrorMatrix {n_} (1 * 1) ({k["Cc"]} * 1), CoeffBound M (({Pp} : Int) * ({Pv} : Int) ^ ({d} - 1)).toNat ∧'
            f'\n      (∑ i ∈ Finset.range {k["tsum_count"]}, colPlace {q} {n_} {k["Cc"]} 1 i (∑ j ∈ Finset.range {k["Wt"]},'
            f'\n        famAt (fun (o : Fin {F}) ↦ {tgt.replace(" j)", " 1)")}) ({k["Wt"]} * i + j))) - {C.W(k["H"])} ='
            f'\n        reduceMatrix {q} {n_} (1 * 1) ({k["Cc"]} * 1) M :=\n')
    txt += (f'  {k["name"]} (t := fun (o : Fin {F}) j ↦ {tgt})\n'
            f'    (u := fun o ↦ if h : o < {F} then {U.replace("(z o)", "(z o)")} else 0) F\n'
            f'    (fun o ho ↦ by simp only [dif_pos ho]; exact ⟨(hdig ⟨o, ho⟩).2.1, (hdig ⟨o, ho⟩).2.2⟩)\n'
            f'    (fun o ↦ by\n      beta_reduce\n      rw [ht_of_digit (hdig o).1]\n      simp only [Fin.is_lt, dif_pos]; rfl)\n\n')
    return txt


def smudge_thm(C, a, m, cn):
    """`smudge_<field>`: the `c1` row of the summed smudge members in mask form."""
    Q = P.Seq(C, a)
    k = int(P.named(Q.args, 'k'))
    Cc, mm, Wt = P.named(Q.args, 'C'), P.named(Q.args, 'm'), Q.pos[1]
    if k != 6:
        raise ValueError('smudge members are not encoding tuples')
    mouts = [xsem.wire_of(o.split()[0]) for o in m['loop']['outs']]
    q, nn, _, _ = P.elem_type(C, mouts[0])
    F = m['loop']['count']
    fin = Q.final
    tup = '(' + ', '.join(f'{C.W(w)} i' for w in mouts) + ', ())'
    tsum = (f'∑ i ∈ Finset.range {Q.count + 1}, colPlace {q} {nn} {Cc} {mm} i '
            f'(∑ j ∈ Finset.range {Wt}, famAt (fun k ↦ t k 1) ({Wt} * i + j))')
    name = f'smudge_{a["field"]}'
    txt = (f'/-- The smudge row: the summed members `{m["loop"]["child"]}` (encodings `EncRel s (member i) (t i) B`,\n'
           f'from `SmudgeMember.rel`) in column loop `{Q.child}`: `c1 = maskPart s ![A01, A11] - Tsm + es`. -/\n')
    txt += P.HEAD.format(name=name, inst=C.inst)
    txt += (f'\n    {{sm : ErrorPoly {nn}}} {{t : Fin {F} → Fin 2 → ExactMatrix {q} {nn} 1 {mm}}} {{B : Nat}}'
            f'\n    (hmem : ∀ i : Fin {F}, EncRel sm {tup} (t i) B) :'
            f'\n    ∃ es : ErrorMatrix {nn} (1 * 1) ({Cc} * {mm}), CoeffBound es ({Wt} * B) ∧'
            f'\n      {C.W(fin[5])} = maskPart (reducePoly {q} {nn} sm) ![{C.W(fin[1])}, {C.W(fin[3])}] -'
            f'\n        {tsum} + reduceMatrix {q} {nn} (1 * 1) ({Cc} * {mm}) es := by\n')
    txt += '  choose e he hc using hmem\n'
    txt += f'  have hcs := {cn} F\n'
    txt += (f'  exact smudge_sum_gen (a0 := {C.W(mouts[1])}) (a1 := {C.W(mouts[3])})\n'
            f'    (c1 := {C.W(mouts[5])}) (t := fun k ↦ t k 1) (e := fun k ↦ e k 1)\n'
            f'    (fun k ↦ hc k 1) (fun k ↦ he k 1) hcs{P.conj_proj(1, 6)} hcs{P.conj_proj(3, 6)} hcs{P.conj_proj(5, 6)}\n')
    return txt


def smudge_keys_link(CO, CP, notes):
    """`smudge_keys_<f>`: the online smudge column keys (`Ks` of `hs`) are the preprocessing's
    smudge key column sums (`Ks` of `hpre`), given the member-key equality `hkeys` (D)."""
    def colsum_of(C, member_role):
        mem = [a for a in C.ij['atoms'] if a.get('loop') and a['loop']['kind'] == 'par'
               and C.roles.get(a['loop']['child'], {}).get('role') == member_role]
        for a in C.ij['atoms']:
            L = a.get('loop')
            if not L or L['kind'] != 'seq' or L['child'] not in C.sad or \
                    not C.sad[L['child']][0].startswith('ColStep.Spec '):
                continue
            fam = [xsem.wire_of(x.split()[0]) for x in L['args'] if xsem.wire_of(x.split()[0])]
            for m in mem:
                if fam == [xsem.wire_of(o.split()[0]) for o in m['loop']['outs']]:
                    return a, m
        return None, None
    ao, mo = colsum_of(CO, 'smudge.member')
    ap, mp_ = colsum_of(CP, 'smudge.key-member')
    if not ao or not ap:
        notes.append('-- smudge keys link: column loops not found')
        return []
    fo, fp = xsem.tuple_wires(ao['loop']['final']), xsem.tuple_wires(ap['loop']['final'])
    mo_out = [xsem.wire_of(o.split()[0]) for o in mo['loop']['outs']]
    mp_out = [xsem.wire_of(o.split()[0]) for o in mp_['loop']['outs']]
    F = mo['loop']['count']
    comps = [1, 3]  # the key columns `A01, A11` of the encoding order = keys `K01, K11`
    O, Pn = f'Stage_online_eval.{CO.inst}', f'Stage_preprocess.{CP.inst}'
    hk = ' ∧ '.join(f'{O}.{mo_out[c]} octx i = {Pn}.{mp_out[c]} pctx i' for c in comps)
    concl = ' ∧ '.join(f'{O}.{fo[c]} octx = {Pn}.{fp[c]} pctx' for c in comps)
    name = f'smudge_keys_{ao["field"]}'
    txt = (f'/-- The online smudge column keys (`Ks` of `smudge_{ao["field"]}`) are the preprocessing\'s smudge key\n'
           f'column sums (`Ks` of `hpre_*`), given the member-key equality `hkeys` (from the online LUT key tracking). -/\n')
    txt += f'''theorem {name} {{backend : BackendContext}} {{hashModel : HashModel}} {{i_0 : Nat}} [Fact (i_0 < S)]
    {{oparams : Stage_online_eval.Params}} {{octx : {O}.Ctx backend hashModel oparams i_0}} {{oout}}
    (FO : {O}.Facts octx oout)
    {{pparams : Stage_preprocess.Params}} {{pctx : {Pn}.Ctx backend hashModel pparams i_0}} {{pout}}
    (FP : {Pn}.Facts pctx pout)
    (hkeys : ∀ i : Fin {F}, {hk}) :
    {concl} := by
  have ho := colsum_{ao["field"]} FO
  have hp := RefreshTopProof.GenInst.PreprocessKeys.colsum_{ap["field"]} FP
'''
    pf = []
    for j, c in enumerate(comps):
        sel = '.1' if j == 0 else '.2'
        txt += f'  have h{c} : {O}.{mo_out[c]} octx = {Pn}.{mp_out[c]} pctx := funext fun i ↦ (hkeys i){sel}\n'
        pf.append(f'by rw [ho{P.conj_proj(c, 6)}, hp{P.conj_proj(c, 4)}, h{c}]')
    txt += '  exact ⟨' + ', '.join(pf) + '⟩\n'
    return [txt]


def smudge_table(CP, CO, notes):
    """`smudge_table_<f>`: the exported smudge LUT table (preprocessing key table feeding the smudge key
    members; its values `tv` from `table_*`) is the half-integer table `2 ⌊p' k / n'⌋ + 1`."""
    Pp = getattr(CO, '_Pp', None)
    if Pp is None:
        return []
    mem = [a for a in CP.ij['atoms'] if a.get('loop') and a['loop']['kind'] == 'par'
           and CP.roles.get(a['loop']['child'], {}).get('role') == 'smudge.key-member']
    if not mem:
        return []
    args = {xsem.wire_of(x.split()[0]) for x in mem[0]['loop']['args'] if xsem.wire_of(x.split()[0])}
    for a in CP.ij['atoms']:
        L = a.get('loop')
        if not L or L['kind'] != 'par' or CP.roles.get(L['child'], {}).get('role') != 'lut.key-table':
            continue
        if not {xsem.wire_of(o.split()[0]) for o in L['outs']} & args:
            continue
        try:
            txt, _ = P.emit_par(CP, a, 'table')
        except (KeyError, ValueError, IndexError) as e:
            notes.append(f'-- smudge table: {e!r}')
            return []
        k = txt.find('(tv := ')
        if k < 0:
            notes.append('-- smudge table: values not found (table not in the loop form)')
            return []
        e = xmodel.matching(txt, k)
        tv = txt[k + len('(tv := '):e].strip()
        mW = re.match(r'^\(fun \(j : Fin \(?(\d+)\)?\) ↦', tv)
        if not mW:
            return []
        W = mW.group(1)
        inst = 'i_0' in tv
        name = f'smudge_table_{a["field"]}'
        out = (f'/-- The smudge LUT table (`{L["child"]}`, the values of `table_{a["field"]}`) is the half-integer table. -/\n'
               f'theorem {name}' + (' (i_0 : Nat) [h : Fact (i_0 < S)]' if inst else '') +
               f' :\n    ∀ k : Fin {W}, {tv} k = halfTable {Pp} {W} k := by\n' +
               ('  have := h.out\n  interval_cases i_0 <;> decide\n' if inst else '  decide\n'))
        return [out]
    return []


def hint_thms(CE, CO, notes):
    """`hint_<field>` (encrypt) and `hint_online`."""
    out = []
    I = CE.I
    Mk = P.Masks(CE)
    for c, t in I.lets.items():
        h, xs = xsem.app(t)
        if h != 'matrixAdd' or len(xs) != 2:
            continue
        hm, ms = xsem.app(I.lets.get(xsem.wire_of(xs[0]) or '', ''))
        ea = I.prod.get(xsem.wire_of(xs[1]) or '')
        if hm != 'matrixMul' or not ea or not ea['head'].endswith('gaussianSample'):
            continue
        cc = I.prod.get(xsem.wire_of(ms[0]))
        if not cc or not cc['head'].endswith('concatColumns'):
            continue
        ra, rb = [I.prod.get(xsem.wire_of(x)) for x in cc['args'][:2]]
        if not ra or not rb or not ra['head'].endswith('modulusReduceRuns'):
            continue
        src = xsem.wire_of(ra['args'][0])
        if src not in CE.secrets:
            continue
        Mk.used.add(src)
        A = xsem.wire_of(ms[1])
        _, q0, nn, _, hw = xsem.mat_type(I.wires[c]['type'])
        cutoff = ea['args'][1].strip()
        Q0 = xsem.qterm(q0)
        name = f'hint_{c}'
        sname, sq, snn = CE.secrets[src]
        txt = (f'/-- The hint `{c} = [s, 1] A + e` of the encryption instance (`Gen.hint_gen`): '
               '`maskPart s (rowOf A) + eb`. -/\n')
        txt += P.HEAD.format(name=name, inst='Stage_encrypt.' + CE.inst) + Mk.binders()
        txt += (f' :\n    ∃ eb : ErrorMatrix {nn} 1 {hw}, CoeffBound eb (({cutoff} : Int)).toNat ∧\n'
                f'      {W(CE, c)} = maskPart (reducePoly {Q0} {nn} {sname}) (fun k ↦ rowOf {W(CE, A)} k) +\n'
                f'        reduceMatrix {Q0} {nn} 1 {hw} eb :=\n')
        gt = xsem.Certs('Stage_encrypt').gt(q0)
        txt += (f'  Gen.hint_gen (by decide) {gt} (by decide) h_{src} rfl {I.F(ra)} {I.F(rb)} {I.F(cc)} {I.F(ea)}\n')
        out.append(txt)
        # the online hint input: left factor of an input × input product of the same width
        for oc, ot in CO.I.lets.items():
            oh, oxs = xsem.app(ot)
            if oh != 'matrixMul':
                continue
            l, r = xsem.wire_of(oxs[0]), xsem.wire_of(oxs[1])
            if not l or not r or CO.ij['wires'].get(l, {}).get('src') != 'input' or \
                    CO.ij['wires'].get(r, {}).get('src') != 'input':
                continue
            _, oq, onn, _, ohw = xsem.mat_type(CO.ij['wires'][l]['type'])
            if ohw != hw:
                continue
            OQ = xsem.qterm(oq)
            txt = (f'/-- The online hint input `{l}` (factor of `{oc} = {l} * {r}`), carried from the encryption\'s '
                   f'`{c}` by the stage link `hlink`. -/\n')
            txt += f'''theorem hint_online {{backend : BackendContext}} {{hashModel : HashModel}} {{i_0 : Nat}}
    [Fact (i_0 < S)] {{eparams : Stage_encrypt.Params}} {{ectx : Stage_encrypt.{CE.inst}.Ctx backend hashModel eparams i_0}}
    {{eout}} (FE : Stage_encrypt.{CE.inst}.Facts ectx eout)
    {{oparams : Stage_online_eval.Params}} {{octx : Stage_online_eval.{CO.inst}.Ctx backend hashModel oparams i_0}}''' + \
                Mk.binders().replace('ctx', 'ectx').replace(f'{CE.inst}.', f'Stage_encrypt.{CE.inst}.') + f'''
    (hlink : Stage_online_eval.{CO.inst}.{l} octx = Stage_encrypt.{CE.inst}.{c} ectx) :
    ∃ eb : ErrorMatrix {onn} 1 {ohw}, CoeffBound eb (({cutoff} : Int)).toNat ∧
      Stage_online_eval.{CO.inst}.{l} octx = maskPart (reducePoly {OQ} {onn} {sname})
        (fun k ↦ rowOf (Stage_encrypt.{CE.inst}.{A} ectx) k) + reduceMatrix {OQ} {onn} 1 {ohw} eb := by
  rw [hlink]
  exact {name} FE {Mk.args()}
'''
            out.append(txt)
            break
    if not out:
        notes.append('-- no encryption hint recognized')
    return out


def W(C, w):
    return C.W(w)


def hpre_thms(CP, notes):
    """`hpre_<field>`: the preprocessing target with its combination keys split, at given D, Y, P, A."""
    out = []
    finals = {}
    tgt = [a for a in CP.ij['atoms'] if not a.get('loop') and a['head'].endswith('preimageRunsDispatched')]
    txts = P.emit_target(CP)
    names = [n for _, n in txts]
    for a in tgt:
        tname = f'target_{a["field"]}'
        if tname not in names:
            continue
        A, T, tg, cut, Pw = [xsem.wire_of(x.strip()) if xsem.wire_of(x.strip()) else x for x in a['args'][1:]]
        cat = CP.I.prod.get(tg)
        rows = [xsem.wire_of(x) for x in cat['args'][:2]]
        leaves = [P.flatten_add(CP, r) for r in rows]
        combs = []
        for lv in leaves:
            w = lv[0]
            h, xs = xsem.app(CP.I.lets.get(w, ''))
            x, y = xsem.wire_of(xs[0]), xsem.wire_of(xs[1])
            _, xx = xsem.app(CP.I.lets.get(x, ''))
            _, yy = xsem.app(CP.I.lets.get(y, ''))
            gc, D = xsem.wire_of(xx[0]), xsem.wire_of(xx[1])
            cc = CP.I.prod.get(gc)
            g, c1 = xsem.wire_of(cc['args'][0]), xsem.wire_of(cc['args'][1])
            Kx, Y = xsem.wire_of(yy[0]), xsem.wire_of(yy[1])
            combs.append(dict(w=w, g=g, c1=c1, D=D, Kx=Kx, Y=Y))
        if len({c['D'] for c in combs}) != 1 or len({c['Y'] for c in combs}) != 1:
            notes.append('-- hpre: rows use different decompositions')
            continue
        D, Y = combs[0]['D'], combs[0]['Y']
        vec = lambda ws: '![' + ', '.join(CP.W(w) for w in ws) + ']'
        tyD = CP.ij['wires'][D]['type']
        tyY = CP.ij['wires'][Y]['type']
        tyP = CP.ij['wires'][Pw]['type']
        tyA = CP.ij['wires'][A]['type']
        name = f'hpre_{a["field"]}'
        txt = ('/-- `final_inst`\'s `hpre` from the preprocessing (`target_*`, `comb_*`) at a decomposition `D`, action '
               'digits `Y`, preimage `P` and public matrix `A` equal to the preprocessing ones. -/\n')
        txt += P.HEAD.format(name=name, inst='Stage_preprocess.' + CP.inst)
        txt += (f'\n    {{D : {qual(tyD)}}} {{Y : {qual(tyY)}}} {{Pm : {qual(tyP)}}} {{A : {qual(tyA)}}}'
                f'\n    (hD : D = {pw(CP, D)}) (hY : Y = {pw(CP, Y)}) (hP : Pm = {pw(CP, Pw)}) (hA : A = {pw(CP, A)}) :'
                f'\n    ∀ k : Fin 2, rowOf A k * Pm ='
                f'\n      ({pvec(CP, [c["g"] for c in combs])} k * topRows D + {pvec(CP, [c["c1"] for c in combs])} k * bottomRows D -'
                f'\n        {pvec(CP, [c["Kx"] for c in combs])} k * Y) + {pvec(CP, [l[1] for l in leaves])} k + {pvec(CP, [l[2] for l in leaves])} k := by\n')
        txt += '  subst hD hY hP hA\n  intro k\n'
        txt += f'  rw [RefreshTopProof.GenInst.PreprocessKeys.{tname} F k]\n'
        txt += '  refine Fin.cases ?_ (fun j ↦ ?_) k\n'
        txt += f'  · show {pw(CP, combs[0]["w"])} + _ + _ = _\n    rw [RefreshTopProof.GenInst.PreprocessKeys.comb_{combs[0]["w"]} F]; rfl\n'
        txt += (f'  · rw [Fin.fin_one_eq_zero j]\n    show {pw(CP, combs[1]["w"])} + _ + _ = _\n'
                f'    rw [RefreshTopProof.GenInst.PreprocessKeys.comb_{combs[1]["w"]} F]; rfl\n')
        out.append(txt)
    return out


def qual(ty):
    """Qualify the stage abbreviations of a preprocessing wire type."""
    return re.sub(r'(?<![\w.])(mod_\d+|modulus_\d+|sel_\d+)\b', r'Stage_preprocess.\1', ty)


def pw(C, w):
    return f'(Stage_preprocess.{C.inst}.{w} ctx)'


def pvec(C, ws):
    return '![' + ', '.join(pw(C, w) for w in ws) + ']'


