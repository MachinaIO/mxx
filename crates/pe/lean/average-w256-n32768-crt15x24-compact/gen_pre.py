def fact_fields(scope):
    source = reference_facts('pre')
    result = {}
    for match in re.finditer(r'structure ' + scope + r'\.Facts_(\d+) .*? where\n(.*?)(?=\ntheorem)', source, re.S):
        for line in match[2].splitlines():
            field = re.match(r'  (h\w+) : (.*)', line)
            if field:
                result[field[1]] = ('F.c' + match[1] + '.' + field[1], field[2])
    return result


