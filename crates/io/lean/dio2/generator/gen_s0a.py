def preprocessing_tables(module):
    roots = [root for root in module.root.loops
             if len(root.loop.args) == 3 and len(root.loop.outs) == 4
             and any(atom.kind == 'ringAutomorphismRuns'
                     for atom in module.scopes[root.loop.child].atoms)]
    meta.require(len(roots) >= 6, 'encrypted preprocessing table families')
    result = list(zip(['state', 'smudge', 'sigmaReadout', 'readout'], roots[:4]))
    samplers = [root for root in roots[4:] if root.loop.count > 1]
    meta.require(len(samplers) == 2, 'two coefficient sampler tables')
    result.extend(zip(['sigmaSampler', 'sampler'], samplers))
    for root in roots[4:]:
        if root.loop.count != 1:
            continue
        scope = module.scopes[root.loop.child]
        expression = meta.one((atom.args[0] for atom in scope.atoms
                               if atom.kind == 'ringAutomorphismRuns'), 'single automorphism')
        values = re.search(r'\[([^\]]+)\]', expression)
        meta.require(values is not None, 'automorphism values')
        sigma = meta.one(re.findall(r'-?\d+', values[1]), 'singleton automorphism')
        result.append(('aut' + sigma, root))
    meta.require(len(set(label for label, _ in result)) == len(result),
                 'unique preprocessing table roles')
    return result


