#!/usr/bin/env python3
"""LwrEncryptE.lean: the encryption stage with its errors named.

Usage: gen_encrypt_e.py <parameter dir>

Rewrites the set's own `LwrEncrypt.lean`: every `Rel _ _ _ _ 26` conclusion becomes `RelE` with the
named error (the clamped Gaussian tape samples), and every `gaussian_bound_at` becomes the explicit
sample.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from info import Info  # noqa: E402


def module(I):
    src = open(os.path.join(I.d, 'LwrEncrypt.lean')).read()
    B, L, M, W = I.B, I.L, I.M, I.W
    cut = I.cutoff
    mL, mL1, m1 = I.m(L), I.m(L - 1), I.m(1)
    # The member loop is the first parallel loop; the helper loop is the one whose outputs are at `Q2`
    # (as in `gen_encrypt`).
    enc = I.enc
    loops = [x for x in range(36, 36 + B + 1)
             if re.search(rf'def parallel_generatedRoot_{x} .*\(outputs : Mxx\.Primitives\.ExactMatrix {I.Q[2]} ', enc)]
    member_loop, helper_loop = 35, loops[0]
    body = src[src.index('set_option maxHeartbeats', src.index('variable {tape')):src.rindex('end LwrProof')]
    thms = re.split(r'(?=set_option maxHeartbeats \d+ in\n(?:set_option [^\n]*\n)*/-- )', body)
    thms = [t for t in thms if t.strip()]
    cw = lambda site: (f'clampedWitness tape ({site}) (.gaussian (4/1) {cut}) (-(({cut} : Nat) : Int)) '
                       f'(({cut} : Nat) : Int)')
    out = [f'''import LwrEncrypt
import ExponentErrorForm
import ExponentFunctional

/-!
# The encryption stage with its errors named

Generated by `generator/gen_encrypt_e.py`. The errors of the state, of every member of `a`, and of
every LUT helper are the Gaussian tape samples of the encryption stage.
-/

namespace LwrProof

open Mxx.Primitives MxxRuntime MxxExponentLut

set_option maxRecDepth 100000

variable {{tape : SampleTape}} {{path : List Nat}}

/-- The state error: the samples at `path ++ [20]` and `path ++ [31]`. -/
noncomputable def stateError (tape : SampleTape) (path : List Nat) : Fin 2 → ErrorMatrix N 1 {mL1} :=
  ![{cw('path ++ [20]')},
    {cw('path ++ [31]')}]

/-- The error of member `i` of `a`. -/
noncomputable def memberError (tape : SampleTape) (path : List Nat) (i : Fin {M}) :
    Fin 2 → ErrorMatrix N 1 {mL} :=
  ![{cw(f'path ++ [{member_loop}, i.val] ++ [16]')},
    {cw(f'path ++ [{member_loop}, i.val] ++ [25]')}]

/-- The error of LUT helper `i`. -/
noncomputable def helperError (tape : SampleTape) (path : List Nat) (i : Fin {W}) :
    Fin 2 → ErrorMatrix N 1 {m1} :=
  ![{cw(f'path ++ [{helper_loop}, i.val] ++ [18]')},
    {cw(f'path ++ [{helper_loop}, i.val] ++ [29]')}]
''']
    errs = {'encrypt_state': 'stateError tape path', 'encrypt_member': 'memberError tape path i',
            'encrypt_helper': 'helperError tape path i'}
    for t in thms:
        name = re.search(r'theorem (\w+)', t).group(1)
        if name not in errs:
            continue
        err = errs[name]
        t = t.replace(f'theorem {name} ', f'theorem {name}E ', 1)
        t = re.sub(r'/-- [^\n]*?(?:\n[^\n]*?)*?-/', f'/-- `{name}` with its error named. -/', t, count=1)
        t = t.replace('    Rel sm ', '    RelE sm ', 1)
        t = re.sub(rf'\] {cut} (:= by|∧)', rf'] ({err}) \1', t, count=1)
        t = re.sub(r'  obtain ⟨e(\d), hb(\d), he(\d)⟩ := gaussian_bound_at hN (h\d+)\n',
                   lambda mm: (f'  obtain ⟨hb{mm.group(2)}, he{mm.group(3)}⟩ := gaussianSampleAt_explicit hN '
                               f'{mm.group(4)}\n  rw [← clampedWitness_eq_of_bound hN (c := {cut}) he{mm.group(3)}] '
                               f'at hb{mm.group(2)}\n'), t)
        t = t.replace('refine ⟨⟨![e0, e1], fun j ↦ by fin_cases j <;> assumption, fun j ↦ ?_⟩, ?_⟩',
                      'refine ⟨fun j ↦ ?_, ?_⟩')
        t = t.replace('refine ⟨![e0, e1], fun j ↦ by fin_cases j <;> assumption, fun j ↦ ?_⟩', 'intro j')
        # The named error unfolds in the closing simp sets.
        short = err.split(' ')[0]
        t = re.sub(r'(simp (?:only )?\[[^\]]*?)(\])', lambda mm: mm.group(1) + f', {short}' + mm.group(2)
                   if 'hb0' in mm.group(1) else mm.group(0), t)
        assert 'gaussian_bound_at' not in t and 'e0, e1' not in t, name
        out.append(t)
    out.append('end LwrProof\n')
    return '\n'.join(out)


def main():
    d = sys.argv[1]
    I = Info(d)
    path = os.path.join(d, 'LwrEncryptE.lean')
    with open(path, 'w') as f:
        f.write(module(I))
    print('wrote', path)


if __name__ == '__main__':
    main()
