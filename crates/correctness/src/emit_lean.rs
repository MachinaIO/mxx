pub const GENERATOR_VERSION: &str = "mxx-correctness-emitter-v4";

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct EmittedProtocol {
    pub protocol_hash: String,
    pub ir: String,
    /// Application-specific semantic certificate module, when the protocol
    /// carries a specialized certificate understood by its owning Lean package.
    pub certificate: Option<String>,
    pub statement: String,
    pub proof_scaffold: String,
}

#[derive(Debug, Error)]
pub enum EmitError {
    #[error(transparent)]
    Protocol(#[from] ProtocolError),
    #[error("protocol serialization failed: {0}")]
    Serialization(#[from] serde_json::Error),
    #[error("Lean denotation is not implemented for Graph IR node {0}")]
    UnsupportedNode(&'static str),
    #[error("Lean parameter validation cannot evaluate irrational expression {0}")]
    IrrationalConstraint(String),
    #[error("Lean denotation does not yet support child Graph IR scopes")]
    ChildScope,
    #[error("Lean denotation is not implemented for Graph IR wire type {0}")]
    UnsupportedWireType(&'static str),
}

pub fn emit_protocol_for(
    name: &str,
    protocol: &ProtocolDecl,
    module_root: &str,
) -> Result<EmittedProtocol, EmitError> {
    protocol.validate()?;
    ensure_supported_wire_types(protocol)?;
    let normalized = normalized_protocol(protocol)?;
    let canonical = serde_json::to_vec(&normalized)?;
    let protocol_hash = format!("{:x}", Sha256::digest(&canonical));
    let lean_name = lean_identifier(name);
    let executable = lean_workflow(&lean_name, protocol)?;
    let ir = format!(
        "-- Generated by {GENERATOR_VERSION}; do not edit.\nimport Mxx.Ir\n\nnamespace {module_root}.Generated.{lean_name}\n\ndef {lean_name}_protocolHash : String := \"{protocol_hash}\"\n\n{executable}\nend {module_root}.Generated.{lean_name}\n"
    );
    let certificate = lean_semantic_certificate(protocol, module_root, &lean_name);
    let params = protocol
        .params
        .iter()
        .map(|parameter| {
            let ty = match parameter.kind {
                crate::ParameterKind::Dimension => "Nat",
                crate::ParameterKind::Integer => "Int",
                crate::ParameterKind::Rational => "Rat",
            };
            format!("  {} : {ty}", lean_field_identifier(&parameter.name))
        })
        .collect::<Vec<_>>()
        .join("\n");
    let inputs = protocol
        .correctness
        .protocol_inputs
        .iter()
        .map(|(name, destinations)| -> Result<_, EmitError> {
            let (stage, input) = destinations.first().expect("validated nonempty input mapping");
            let stage = protocol.stages.iter().find(|candidate| &candidate.id == stage).unwrap();
            let wire_type = stage
                .graph
                .root_scope()
                .nodes()
                .iter()
                .find_map(|node| match node.kind() {
                    NodeKind::Input { name, .. } if name == &input.0 => {
                        Some(&node.output_types()[0])
                    }
                    _ => None,
                })
                .expect("validated stage input");
            Ok(format!("  {} : {}", lean_field_identifier(&name.0), lean_wire_type(wire_type)?))
        })
        .collect::<Result<Vec<_>, _>>()?
        .join("\n");
    let mut constrained_graphs =
        protocol.stages.iter().map(|stage| &stage.graph).collect::<Vec<_>>();
    constrained_graphs.push(&protocol.correctness.ideal.graph);
    constrained_graphs
        .extend(protocol.correctness.requires.iter().map(|requirement| &requirement.graph));
    if let Comparator::EqualAfterMap { map } = &protocol.correctness.comparator {
        constrained_graphs.push(&map.graph);
    }
    let constraints = constrained_graphs
        .into_iter()
        .flat_map(|graph| {
            derive_param_constraints(graph)
                .expect("validated protocol graph has derivable parameter constraints")
        })
        .map(|constraint| lean_constraint(&constraint, protocol))
        .collect::<Result<BTreeSet<_>, _>>()?
        .into_iter()
        .collect::<Vec<_>>();
    let params_valid =
        if constraints.is_empty() { "true".to_owned() } else { constraints.join(" &&\n    ") };
    let semantics = lean_correctness_semantics(protocol, &lean_name, module_root);
    let application_import = match &protocol.semantic_certificate {
        SemanticCertificate::None => String::new(),
        SemanticCertificate::Diamond(_) => {
            format!("import {module_root}.GenericBooleanLayers\n")
        }
    };
    let statement = format!(
        "-- Generated by {GENERATOR_VERSION}; do not edit.\nimport {module_root}.Generated.{lean_name}.Ir\nimport Mxx.Correctness\n{application_import}\nset_option linter.unusedVariables false\n\nopen Mxx\n\nnamespace {module_root}.Generated.{lean_name}\n\nstructure {lean_name}Params where\n{params}\n\nstructure {lean_name}Inputs (_p : {lean_name}Params) where\n{inputs}\n\ndef {lean_name}ParamsValid (p : {lean_name}Params) : Bool :=\n  {params_valid}\n\n{semantics}\n\nstructure {lean_name}CorrectStatement (checker : {lean_name}Params → Bool) : Prop where\n  accepts_valid_parameters :\n    ∃ p : {lean_name}Params, checker p = true ∧ {lean_name}ParamsValid p = true\n  probability_zero :\n    ∀ samplers : MxxSamplerFamily, MxxBoundedSamplerContract samplers →\n    ∀ p : {lean_name}Params, checker p = true → {lean_name}ParamsValid p = true →\n    ∀ x : {lean_name}Inputs p, {lean_name}InputsWF p x → {lean_name}Preconditions p x →\n      {lean_name}FailureProbability samplers p x = 0\n\nend {module_root}.Generated.{lean_name}\n"
    );
    let lower = lower_identifier(name);
    let proof_scaffold = format!(
        "import {module_root}.Generated.{lean_name}.Statement\n\nopen {module_root}.Generated.{lean_name}\n\n-- Define `{lower}Checker` and prove `{lower}_correct` in this owning crate.\n-- The proof must construct both `accepts_valid_parameters` and `probability_zero`;\n-- no default checker or vacuous proof is generated.\n"
    );
    Ok(EmittedProtocol { protocol_hash, ir, certificate, statement, proof_scaffold })
}

fn lean_semantic_certificate(
    protocol: &ProtocolDecl,
    module_root: &str,
    lean_name: &str,
) -> Option<String> {
    let SemanticCertificate::Diamond(certificate) = &protocol.semantic_certificate else {
        return None;
    };
    Some(format!(
        "-- Generated by {GENERATOR_VERSION}; do not edit.\n\
         import {module_root}.Generated.{lean_name}.Ir\n\
         import {module_root}.Certificate.Syntax\n\n\
         namespace {module_root}.Generated.{lean_name}\n\n\
         def {lean_name}_certificate : {module_root}.Certificate.DiamondCertificate :=\n\
         {}\n\n\
         end {module_root}.Generated.{lean_name}\n",
        indent_lean(&lean_diamond_certificate(protocol, certificate), 2)
    ))
}

fn lean_diamond_certificate(
    protocol: &ProtocolDecl,
    certificate: &certificate::DiamondCertificate,
) -> String {
    lean_record([
        ("workflow", lean_diamond_workflow(&certificate.workflow)),
        ("message", lean_message_construction(&certificate.message)),
        ("publicKeySampling", lean_public_key_sampling(&certificate.public_key_sampling)),
        (
            "encryptionInitialPublicKeys",
            lean_encryption_initial_public_keys(&certificate.encryption_initial_public_keys),
        ),
        ("inputPreprocessing", lean_input_preprocessing(&certificate.input_preprocessing)),
        ("artifactPreprocessing", lean_artifact_preprocessing(&certificate.artifact_preprocessing)),
        ("inputInjection", lean_input_injection(protocol, &certificate.input_injection)),
        (
            "decryptionInitialEncodings",
            lean_decryption_initial_encodings(&certificate.decryption_initial_encodings),
        ),
        ("booleanLayers", lean_boolean_layers(protocol, &certificate.boolean_layers)),
        ("decoder", lean_decoder(protocol, &certificate.decoder)),
    ])
}

