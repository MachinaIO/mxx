def initial_tuples(module, loop_atom):
    initial = meta.flat_tuple(loop_atom.loop.init)
    terms = [meta.xmodel.app_split(module.root.wires[value].term)[1] for value in initial]
    return [lean_tuple([f"(generatedRoot.{term[index]} ctx)" for term in terms])
            for index in range(2)]


def qualify_witness(scope, text):
    if scope.kind != "record":
        return text
    statement, proof = text.split(":= by\n", 1)
    fields = {wire for wire, _ in scope.witness}
    proof = re.sub(r"(?<![.\w])(w_\d+(?:_\d+)?(?:_concat_\d+)?)\b",
                   lambda match: "wit." + match[1] if match[1] in fields else match[1], proof)
    return statement + ":= by\n" + proof


def runtime_adapters(package):
    roles = {"gather.unpack", "sum.members.step", "sum.members.step1", "prf.rowsum",
             "sum.columns.step"}
    text, done, _, failed = adapters.gen_module(package / "worst", "W_Stage_online_0", roles)
    meta.require(not failed, f"Runtime adapter generation failed: {failed}")
    text = re.sub(r"^import .*\n", "", text, flags=re.M)
    for scope, _ in sorted(done, key=lambda item: -len(item[0])):
        text = text.replace(scope + ".sem", scope + ".g2_sem")
    return text


def placement_from_scope(scope):
    binders, call, _ = adapters.header(scope)
    per, atoms = adapters.atom_names(scope)
    gets = [(name, meta.xmodel.app_split(atom)[1]) for name, atom in atoms
            if atom.startswith("MxxRuntime.familyGetDynamic ")]
    meta.require(len(gets) == 6 and len(scope.inputs) == 6 and len(scope.output) == 6,
                 f"Unsupported fused gather: {scope.name}")
    indices = {args[1] for _, args in gets}
    meta.require(len(indices) == 1, f"Distinct gather indices: {scope.name}")
    index = adapters.wire_term(scope, indices.pop())
    q, n, rows, columns = meta.dims(scope.output[0])
    meta.require(rows == 1, "Fused placement row count")
    count = meta.family_count(scope.inputs[0])
    gathered = lean_tuple([args[2] for _, args in gets])
    output_name = meta.one((name for name, atom in atoms if atom.startswith("outputs = ")),
                           "fused placement output equation")
    text = f'''/-- The exported fused gather/monomial placement, without family enumeration. -/
theorem {scope.name}.placement_rel {binders}
    (h : {call}) {{sm : ErrorPoly {n}}}
    {{target : Fin {count} → Fin 2 → ExactMatrix {q} {n} 1 {columns}}} {{budget : Nat}}
    (hmember : ∀ member, EncRel sm (Tup.ev inputs member) (target member) budget) :
    ∃ member : Fin {count}, EncRel sm outputs
      (fun port ↦ reducePoly {q} {n} (Xe (n := {n}) (i_0 % {n})) • target member port) budget := by
  obtain {adapters.pattern(scope, per, witness=scope.kind == 'record')} := h
  apply gather_monomial_place_rel (by norm_num : 1 < {n})
    (families := inputs) (gathered := {gathered})
    (index := {index}) (exponent := i_0 % {n}) (by omega)
  · apply GatherUnpack.sem (by omega) (by omega)
    intro component
    fin_cases component
    exacts [{', '.join(name for name, _ in gets)}]
  · intro component
    rw [{output_name}]
    have hexponent : Int.fmod (Int.ofNat i_0) ({n} : Int) = ((i_0 % {n} : Nat) : Int) :=
      fmod_ofNat i_0 {n}
    fin_cases component <;> rw [hexponent] <;> rfl
  · exact hmember

'''
    return qualify_witness(scope, text)


def buckets_from_graph(module, view):
    text = ""
    for role, prf in view["prfs"].items():
        for bucket, block in enumerate(prf["block_scopes"]):
            scope = module.scopes[block["scope"]]
            binders, call, _ = adapters.header(scope)
            q, n, _, columns = meta.dims(scope.output[0])
            members, width = prf["members"], block["bucket_width"]
            meta.require(meta.family_count(scope.inputs[0]) == members * width,
                         "PRF cell family differs from bucket metadata")
            text += f'''/-- The actual {role} bucket-{bucket} row sum retains every cell error. -/
theorem {scope.name}.bucket_sum {binders}
    (h : {call}) {{sm : ErrorPoly {n}}}
    {{target : Fin ({members} * {width}) → Fin 2 → ExactMatrix {q} {n} 1 {columns}}}
    {{budget : Nat}}
    (hcell : ∀ cell, EncRel sm (Tup.ev inputs cell) (target cell) budget)
    (hmember : i_0 < {members}) :
    EncRel sm outputs
      (∑ column : Fin {width}, target (cellAt (⟨i_0, hmember⟩ : Fin {members}) column))
      ({width} * budget) := by
  exact online0_bucket_sum ⟨i_0, hmember⟩ ({scope.name}.g2_sem h) hcell

'''
    return text


def member_total_from_graph(module, prf):
    count = prf["members"]
    root = module.root
    loop_atom = meta.one((atom for atom in root.loops if atom.loop.kind == "seq"
                          and atom.loop.count == count - 2 and len(atom.loop.args) == 12
                          and meta.family_count(root.wires[atom.loop.args[-1]].type) == count),
                         "sigma member total")
    families, initial, reads0, reads1 = sum_inputs(module, loop_atom)
    q, n, _, columns = meta.dims(root.wires[families[0]].type)
    final = meta.flat_tuple(loop_atom.loop.final)
    header, fams, output = root_total_header("online0_sigma_total_graph", n, q, columns,
                                            families, count, final)
    first, second = initial_tuples(module, loop_atom)
    theorem = header + f''':
    EncRel sm {output} (∑ member, target member) ({count} * budget) := by
  exact member_total_rel (by norm_num : 2 ≤ {count})
    (fams := {fams})
    (a := {first}) (b := {second})
    (fun component ↦ by fin_cases component; exacts [{', '.join(reads0)}])
    (fun component ↦ by fin_cases component; exacts [{', '.join(reads1)}])
    (fun component ↦ by fin_cases component <;> rfl)
    {root_fact(root, loop_atom, final[-1])}
    (fun index current next hbody ↦ {loop_atom.loop.child}.g2_sem hbody)
    hmember

'''
    return theorem


def columns_from_graph(module, prf, name, width):
    count, packed = prf["members"], prf["packed_members"]
    root = module.root
    loop_atom = meta.one((atom for atom in root.loops if atom.loop.kind == "seq"
                          and atom.loop.count == packed - 1 and len(atom.loop.args) == 12
                          and meta.family_count(root.wires[atom.loop.args[-1]].type) == count),
                         "packed column loop")
    families = loop_atom.loop.args[-6:]
    init = meta.flat_tuple(loop_atom.loop.init)
    tensors = [meta.one((atom for atom in root.atoms if atom.kind == "tensorRuns"
                        and atom.args[-1] == value), "column initializer tensor") for value in init]
    prefix_final = [atom.args[1] for atom in tensors]
    prefix = meta.one((atom for atom in root.loops if atom.loop.kind == "seq"
                      and meta.flat_tuple(atom.loop.final) == prefix_final), "column zero member sum")
    prefix_families, _, reads0, reads1 = sum_inputs(module, prefix)
    meta.require(prefix_families == families and prefix.loop.count == width - 2,
                 "Column prefix differs from packing width")
    q, n, _, columns = meta.dims(root.wires[families[0]].type)
    final = meta.flat_tuple(loop_atom.loop.final)
    header, fams, output = root_total_header(name, n, q, columns, families, count, final,
                                            f"(column : Fin {packed})")
    first, second = initial_tuples(module, prefix)
    initial = lean_tuple([f"(generatedRoot.{value} ctx)" for value in init])
    column_zero = lean_tuple([f"(generatedRoot.{value} ctx)" for value in prefix_final])
    step_inputs = lean_tuple(["current." + "2." * index + "1" for index in range(6)] +
                             [f"(generatedRoot.{value} ctx)" for value in families])
    theorem = header + f''' :
    EncRel sm (blkT (C := {packed}) (m := {columns}) {output} column)
      (∑ coefficient : Fin {width}, target
        ⟨{width} * column + coefficient, by have := column.isLt; have := coefficient.isLt; omega⟩)
      ({width} * budget) := by
  have hprefix := member_prefix (α := ExactMatrix {q} {n} 1 {columns})
    (k := 6) (F := {count}) (Wm := {width}) (by norm_num) (by norm_num)
    (fams := {fams})
    (a := {first}) (b := {second})
    (fun component ↦ by fin_cases component; exacts [{', '.join(reads0)}])
    (fun component ↦ by fin_cases component; exacts [{', '.join(reads1)}])
    (fun component ↦ by fin_cases component <;> rfl)
    {root_fact(root, prefix, prefix_final[-1])}
    (fun index current next hbody ↦ {prefix.loop.child}.g2_sem hbody)
  exact column_total_rel (C := {packed}) (m := {columns}) (W := {width}) (F := {count})
    (fams := {fams}) (init := {initial}) (final := {output}) (x0 := {column_zero})
    (t := target) (B := budget)
    (by norm_num) (by norm_num) hprefix
    (fun component ↦ by fin_cases component; exacts [{', '.join(root_fact(root, atom, atom.args[-1]) for atom in tensors)}])
    {root_fact(root, loop_atom, final[-1])}
    (fun index current next hbody ↦ {loop_atom.loop.child}.g2_sem
      (inputs := {step_inputs}) (outputs := next) hbody)
    hmember column

'''
    return theorem


