#!/usr/bin/env python3
"""Generate the instance theorems `Gen_Inst_<Stage>.lean` (L3, WP D) of a refresh_top export.

For a merged stage `Stage_X`, the root runs `∀ i : Fin S, I … i …` over the instance body `I`
(`parallel_generatedRoot_K`). This generator reads the facts module (`Stage_X_Facts.lean`: the
fragment records `I.Facts_k` and their fields) and the role assignment (`xroles.py`), and writes,
for the symbolic instance `i_0`, a theorem over the instance's facts record that derives the role
fact of every child loop of the instance body:

* `par` loops: `fun i ↦ C.sem (F.c<k>.<field> i)` (the child's adapter, `Gen_Stage_X_Scopes`);
* `gather` loops (six gathered families): `Gen.gather_loop6` and then the child's adapter, giving
  `∃ k, ↑k = t i ∧ <role fact of member k>`;
* `seq` loops: `GenInst.steps_of` turns the `IterRuns` of the child scope into the `IterRuns` of
  the child's role step (its adapter), never unrolled.

Each step is a `node_have` (ModularGlue): its own auxiliary theorem. Children are recognized by
their role (roles.json / xroles), never by wire ids or scope numbers.

Usage: gen_instance.py <generated dir> <out dir> Stage_X…
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
import xmodel  # noqa: E402
import xroles  # noqa: E402
import xsem  # noqa: E402
import xchain  # noqa: E402

PRELUDE = '''import {module}_Facts
import Gen_{module}_Scopes
import Gen_InstCerts
import GenRel
import GenBridge_Enc
import GenBridge_Prf
import GenBridge_Lut
import GenInstLemmas
import ModularGlue

/-! Generated by `generator/gen_instance.py`: the role facts of the child loops of `{module}`'s
instance body `{inst}` at a symbolic instance (see `GenIface`, `Gen_{module}_Scopes`). -/

set_option maxHeartbeats 4000000
set_option maxRecDepth 16384
set_option linter.unusedVariables false

namespace RefreshTopProof.GenInst

/-- The steps of an iteration satisfy `P` when every body step does. -/
theorem steps_of {{σ : Type}} {{body : Nat → σ → σ → Prop}} {{count : Nat}} {{init final : σ}}
    (h : MxxIR.IterRuns body count init final) {{P : Nat → σ → σ → Prop}}
    (hs : ∀ i cur next, body i cur next → P i cur next) : MxxIR.IterRuns P count init final :=
  RefreshTopProof.GenIface.seq_forall P hs h

/-- A six-family Gather loop whose child relation `P` implies `Q`: every iteration's `Q` holds at
the table entry's members. -/
theorem gather_sem {{α : Type}} {{F K : Nat}} {{f0 f1 f2 f3 f4 f5 : Fin K → α}} {{t : Fin F → Int}}
    (P : Fin F → Int → α → α → α → α → α → α → Prop)
    (h : ∀ i : Fin F, ∃ x0 x1 x2 x3 x4 x5 : α,
      0 ≤ t i ∧ t i < K ∧ MxxRuntime.familyGetDynamic f0 (t i) x0 ∧
      0 ≤ t i ∧ t i < K ∧ MxxRuntime.familyGetDynamic f1 (t i) x1 ∧
      0 ≤ t i ∧ t i < K ∧ MxxRuntime.familyGetDynamic f2 (t i) x2 ∧
      0 ≤ t i ∧ t i < K ∧ MxxRuntime.familyGetDynamic f3 (t i) x3 ∧
      0 ≤ t i ∧ t i < K ∧ MxxRuntime.familyGetDynamic f4 (t i) x4 ∧
      0 ≤ t i ∧ t i < K ∧ MxxRuntime.familyGetDynamic f5 (t i) x5 ∧
      P i (t i) x0 x1 x2 x3 x4 x5)
    {{Q : Fin F → Int → α → α → α → α → α → α → Prop}}
    (hs : ∀ i ti x0 x1 x2 x3 x4 x5, P i ti x0 x1 x2 x3 x4 x5 → Q i ti x0 x1 x2 x3 x4 x5)
    (i : Fin F) : ∃ k : Fin K, ((k : Nat) : Int) = t i ∧ Q i (t i) (f0 k) (f1 k) (f2 k) (f3 k) (f4 k) (f5 k) :=
  (Gen.gather_loop6 P h i).imp fun _ hk ↦ ⟨hk.1, hs _ _ _ _ _ _ _ _ hk.2⟩

end RefreshTopProof.GenInst

namespace RefreshTopProof.GenInst.{ns}

open {module} RefreshTopProof.GenInst RefreshTopProof.GenIface RefreshTopProof.GenIface.BrLut RefreshTopProof.Gen
open Mxx.Primitives MxxRuntime MxxExponentLut
'''


def facts_fields(text, inst):
    """field name -> (fragment index, type text) of the records `inst.Facts_k`."""
    out = {}
    for m in re.finditer(r'^structure ' + re.escape(inst) + r'\.Facts_(\d+) .*?\n((?:  .*\n)+)', text, re.M):
        k = int(m.group(1))
        for line in m.group(2).splitlines():
            mm = re.match(r'^  (\w+) : (.*)$', line)
            if mm:
                out[mm.group(1)] = (k, mm.group(2))
    return out


def adapters(path):
    text = open(path).read() if os.path.exists(path) else ''
    return set(re.findall(r'^theorem ([\w.]+)\.sem ', text, re.M))


def gather_P(ftype, child):
    """`P` of `Gen.gather_loop6` from a gather field `(∀ i : Fin F, ∃ x : T, …, conj ∧ child …)`."""
    s = xmodel.strip_parens(ftype)
    m = re.match(r'^∀ (\w+) : Fin (\d+), ', s)
    var, body = m.group(1), s[m.end():]
    binders = []
    while body.startswith('∃ '):
        mm = re.match(r'^∃ (\w+) : ', body)
        rest = body[mm.end():]
        ty = xmodel.split_top(rest, ', ')[0]
        binders.append(mm.group(1))
        body = rest[len(ty) + 2:]
    conj = [c.strip() for c in xmodel.split_top(body, ' ∧ ')]
    t = conj[0].split('≤', 1)[1].strip()
    call = conj[-1]
    if len(binders) != 6 or not call.startswith(child + ' '):
        return None
    call = call.replace(t, 'ti')
    return f'(fun {var} ti {" ".join(binders)} ↦ {call})'


def secret_inputs(gdir, module, scopes, inst):
    """instance input wires fed by the payload / mask stage outputs (the ternary secrets)."""
    claim = {c['module']: c for c in xmodel.parse_claim(gdir) if c.get('module')}
    outs = {c['output']: m for m, c in claim.items()}
    root = scopes['generatedRoot'].to_json()
    L = [a for a in root['atoms'] if a.get('loop') and a['loop']['kind'] == 'par'][0]['loop']
    ij = scopes[inst].to_json()
    ins = [w for w, v in ij['wires'].items() if v['src'] == 'input']
    res = {}
    for w, arg in zip(ins, L['args']):
        rw = xsem.wire_of(arg.replace(' i', ''))
        src = root['wires'].get(rw, {})
        if src.get('src') != 'input':
            continue
        idx = src['term'].split('.')[1:].count('2')
        T = claim[module]['args'][idx]
        if outs.get(T) in ('Stage_mask', 'Stage_payload'):
            res[w] = outs[T]
    return res


def bundle_adapters(path):
    text = open(path).read() if os.path.exists(path) else ''
    out = {}
    for m in re.finditer(r'^theorem ([\w.]+)\.sem .*\n.*\n    ((\w+)\.(Comp\w*)) (.*)$', text, re.M):
        out[m.group(1)] = m.group(2)
        out[m.group(1) + '#dims'] = [xmodel.strip_parens(x) for x in xmodel.split_top(m.group(5), ' ')[:8]]
    return out


CHAINS = {}
KEYS = {}

GT = '(by first | decide | exact RefreshTopProof.GenInst.Certs.{M}.{k}_gt _)'


def gen_module(gdir, module, adir, roles):
    scopes = xmodel.load(gdir, module)
    xsem.set_gadget(scopes)
    root = scopes['generatedRoot'].to_json()
    rl = [a for a in root['atoms'] if a.get('loop') and a['loop']['kind'] == 'par'][0]['loop']
    inst = rl['child']
    S = rl['count']
    text = open(f'{gdir}/{module}_Facts.lean').read()
    fields = facts_fields(text, inst)
    ad = adapters(f'{adir}/Gen_{module}_Scopes.lean')
    ij = scopes[inst].to_json()
    steps, notes = [], []
    for a in ij['atoms']:
        L = a.get('loop')
        if not L:
            continue
        child, field = L['child'], a['field']
        frag, ftype = fields[field]
        role = roles.get(child, {}).get('role', '?')
        ref = f'F.c{frag}.{field}'
        name = f'r_{field}'
        if child not in ad:
            notes.append(f'-- {field}: `{child}` ({role}) has no adapter')
            continue
        if L['kind'] == 'par':
            steps.append(f'  -- {role}: par[{L["count"]}] {child}\n'
                         f'  node_have {name} := fun i ↦ {child}.sem ({ref} i)')
        elif L['kind'] == 'gather':
            P = gather_P(ftype, child)
            if P is None:
                notes.append(f'-- {field}: gather of `{child}` ({role}) not of the six-family form')
                continue
            steps.append(f'  -- {role}: gather[{L["count"]}] {child}\n'
                         f'  node_have {name} := gather_sem {P} {ref}\n'
                         f'    (fun _ _ _ _ _ _ _ _ hc ↦ {child}.sem hc)')
        elif L['kind'] == 'seq':
            steps.append(f'  -- {role}: seq[{L["count"]}] {child}\n'
                         f'  node_have {name} := steps_of {ref} (fun _ _ _ hb ↦ {child}.sem hb)')
    hyps = ''
    if module == 'Stage_encrypt':
        I = xsem.Inst(ij, fields, inst)
        sec = secret_inputs(gdir, module, scopes, inst)
        names = {}
        for w, m in sec.items():
            s = 'sm' if m == 'Stage_mask' else 'sp'
            q = ij['wires'][w]['type'].split('ExactMatrix ', 1)[1].rsplit(' ', 3)[0]
            names[w] = (f'h_{w}', f'h{s}small')
            hyps += f' (h_{w} : {inst}.{w} ctx = fun _ _ ↦ reducePoly {q} {xsem.ring_n(ij["wires"])} {s})'
        M = xsem.MaskFacts(I, names)
        def gt(q):
            q = xmodel.strip_parens(q)
            mm = re.match(r'^(mod_\d+) \(?\(Int\.ofNat i_0\)\)?$', q)
            if mm:
                return f'RefreshTopProof.GenInst.Certs.{module}.{mm.group(1)}_gt i_0'
            return 'by decide'
        ba = bundle_adapters(f'{adir}/Gen_{module}_Scopes.lean')
        ssteps, snotes = xsem.enc_steps(I, M, roles, ba, gt)
        steps += M.haves + ssteps
        notes += ['-- ' + x for x in snotes]
        hyps = f' {{sm sp : ErrorPoly {xsem.ring_n(ij["wires"])}}} (hsmsmall : polyNorm sm ≤ 1) (hspsmall : polyNorm sp ≤ 1)' + hyps
    ns = module.replace('Stage_', '').title().replace('_', '')
    out = PRELUDE.format(module=module, inst=inst, ns=ns)
    out += f'''
/-- The instances of the stage root. -/
abbrev S : Nat := {S}
'''
    # segment theorems (semantic roles over the instance's facts record)
    I = xsem.Inst(ij, fields, inst)
    C = xsem.Certs(module)
    segs, keyths = [], []
    for a in ij['atoms']:
        L = a.get('loop')
        if not L:
            continue
        role = roles.get(L['child'], {}).get('role')
        try:
            if L['kind'] == 'seq' and role == 'lut.round.step':
                r = xsem.root_lut_match(I, a)
                segs.append(xsem.emit_root_lut(I, a, r, C, f'seg_{a["field"]}'))
                kt = xsem.emit_root_lut_keys(I, a, r, C, f'keys_{a["field"]}')
                if kt:
                    keyths.append(kt)
            elif L['kind'] == 'gather' and role == 'prf.cell0':
                P = gather_P(fields[a['field']][1], L['child'])
                segs.append(xsem.emit_cell0(I, a, C, P, scopes[L['child']].to_json()['atoms'], f'seg_{a["field"]}'))
            elif L['kind'] == 'par' and role in xsem.MEMBER_BRIDGE:
                s = xsem.emit_lut_member(I, a, C, role, scopes, f'seg_{a["field"]}')
                if s:
                    segs.append(s)
            elif L['kind'] == 'gather' and role == 'prf.cell1':
                P = gather_P(fields[a['field']][1], L['child'])
                segs.append(xsem.emit_cell1(I, a, C, P, scopes[L['child']].to_json()['atoms'], f'seg_{a["field"]}'))
        except (KeyError, StopIteration, AttributeError, IndexError) as e:
            notes.append(f'-- segment {a["field"]} ({role}) not matched: {e!r}')
    if module == 'Stage_online_eval':
        for r in xsem.root_private_match(I):
            try:
                segs.append(xsem.emit_root_private(I, r, C, f'seg_{r["both"]["field"]}'))
                keyths.append(xsem.emit_root_private_keys(I, r, C, f'keys_{r["both"]["field"]}'))
            except (KeyError, StopIteration, AttributeError, IndexError) as e:
                notes.append(f'-- private multiplication {r["both"]["field"]} not matched: {e!r}')
    chains_text = ''
    if module == 'Stage_online_eval':
        segd = {}
        for s in segs:
            m = re.match(r'theorem (seg_\S+) ', s)
            segd[m.group(1).replace('seg_', '')] = s[:s.index(':= by') + 5]
        segd.update({f'seg_{r["both"]["field"]}': segd.get(r['both']['field'], '') for r in []})
        try:
            hdr = (f'{{backend : BackendContext}} {{hashModel : HashModel}} {{params : Params}} {{i_0 : Nat}} [Fact (i_0 < S)]\n'
                   f'    {{ctx : {inst}.Ctx backend hashModel params i_0}} {{outputs}} (F : {inst}.Facts ctx outputs)\n'
                   f'    (hb : backend = Backend.backend) {{sm sp : ErrorPoly {xsem.ring_n(ij["wires"])}}} (hsm : polyNorm sm ≤ 1)')
            segs_by = {k: v for k, v in segd.items()}
            privs_raw = xsem.root_private_match(I)
            for r in privs_raw:
                segs_by[f'seg_{r["both"]["field"]}'] = segd[r['both']['field']]
            for cname, ctext, ends in xchain.compose(I, roles, segs_by, scopes, privs_raw, hdr):
                chains_text += ctext + f'\n/-! End facts of `{cname}`:\n' + '\n'.join(
                    f'* `{n}`: {d}' for n, d in ends) + '\n-/\n\n'
        except (KeyError, StopIteration, AttributeError, IndexError, ValueError) as e:
            notes.append(f'-- chains not composed: {e!r}')
    out += '\n' + '\n'.join(segs) + f'''

set_option maxHeartbeats 64000000 in
/-- The role facts of the child loops of instance body `{inst}` (symbolic instance `i_0`). -/
theorem roles {{backend : MxxRuntime.BackendContext}} {{hashModel : MxxRuntime.HashModel}}
    {{params : Params}} {{i_0 : Nat}} [Fact (i_0 < {S})] {{ctx : {inst}.Ctx backend hashModel params i_0}} {{outputs}}
    (F : {inst}.Facts ctx outputs){hyps} : True := by
''' + '\n'.join(steps) + '\n  trivial\n'
    if notes:
        out += '\n' + '\n'.join(notes) + '\n'
    out += f'\nend RefreshTopProof.GenInst.{ns}\n'
    if chains_text:
        ch = (f'import Gen_Inst_{module}\n\n/-! Generated by `generator/gen_instance.py` (xchain): the composition of the online\n'
              f'segments along the PRF chains (test theorems, conclusion `True`; the same steps are used inline by\n'
              f'the part theorem). -/\n\nset_option maxRecDepth 16384\n\nnamespace RefreshTopProof.GenInst.{ns}\n\n'
              f'open {module} RefreshTopProof.GenInst RefreshTopProof.GenIface RefreshTopProof.GenIface.BrLut RefreshTopProof.Gen\n'
              f'open Mxx.Primitives MxxRuntime MxxExponentLut\n\n' + chains_text + f'end RefreshTopProof.GenInst.{ns}\n')
        CHAINS[module] = ch
    if keyths:
        KEYS[module] = (f'import Gen_Inst_{module}\nimport GenKeyChain\n\n'
                        f'/-! Generated by `generator/gen_instance.py`: the keys of `{module}`\'s instance pieces in the\n'
                        f'preprocessing\'s closed forms (no semantic hypothesis; `GenKeyChain`). -/\n\n'
                        f'set_option maxHeartbeats 64000000\nset_option maxRecDepth 16384\n\n'
                        f'namespace RefreshTopProof.GenInst.{ns}\n\n'
                        f'open {module} RefreshTopProof.GenInst RefreshTopProof.GenIface RefreshTopProof.GenIface.BrLut\n'
                        f'open RefreshTopProof.GenIface.BrLutKey RefreshTopProof.Gen Mxx.Primitives MxxRuntime MxxExponentLut\n\n'
                        + '\n'.join(keyths) + f'\nend RefreshTopProof.GenInst.{ns}\n')
    return out, len(steps), notes


if __name__ == '__main__':
    gdir, odir, adir = sys.argv[1], sys.argv[2], sys.argv[3]
    import json
    rolesj = sys.argv[4]
    R = json.load(open(rolesj))
    for m in sys.argv[5:]:
        out, n, notes = gen_module(gdir, m, adir, R.get(m, {}))
        open(f'{odir}/Gen_Inst_{m}.lean', 'w').write(out)
        if m in CHAINS:
            open(f'{odir}/Gen_Inst_{m}_Chains.lean', 'w').write(CHAINS[m])
        if m in KEYS:
            open(f'{odir}/Gen_Inst_{m}_KeyChain.lean', 'w').write(KEYS[m])
        print(f'{m}: {n} steps, {len(notes)} skipped')
