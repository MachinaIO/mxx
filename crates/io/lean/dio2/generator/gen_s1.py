def tuple_leaves(term, path=""):
    parts = xmodel.split_top(xmodel.strip_parens(term), ",")
    if len(parts) == 1:
        return [(path, xmodel.strip_parens(parts[0]))]
    leaves = []
    for index, part in enumerate(parts):
        suffix = ".2" * index + (".1" if index + 1 < len(parts) else "")
        leaves.extend(tuple_leaves(part, path + suffix))
    return leaves


