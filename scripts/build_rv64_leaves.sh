#!/usr/bin/env bash
# Builds crates/lattice-leaves for the mathcal-A machine and writes its code to
# crates/ir-core/src/lower/rv64_leaves.rs.
#
# The crate is compiled with a pinned nightly (for -Zbuild-std, so core and compiler_builtins are
# compiled without compressed or atomic instructions) and the medium code model (all addressing
# pc-relative, so the image is position independent), linked at address 0 by
# scripts/rv64/leaves.ld, and checked: no writable data, and every entry symbol present.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
TOOLCHAIN=${MXX_RV64_TOOLCHAIN:-nightly-2026-07-25}
TARGET=riscv64imac-unknown-none-elf
OUT=$ROOT/target/rv64-leaves
BIN=$(rustc +"$TOOLCHAIN" --print sysroot)/lib/rustlib/x86_64-unknown-linux-gnu/bin
mkdir -p "$OUT"
(
  cd "$ROOT"
  CARGO_PROFILE_RELEASE_LTO=false CARGO_PROFILE_RELEASE_STRIP=none CARGO_PROFILE_RELEASE_PANIC=abort \
  CARGO_TARGET_DIR="$OUT/cargo" \
  RUSTFLAGS="-C target-feature=-c,-zca,-a,-zaamo,-zalrsc -C code-model=medium -C relocation-model=static" \
    cargo +"$TOOLCHAIN" rustc -q -p mxx-lattice-leaves --release --target $TARGET \
      -Zbuild-std=core,compiler_builtins -Zbuild-std-features=compiler-builtins-mem \
      --crate-type staticlib
)
ARCHIVE=$OUT/cargo/$TARGET/release/libmxx_lattice_leaves.a
ENTRIES=$("$BIN/llvm-nm" --defined-only "$ARCHIVE" 2>/dev/null | awk '$2 == "T" && $3 ~ /^mxx_/ {print $3}' | sort -u)
UNDEFINED=$(for e in $ENTRIES; do printf -- "--undefined=%s " "$e"; done)
"$BIN/rust-lld" -flavor gnu -e 0 -T "$ROOT/scripts/rv64/leaves.ld" --gc-sections $UNDEFINED \
  -o "$OUT/leaves.elf" "$ARCHIVE"
WORD_OPS=$("$BIN/llvm-objdump" -d --no-show-raw-insn "$OUT/leaves.elf" |
  grep -E "\s(addw|subw|sllw|srlw|sraw|mulw|divw|divuw|remw|remuw|slliw|srliw|sraiw|negw)\s" || true)
if [ -n "$WORD_OPS" ]; then
  echo "RV64 word operations, which the mathcal-A machine lacks:" >&2
  echo "$WORD_OPS" >&2
  exit 1
fi
for section in .data .bss; do
  size=$("$BIN/llvm-size" -A "$OUT/leaves.elf" | awk -v s=$section '$1 == s {print $2}')
  if [ -n "$size" ] && [ "$size" != 0 ]; then echo "writable section $section of $size bytes" >&2; exit 1; fi
done
"$BIN/llvm-objcopy" -O binary --only-section=.text "$OUT/leaves.elf" "$OUT/text.bin"
"$BIN/llvm-objcopy" -O binary --only-section=.rodata "$OUT/leaves.elf" "$OUT/rodata.bin" || : > "$OUT/rodata.bin"
TEXT_ADDR=$("$BIN/llvm-objdump" -h "$OUT/leaves.elf" | awk '$2 == ".text" {print $4}')
RODATA_ADDR=$("$BIN/llvm-objdump" -h "$OUT/leaves.elf" | awk '$2 == ".rodata" {print $4}')
"$BIN/llvm-nm" --defined-only "$OUT/leaves.elf" | awk '$3 ~ /^mxx_/ {print $3, $1}' > "$OUT/entries.txt"
python3 - "$OUT" "$TEXT_ADDR" "${RODATA_ADDR:-}" "$ROOT/crates/ir-core/src/lower/rv64_leaves.rs" "$TOOLCHAIN" <<'PY'
import sys, struct
out, text_addr, rodata_addr, dest, toolchain = sys.argv[1:6]
text = open(f"{out}/text.bin", "rb").read()
rodata = open(f"{out}/rodata.bin", "rb").read()
assert int(text_addr, 16) == 0, "code must start at 0"
assert len(text) % 4 == 0
if rodata:
    gap = int(rodata_addr, 16) - len(text)
    assert gap >= 0 and gap < 8, "read-only data must follow the code"
    rodata = b"\0" * gap + rodata
words = struct.unpack(f"<{len(text)//4}I", text)
entries = []
for line in open(f"{out}/entries.txt"):
    name, addr = line.split()
    addr = int(addr, 16)
    assert addr % 4 == 0 and addr < len(text)
    entries.append((name, addr // 4))
with open(dest, "w") as f:
    f.write("// Generated by scripts/build_rv64_leaves.sh with the Rust toolchain `%s`. Do not edit.\n\n" % toolchain)
    f.write("/// The RV64IM code of `mxx-lattice-leaves`, linked at address 0.\n")
    f.write("pub(super) const WORDS: &[u32] = &[\n")
    for i in range(0, len(words), 8):
        f.write("    " + ", ".join(f"0x{w:08x}" for w in words[i:i+8]) + ",\n")
    f.write("];\n\n/// Read-only data, placed right after the code.\n")
    f.write("pub(super) const RODATA: &[u8] = &[\n")
    for i in range(0, len(rodata), 16):
        f.write("    " + ", ".join(f"0x{b:02x}" for b in rodata[i:i+16]) + ",\n")
    f.write("];\n\n/// Entry points: symbol and instruction index.\n")
    f.write("pub(super) const ENTRIES: &[(&str, u64)] = &[\n")
    for name, word in sorted(entries):
        f.write(f"    (\"{name}\", {word}),\n")
    f.write("];\n")
print(f"{len(words)} code words, {len(rodata)} data bytes, {len(entries)} entries")
PY
