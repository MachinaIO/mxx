# (identity coefficient, internal sum, first-depth leaf sum, second-depth leaf sum) scopes, per step.
SUM = {0: (55, 64, 65, 66), 1: (115, 124, 125, 126), 2: (175, 184, 185, 186), 3: (235, 244, 245, 246)}

# The last step reads its table as constants: `coefTermC` and one witness less per coefficient term.
FINAL_COEF = [
    ("obtain ⟨w6, w16, -, -, x6, x16, xout⟩ := hb", "obtain ⟨w5, w13, -, -, x5, x13, xout⟩ := hb"),
    ("obtain ⟨w6, w16, -, -, x6, -, -, x16, xout⟩ := h", "obtain ⟨w5, w13, -, -, x5, -, -, x13, xout⟩ := h"),
    ("rw [hsel] at x16", "rw [hsel] at x13"),
    ("obtain ⟨_, hw6⟩ := familyGet_eq x6", "obtain ⟨_, hw5⟩ := familyGet_eq x5"),
    ("obtain ⟨-, -, -, hw16⟩ := x16", "obtain ⟨-, -, -, hw13⟩ := x13"),
    ("simp only [dif_pos hi, coefTerm, hw16]", "simp only [dif_pos hi, coefTermC, hw13]"),
    ("simp only [coefTerm, hw16]", "simp only [coefTermC, hw13]"),
    ("congr 3\n      rw [hw6]", "congr 2\n      rw [hw5]"),
    ("congr 3\n  rw [hw6]", "congr 2\n  rw [hw5]"),
]


def final_coef(match: re.Match) -> str:
    text = match.group(0)
    for old, new in FINAL_COEF:
        text = text.replace(old, new)
    return text


def sums() -> None:
    template = (HERE / "PePreSum.lean.in").read_text()
    for step, (c55, c64, c65, c66) in SUM.items():
        text = (template.replace("⟦S⟧", str(step)).replace("⟦C55⟧", str(c55)).replace("⟦C64⟧", str(c64))
                .replace("⟦C65⟧", str(c65)).replace("⟦C66⟧", str(c66)))
        text = re.sub(r"(coefTerm|branchCoef) tables 0 ", rf"\1 tables {128 * step} ", text)
        if step == 3:
            text = re.sub(r"(?ms)^theorem (?:coefLoopId|coefStep\w+) .*?(?=\n\n)", final_coef, text)
            text = re.sub(r"\bcoefTerm\b", "coefTermC", text)
            text = re.sub(r"\bbranchCoef\b", "branchCoefC", text)
            text = re.sub(r"\bcoefAccum\b", "coefAccumC", text)
        (HERE / f"PePreSum{step}.lean").write_text(
            "-- Generated by `gen_pre.py` from `PePreSum.lean.in`; edit the template instead.\n" + text)


if __name__ == "__main__":
    main()
    lut()
    internal()
    lut2()
    sums()
