#!/usr/bin/env python3
"""Write `Dio2Online0PartPrimes.lean`: `prime_term` at every prime of a refresh part of step 0.

The refresh part `parallel_generatedRoot_1281` of `W_Stage_online_0` sums one CRT term per prime
(`(((t₀ + t₁) + t₂) + t₃) + t₄`). For every prime this script walks the term's wires back through
the final combination (`term = lift(switch(b P - ((comb + fresh) + smudge) - H)) K`, the
combination `[g | c₁] D - cₓ Y`, `D` the digits of `Q_q A'`, `Y` the digits of `c' lift(s₁₀ s₉
(G' mod q))`) and writes `online0_part_prime<c>`, the application of `prime_term` to those atoms
(the first prime is `Dio2Online0Part.online0_part_prime0`'s pattern).

Usage: gen_part_primes.py <average package>
"""
import os
import re
import sys

pkg = sys.argv[1]
stage = open(os.path.join(pkg, 'worst/W_Stage_online_0.lean')).read()
facts = open(os.path.join(pkg, 'worst/W_Stage_online_0_Facts.lean')).read()
scope = 'parallel_generatedRoot_1281'

nats = dict(re.findall(r'^local notation "(mxxNat\d+)" => (\d+)$', stage, re.M))
mods = dict(re.findall(r'^abbrev (modulus_\d+) : Nat := (\S+)$', stage, re.M))
mods = {k: int(nats.get(v, v)) for k, v in mods.items()}
nots = dict(re.findall(r'^local notation "(mxxMat\d+)" => Mxx\.Primitives\.ExactMatrix (\S+) ', stage, re.M))

b = stage.index(f'abbrev {scope}.body')
body = stage[b:stage.index('\n\n', b)]
lets = {}
types = {}
for w, ty, t in re.findall(r'^  let (w_\d+_\d+(?:_concat_\d+)?)(?: : (\S+))? := (.+)$', body, re.M):
    lets[w] = t
    if ty:
        types[w] = ty
wit = re.search(rf'^structure {scope}\.Witness where\n(.*?)\n\n', stage, re.M | re.S).group(1)
types.update(re.findall(r'^\s+(w_\d+_\d+(?:_concat_\d+)?) : (\S+)$', wit, re.M))
atoms = {}
for m in re.finditer(rf'^abbrev {scope}\.constraints_\d+ .*?:=\n(.*?)(?=^abbrev |^def |^structure |\Z)',
                     stage, re.M | re.S):
    for line in m.group(1).split('\n'):
        line = line.strip()
        if line.endswith(' ∧'):
            line = line[:-2]
        mm = re.match(r'^MxxRuntime\.(\w+) (.*) (w_\d+_\d+)$', line)
        if mm:
            atoms[mm.group(3)] = (mm.group(1), mm.group(2))
field = {}
cur = None
for line in facts.split('\n'):
    m = re.match(rf'^structure {scope}\.Facts_(\d+)', line)
    if m:
        cur = m.group(1)
        continue
    if line.startswith('structure '):
        cur = None
    m = re.match(r'^  (h[0-9_]+) :', line)
    if m and cur is not None:
        field[m.group(1)] = f'F.c{cur}.{m.group(1)}'


def let(w, head):
    t = lets[w].replace('MxxRuntime.', '')
    m = re.fullmatch(rf'{head} (w_\d+_\d+) (w_\d+_\d+)', t)
    assert m, (w, t, head)
    return m.group(1), m.group(2)


def atom(w, head):
    h, args = atoms[w]
    assert h == head, (w, h, head)
    return args


def fact(w):
    return field['h' + w[2:]]


def const(w):
    t = lets[w]
    m = re.search(r'matrixPolynomial \[\(([^)]*)\)\]', t)
    v = m.group(1)
    return int(nats.get(v, v))


def modulus_of(w):
    return nots[types[w]]


terms = []
w = 'w_288_0'
while True:
    a, b_ = let(w, 'matrixAdd')
    terms.append(b_)
    if lets.get(a, '').startswith('MxxRuntime.matrixAdd'):
        w = a
    else:
        terms.append(a)
        break
terms.reverse()
assert len(terms) == 5, terms

out = ['''import Dio2Online0Part

/-! Generated by `crates/io/lean/dio2/generator/gen_part_primes.py`: `prime_term` at the primes of
refresh part `parallel_generatedRoot_1281` of step 0 (see `Dio2Online0Part`). -/

set_option maxHeartbeats 32000000

namespace Dio2Proof

open Mxx.Primitives MxxRuntime MxxExponentLut Mxx.ExponentLut.Refresh RefreshTopProof
  RefreshTopProof.GenFinal GenDecode W_Stage_online_0
''']
summary = []
for c, t in enumerate(terms):
    l, kw = let(t, 'matrixMulScalarRight')
    K = const(kw)
    r = atom(l, 'centeredRebaseRuns').split()[0]
    zeta = atom(r, 'modulusSwitchRuns').split()[0]
    q = modulus_of(r)
    z1, H = let(zeta, 'matrixSub')
    w3, ssum = let(z1, 'matrixSub')
    w2 = atom(w3, 'modulusReduceRuns').split()[0]
    bw, P = let(w2, 'matrixMul')
    cf, sm = let(ssum, 'matrixAdd')
    comb, fresh = let(cf, 'matrixAdd')
    gcD, cxY = let(comb, 'matrixSub')
    gc, D = let(gcD, 'matrixMul')
    cx, Y = let(cxY, 'matrixMul')
    g, c1 = atom(gc, 'concatColumns').split()[:2]
    Dp = atom(D, 'compactCenteredRebaseRuns').split()[1]
    zA = atom(Dp, 'gadgetDecomposeRuns').split()[-1]
    qq, A = let(zA, 'matrixMulScalarLeft')
    Qq = const(qq)
    Yp = atom(Y, 'compactCenteredRebaseRuns').split()[1]
    zY = atom(Yp, 'gadgetDecomposeRuns').split()[-1]
    w21, cp = let(zY, 'matrixMulScalarRight')
    cprime = const(cp)
    w20 = atom(w21, 'centeredRebaseRuns').split()[0]
    w18, s10w = let(w20, 'matrixMulScalarRight')
    w16, s9w = let(w18, 'matrixMulScalarRight')
    s10, s9 = const(s10w), const(s9w)
    w15 = atom(w16, 'modulusReduceRuns').split()[0]
    w14 = atom(w15, 'centeredRebaseRuns').split()[0]
    assert atoms[w14][0] == 'gadgetMatrixRuns'
    Q0 = mods['modulus_0']
    assert Q0 == Qq * mods[q], (c, q)
    summary.append((c, t, q, K))
    pw = lambda x: f'{scope}.{x} ctx'
    out.append(f'''
/-- **Prime {c} of refresh part `i` of step 0** (`{q}`). -/
theorem online0_part_prime{c} {{backend : BackendContext}} {{hashModel : HashModel}} {{params : Params}}
    {{i : Nat}} (ctx : {scope}.Ctx backend hashModel params i) {{outputs : _}}
    (F : {scope}.Facts ctx outputs)
    (hRq : modulus_0 = {Qq} * {q})
    (L : RegularLayout modulus_0) (hL : backend.regularLayout modulus_0 8 = some L)
    (hLx : L.droppedModuli = 0)
    {{k : Int}} (hc : ((1 : Nat) : Int) * {cprime} = ({Qq} : Int) * k)
    {{s β : ExactPoly modulus_0 8}} {{x : ErrorPoly 8}}
    {{Kg K₁ Kx : Fin 2 → ExactMatrix modulus_0 8 1 25}}
    {{eg e₁ ex : ErrorMatrix 8 1 25}} {{Beg Be1 Bex : Nat}}
    (heg : CoeffBound eg Beg) (he1 : CoeffBound e₁ Be1) (hex : CoeffBound ex Bex)
    (hg : {pw(g)} = maskPart s Kg - β • {pw(w14)} + reduceMatrix modulus_0 8 1 25 eg)
    (hc₁ : {pw(c1)} = maskPart s K₁ - {pw(w14)} + reduceMatrix modulus_0 8 1 25 e₁)
    (hcx : {pw(cx)} = maskPart s Kx -
      reducePoly modulus_0 8 (((1 : Nat) : Int) * x) • {pw(w15)} + reduceMatrix modulus_0 8 1 25 ex)
    {{T : ExactPoly modulus_0 8}}
    (hscalar : reducePoly {q} 8 (((k : Int) : ErrorPoly 8) * x) * (({s9} : Int) : ExactPoly {q} 8) *
      (({s10} : Int) : ExactPoly {q} 8) = GenFinal.rho {q} T)
    {{Bk : Fin 2 → ExactMatrix modulus_0 8 1 54}} {{eb : ErrorMatrix 8 1 54}} {{Beb : Nat}}
    (hb : {pw(bw)} = maskPart s Bk + reduceMatrix modulus_0 8 1 54 eb) (heb : CoeffBound eb Beb)
    {{Pd : ErrorMatrix 8 54 25}} {{BP : Nat}}
    (hP : {pw(P)} = reduceMatrix modulus_0 8 54 25 Pd) (hPd : CoeffBound Pd BP)
    {{Kf Ks : Fin 2 → ExactMatrix modulus_0 8 1 25}}
    (hpre : ∀ k', Bk k' * {pw(P)} =
      (Kg k' * topRows ({pw(D)}) + K₁ k' * bottomRows ({pw(D)}) - Kx k' * {pw(Y)}) + Kf k' + Ks k')
    {{E ef : ErrorMatrix 8 1 25}} {{Bf : Nat}}
    (hf : {pw(fresh)} = maskPart s Kf - (({Qq} : Int) : ExactPoly modulus_0 8) •
      reduceMatrix modulus_0 8 1 25 E + reduceMatrix modulus_0 8 1 25 ef) (hef : CoeffBound ef Bf)
    {{Tsm : ExactMatrix modulus_0 8 1 25}} {{es : ErrorMatrix 8 1 25}} {{Bs : Nat}}
    (hs : {pw(sm)} = maskPart s Ks - Tsm + reduceMatrix modulus_0 8 1 25 es) (hes : CoeffBound es Bs)
    {{M : ErrorMatrix 8 1 25}} {{BM : Nat}}
    (hTH : Tsm - {pw(H)} = reduceMatrix modulus_0 8 1 25 M) (hM : CoeffBound M BM)
    (hnoise : 2 * (54 * 8 * Beb * BP + (25 * 8 * Beg * 2048 + 25 * 8 * Be1 * 2048 + 25 * 8 * Bex * 2048) +
      Bf + Bs + BM) < {Qq}) :
    TermOf {q} {K} ({pw(t)})
      (β • rowOf ({pw(A)}) 0 + rowOf ({pw(A)}) 1 - T • {pw(w15)} +
        reduceMatrix modulus_0 8 1 25 E) := by
  obtain ⟨DI, hDI, hDb⟩ := {fact(D)}.2.2.2
  obtain ⟨YI, hYI, hYb⟩ := {fact(Y)}.2.2.2
  have hR : 1 < modulus_0 := by rw [hRq]; norm_num [{q}]
  exact prime_term (by norm_num) hRq (by norm_num) (by norm_num [{q}]) hR L hL hLx
    {fact(w14)} {fact(w14)} {fact(w15)} {fact(w16)} {fact(w21)} {fact(Yp)} {fact(Y)} hYI hYb hc
    {fact(Dp)} {fact(D)} hDI hDb {fact(gc)} heg he1 hex hg hc₁ hcx hscalar hb heb hP hPd {fact(w3)}
    hpre hf hef hs hes hTH hM hnoise {fact(r)} {fact(l)} _
''')
out.append('\nend Dio2Proof\n')
open(os.path.join(pkg, 'proof/Dio2Online0PartPrimes.lean'), 'w').write(''.join(out))
for s in summary:
    print(*s)
