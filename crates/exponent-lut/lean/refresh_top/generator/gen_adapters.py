def comp_name(role, k):
    base = ''.join(x[:1].upper() + x[1:] for x in re.split(r'[.\-]', role))
    return f'{base}.Comp' + (f'_{k}' if k else '')


class Variants:
    """Bundle texts of all scopes of the bundle roles, grouped into named variants."""

    def __init__(self):
        self.by_role = collections.defaultdict(list)   # role -> [text]
        self.scope = {}                                 # (module, scope) -> (name, bundle)

    def add(self, module, name, role, b):
        text = b.head + '\n' + b.body
        lst = self.by_role[role]
        if text not in lst:
            lst.append(text)
        k = lst.index(text)
        self.scope[(module, name)] = (comp_name(role, k), b)

    def lean(self):
        out = ['-- BEGIN GENERATED COMP (generator/gen_adapters.py --iface; do not edit by hand)', '']
        for role in sorted(self.by_role):
            for k, text in enumerate(self.by_role[role]):
                head, body = text.split('\n', 1)
                out.append(f'/-- Computation bundle of role `{role}` (variant {k}): the scope relation with '
                           f'dimensions, moduli and constants as parameters. -/')
                out.append(f'def {comp_name(role, k)} {head} :=\n  {body}\n')
        out.append('-- END GENERATED COMP')
        return '\n'.join(out)


def collect_variants(gdir, modules):
    V = Variants()
    fails = []
    for m in modules:
        sc = xmodel.load(gdir, m)
        res, _ = xroles.assign(gdir, [m])
        for n, info in res[m].items():
            if info['role'] in BUNDLE_ROLES:
                try:
                    V.add(m, n, info['role'], xbundle.make(sc[n], info['role']))
                except xbundle.Fail as e:
                    fails.append((m, n, info['role'], str(e)))
    return V, fails


def ad_bundle(s, info, cx, V):
    name, b = V.scope[(s.module, s.name)]
    per, flat = atom_names(s)
    if len(flat) != len(b.atoms):
        raise Fail('atom count mismatch')
    names = [n for n, _ in flat]
    witness = s.kind == 'record'
    if witness:
        pat = pattern(s, per, witness=True)
    else:
        pat = pattern(s, per)
    args = [f'({v})' for _, _, v, _ in b.dims] + [f'({v})' for _, _, v, _ in b.consts]
    args += ['backend', 'hashModel' if 'hashModel' in dict(sig_names(s)) else sig_names(s)[1][0]]
    hn = dict(zip([n for n, t in s.sig if t == 'Nat'], index_names(s)))
    args += [hn[o] for o in b.idx_used]
    if b.child:
        child, mid = b.child
        args.append(f'(fun i a b ↦ {child} {mid} a b)')
    if b.table:
        table, mid = b.table
        args.append(f'(fun i o ↦ {table} {mid} i () o)')
    binders, call, _ = header(s)
    io = [n for n, _ in sig_names(s)][-2:]
    concl = f'{name} ' + ' '.join(args) + f' {io[0]} {io[1]}'
    # projection paths of the atoms in the fragment conjunction
    fr = frag_atoms(s)
    paths = []
    for f, atoms in enumerate(fr):
        pf = '.2' * f + ('.1' if f < len(fr) - 1 else '')
        for j in range(len(atoms)):
            pj = '.2' * j + ('.1' if j < len(atoms) - 1 else '')
            paths.append(pf + pj)
    if witness:
        ex = ['wit']
        vals = [f'wit.{w}' for w in b.binders]
    else:
        ex = exists_order(s)
        vals = list(b.binders)
    vals += [f'hc{paths[k]}' for k in b.kept]
    body = vals[0] if len(vals) == 1 else '⟨' + ', '.join(vals) + '⟩'
    term = body
    for x in reversed(ex):
        term = f'Exists.elim hc (fun {x} hc ↦ {term})'
    proof = 'TERM  ' + term.replace('Exists.elim hc', 'Exists.elim h', 1) if ex else 'TERM  ' + body.replace('hc', 'h')
    return binders, call, concl, proof


def gen_module(gdir, module, only=None, V=None):
    sc = xmodel.load(gdir, module)
    cx = xroles.Ctx(sc)
    res, unknown = xroles.assign(gdir, [module])
    roles = res[module]
    out = [PRELUDE.format(module=module)]
    done, skipped, failed = [], collections.Counter(), []
    # children first (adapters reference child adapters)
    order = []

    def visit(n):
        if n in order or n not in sc:
            return
        for c in sc[n].children:
            visit(c)
        order.append(n)
    for n in sc:
        visit(n)
    for n in order:
        info = roles.get(n)
        if info is None:
            continue
        r = info['role']
        if only and r not in only:
            continue
        fn = ADAPTERS.get(r)
        if fn is None and V is not None and (module, n) in V.scope:
            fn = lambda s_, i_, c_: ad_bundle(s_, i_, c_, V)
        if fn is None:
            skipped[r] += 1
            continue
        try:
            binders, call, concl, proof = fn(sc[n], info, cx)
        except (Fail, xbundle.Fail, IndexError, AttributeError, KeyError) as e:
            failed.append((n, r, repr(e)))
            continue
        if sc[n].kind == 'record':
            wf = {w for w, _ in sc[n].witness}
            proof = re.sub(r'(?<![.\w])(w_\d+(?:_\d+)?(?:_concat_\d+)?)\b',
                           lambda m_: f'wit.{m_.group(1)}' if m_.group(1) in wf else m_.group(1), proof)
        if proof.startswith('TERM'):
            out.append(f'/-- `{r}` -/\ntheorem {n}.sem {binders}\n    (h : {call}) :\n    {concl} :=\n{proof[4:]}\n')
        else:
            out.append(f'/-- `{r}` -/\ntheorem {n}.sem {binders}\n    (h : {call}) :\n    {concl} := by\n{proof}\n')
        done.append((n, r))
    out.append(f'end {module}\n')
    return '\n'.join(out), done, skipped, failed


