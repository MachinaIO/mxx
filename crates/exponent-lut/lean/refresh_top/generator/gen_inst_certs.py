#!/usr/bin/env python3
"""Generate `Gen_InstCerts.lean` (WP D): the numeric facts about the instance tables of the merged
stages, for a symbolic instance `i0 < S`, proven once per fact by `interval_cases i0 <;> decide`
(never inside an instance theorem or the part theorem).

For every merged stage module `M` (its instance tables `M.sel_k`, rings `M.mod_k`, fixed moduli
`M.modulus_k`):
* `M.mod_k_gt i0 : 1 < M.mod_k (Int.ofNat i0)`;
* `M.mod_k_layout i0 : ∃ L, Backend.backend.regularLayout (M.mod_k (Int.ofNat i0)) N = some L ∧
  L.droppedModuli = 0` when every instance's ring has a backend layout;
* for rings/moduli `A`, `B` with `B ∣ A` at every instance (`A ≠ B`): `A = A / B * B` and
  `1 < A / B` (the move-down factorizations `q = p q'` of the role lemmas);
* `M.sel_k_periodic i0 : M.sel_k (Int.ofNat i0) = M.sel_k (Int.ofNat (i0 % R))` when the table only
  depends on the component `i0 % R`, and `M.sel_k_chain` when it only depends on `i0 / R`.
Values are computed from the tables (Python) only to decide which facts to state.

Usage: gen_inst_certs.py <generated dir> <out file> Stage_X…  [--R r]
"""
import re
import sys


def tables(path):
    text = open(path).read()
    sel = {k: [int(x) for x in v.split(',')] for k, v in
           re.findall(r'^abbrev (sel_\d+) \(i : Int\) : Int := MxxIR\.selectInt i \[([^\]]*)\]', text, re.M)}
    mods = dict(re.findall(r'^abbrev (mod_\d+) \(i : Int\) : Nat := (.*)$', text, re.M))
    fixed = {k: int(v) for k, v in re.findall(r'^abbrev (modulus_\d+) : Nat := (\d+)$', text, re.M)}
    return sel, mods, fixed


def eval_mod(expr, sel, i):
    e = re.sub(r'\(\(sel_(\d+) \(i\)\)\)', lambda m: str(sel['sel_' + m.group(1)][i]), expr)
    e = e.replace('.toNat', '')
    return int(eval(e))


def layouts(gdir):
    """modulus -> digit count of its backend layout; ring dimension."""
    text = open(f'{gdir}/Backend.lean').read()
    mods = {k: len(v.split(',')) for k, v in re.findall(r'^def (moduli\d+) : List Nat := \[([^\]]*)\]', text, re.M)}
    out = {}
    for k, q, body in re.findall(r'^def layout(\d+) : MxxRuntime\.RegularLayout (\d+) :=\n((?:  .*\n)+)', text, re.M):
        dp = int(re.search(r'digitsPerTower := (\d+)', body).group(1))
        dr = int(re.search(r'droppedModuli := (\d+)', body).group(1))
        out[int(q)] = (mods['moduli' + k] - dr) * dp
    n = re.findall(r'if h : q = \d+ ∧ n = (\d+)', text)[0]
    return out, int(n)


def stage_count(gdir, module):
    text = open(f'{gdir}/{module}.lean').read()
    m = re.search(r'∀ i : Fin (\d+), parallel_generatedRoot_\d+ ', text)
    return int(m.group(1))


def main():
    args = sys.argv[1:]
    R = 2
    if '--R' in args:
        k = args.index('--R')
        R = int(args[k + 1])
        del args[k:k + 2]
    gdir, out, mods_ = args[0], args[1], args[2:]
    lay, N = layouts(gdir)
    lines = ['import ' + m for m in mods_] + ['import Backend', 'import Mathlib.Tactic.IntervalCases', '',
             '/-! Generated by `generator/gen_inst_certs.py`: numeric facts about the instance tables of',
             'the merged stages at a symbolic instance `i0 < S` (`interval_cases i0 <;> decide`). -/', '',
             'set_option maxRecDepth 65536', 'set_option maxHeartbeats 4000000', '',
             'namespace RefreshTopProof.GenInst.Certs', '']
    count = 0
    for M in mods_:
        S = stage_count(gdir, M)
        sel, mods, fixed = tables(f'{gdir}/{M}.lean')
        if not mods and not sel:
            continue
        hyp = f'(i0 : Nat) [h : Fact (i0 < {S})]'
        tac = f'  have := h.out\n  interval_cases i0 <;> decide'
        vals = {f'{M}.{k}': [eval_mod(v, sel, i) for i in range(S)] for k, v in mods.items()}
        terms = {f'{M}.{k}': f'({M}.{k} (Int.ofNat i0))' for k in mods}
        for k, v in fixed.items():
            vals[f'{M}.{k}'] = [v] * S
            terms[f'{M}.{k}'] = f'{M}.{k}'
        lines.append(f'/-! ## `{M}` (instances `i0 < {S}`) -/\n')
        for k in mods:
            name, t = f'{M}.{k}', terms[f'{M}.{k}']
            lines += [f'theorem {name}_gt {hyp} : 1 < {t} := by', tac, '']
            count += 1
            if all(x in lay for x in vals[name]) and len({lay[x] for x in vals[name]}) == 1:
                D = lay[vals[name][0]]
                lines += [f'theorem {name}_layout {hyp} : ∃ L : MxxRuntime.RegularLayout {t},',
                          f'    Backend.backend.regularLayout {t} {N} = some L ∧ L.droppedModuli = 0 ∧ L.digitCount = {D} := by',
                          f'  have := h.out',
                          f'  interval_cases i0 <;> exact ⟨_, by simp [Backend.backend]; rfl, rfl, rfl⟩', '']
                count += 1
        for k, v in fixed.items():
            if v in lay:
                lines += [f'theorem {M}.{k}_layout : ∃ L : MxxRuntime.RegularLayout {M}.{k},',
                          f'    Backend.backend.regularLayout {M}.{k} {N} = some L ∧ L.droppedModuli = 0 ∧ L.digitCount = {lay[v]} :=',
                          f'  ⟨_, by simp [Backend.backend]; rfl, rfl, rfl⟩', '']
                count += 1
        names = list(vals)
        for a in names:
            for b in names:
                if a == b or not any(k in a for k in mods) and not any(k in b for k in mods):
                    continue
                va, vb = vals[a], vals[b]
                if all(y != x and x % y == 0 for x, y in zip(va, vb)):
                    an = a.split('.')[1]
                    bn = b.split('.')[1]
                    lines += [f'theorem {M}.{an}_div_{bn} {hyp} : {terms[a]} = {terms[a]} / {terms[b]} * {terms[b]} := by', tac, '',
                              f'theorem {M}.{an}_quot_{bn} {hyp} : 1 < {terms[a]} / {terms[b]} := by', tac, '']
                    count += 2
        for k, v in sel.items():
            if len(set(v)) == 1:
                continue
            if all(v[i] == v[i % R] for i in range(S)):
                lines += [f'theorem {M}.{k}_comp {hyp} : {M}.{k} (Int.ofNat i0) = {M}.{k} (Int.ofNat (i0 % {R})) := by', tac, '']
                count += 1
            if all(v[i] == v[(i // R) * R] for i in range(S)):
                lines += [f'theorem {M}.{k}_chain {hyp} : {M}.{k} (Int.ofNat i0) = {M}.{k} (Int.ofNat (i0 / {R} * {R})) := by', tac, '']
                count += 1
    lines.append('end RefreshTopProof.GenInst.Certs')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print('wrote', out, count, 'certificates')


main()
