#!/usr/bin/env python3
"""Generate the initial, import and preimage proofs from dio2 metadata.

Only stage scopes, exported ports and prime families are visited. Family members,
labels, polynomial coefficients and refresh parts are never enumerated. Use
--output-dir to inspect another package without writing to that package.
"""
import argparse
from pathlib import Path
import re

import dio2_meta as meta
from xmodel import app_split, strip_parens


HEADER = '''set_option maxHeartbeats 4000000
set_option maxRecDepth 16384
set_option linter.unusedVariables false

attribute [local irreducible] Mxx.Primitives.negacyclicModulus

namespace Dio2Proof

open Mxx.Primitives MxxRuntime MxxExponentLut

'''


def identifier(name):
    return re.sub(r'[^a-zA-Z0-9]+', '_', name).strip('_')


def projection(index, value='outputs'):
    return value + '.2' * index + '.1'


def output_projection(scope, index, value='outputs'):
    """Project a flattened output through the export's actual tuple tree."""
    term = next(atom.args[0] for atom in scope.atoms if atom.kind == 'out')
    leaves = []

    def visit(expression, path):
        expression = meta.xmodel.strip_parens(expression)
        if not expression:
            return
        items = meta.xmodel.split_top(expression, ',')
        if len(items) == 1:
            leaves.append(path)
            return
        for position, item in enumerate(items):
            suffix = '.2' * position + ('.1' if position < len(items) - 1 else '')
            visit(item, path + suffix)

    visit(term, value)
    meta.require(len(leaves) == len(meta.output_wires(scope)), 'Output tuple leaf mismatch')
    return leaves[index]


def atom_fact(atom, variable='F'):
    if atom.kind == 'out':
        return f'{variable}.c{atom.frag}.hout'
    wire = atom.loop.outs[-1].split()[0] if atom.loop else atom.args[-1]
    return f'{variable}.c{atom.frag}.h{wire[2:]}'


def atom_projection(scope, atom):
    atoms = [item for item in scope.atoms if item.frag == atom.frag]
    position = atoms.index(atom)
    suffix = '.2' * position
    if position != len(atoms) - 1:
        suffix += '.1'
    if len(scope.frag_src) > 1:
        fragments = sorted(scope.frag_src)
        part = fragments.index(atom.frag)
        suffix = '.2' * part + ('.1' if part != len(fragments) - 1 else '') + suffix
    return 'constraints' + suffix


def replace_wires(term, function):
    return re.sub(r'\bw_\d+_\d+\b', lambda match: function(match[0]), term)


def expand(scope, term):
    def wire(name):
        entry = scope.wires[name]
        if entry.src == 'exists':
            return name
        return '(' + expand(scope, entry.term) + ')'
    return replace_wires(term, wire)


def binary(scope, wire, operation):
    head, arguments = app_split(scope.wires[wire].term)
    meta.require(head == 'MxxRuntime.' + operation and len(arguments) == 2,
                 f'{scope.name}.{wire}: expected {operation}')
    return tuple(map(strip_parens, arguments))


def row_parts(scope, output):
    subtotal, noise = binary(scope, output, 'matrixAdd')
    keypart, targetpart = binary(scope, subtotal, 'matrixSub')
    left, right = binary(scope, keypart, 'matrixAdd')
    mask, key0 = binary(scope, left, 'matrixMulScalarLeft')
    unit, key1 = binary(scope, right, 'matrixMulScalarLeft')
    target, gadget = binary(scope, targetpart, 'matrixMulScalarLeft')
    noise0, noise1 = binary(scope, noise, 'matrixSub')
    return dict(mask=mask, unit=unit, key0=key0, key1=key1, target=target,
                gadget=gadget, noise0=noise0, noise1=noise1, output=output)


