#!/usr/bin/env python3
"""Generate the per-scope role adapters `Gen_<Stage>_Scopes.lean` (L2).

For every scope `S` of a stage with a role from `xroles.py`, emits

    theorem S.sem {…} (h : S backend hashModel params i… inputs outputs) : <Role>.Spec … inputs outputs

proved by destructuring the scope once (its `∃` chain or `∃ witness`, then the conjunction of its
`constraints_k` fragments) and applying the role lemma of `GenIface.lean`; a loop parent passes its
child's adapter as the step (`fun i cur next hb ↦ Child.sem hb`). Encoding-level roles use the
generated computation bundles `<Role>.Comp` of `GenIface.lean` (see `gen_bundles` below), whose
adapter is the scope itself up to the bundle's parameters.

Usage: gen_adapters.py <generated dir> <out dir> <Module>… [--only role,role]
"""
import collections
import re
import sys

sys.path.insert(0, __file__.rsplit('/', 1)[0])
import xmodel  # noqa: E402
import xroles  # noqa: E402
import xbundle  # noqa: E402

PRELUDE = '''import {module}
import GenIface

/-! Generated by `generator/gen_adapters.py`: the role adapters of `{module}` (see `GenIface`). -/

set_option maxHeartbeats 4000000
set_option maxRecDepth 16384
set_option linter.unusedVariables false

namespace {module}

open RefreshTopProof.GenIface
'''


class Fail(Exception):
    pass


# --------------------------------------------------------------------------- scope helpers

def sig_names(s):
    """Parameter names of `def S` (unnamed ones renamed), and the binder list."""
    out = []
    k = 0
    for n, t in s.sig:
        if n == '_':
            n = f'x_{k}'
            k += 1
        out.append((n, t))
    return out


def header(s):
    names = sig_names(s)
    binders = ' '.join('{%s : %s}' % (n, t) for n, t in names)
    call = f'{s.name} ' + ' '.join(n for n, _ in names)
    return binders, call, [n for n, _ in names]


def index_names(s):
    """The names under which the scope's index binders appear in `header` (by position)."""
    names = sig_names(s)
    return [n for (n, t) in names if t == 'Nat']


def exists_order(s):
    src = s.body_src or s.def_src
    return re.findall(r'∃ \((w_\d+(?:_\d+)?(?:_concat_\d+)?) : ', src)


def frag_atoms(s):
    """Atoms of the def-form fragments in order: list of lists of (text) per fragment."""
    out = []
    for k in sorted(s.frag_src):
        _, body = s.frag_src[k]
        out.append(xmodel.split_conj(body))
    return out


def subst_binders(term, s):
    """Rename the scope's own index binders (`i_k` in the def) to the header names."""
    names = sig_names(s)
    orig = [n for n, t in s.sig if t == 'Nat']
    new = [n for n, t in names if t == 'Nat']
    for o, nn in zip(orig, new):
        if o != '_' and o != nn:
            term = re.sub(rf'\b{o}\b', nn, term)
    return term


def inline(s, term, depth=0):
    """Inline `let` wires and input wires (as `inputs.…` projections) into `term`."""
    if depth > 50:
        raise Fail('inline depth')

    def rep(m):
        w = s.wires.get(m.group(0))
        if w is None:
            return m.group(0)
        if w.src == 'input':
            return w.term
        if w.src == 'let':
            t = w.term
            if t.startswith('(') and ' : ' in t and xmodel.matching(t, 0) == len(t) - 1:
                t = t  # typed ascription, keep
            return '(' + inline(s, t, depth + 1) + ')'
        return m.group(0)
    return re.sub(r'\bw_\d+(?:_\d+)?(?:_concat_\d+)?\b', rep, term)


def wire_term(s, w):
    return subst_binders(inline(s, w), s)


def tup(items):
    out = '()'
    for x in reversed(items):
        out = f'({x}, {out})'
    return out


def fin_match(k, cases, fallback='absurd h (by omega)'):
    """`fun c ↦ match c with | ⟨0, _⟩ => e0 | … | ⟨_ + k, h⟩ => fallback`."""
    arms = ' '.join(f'| ⟨{j}, _⟩ => {e}' for j, e in enumerate(cases))
    return f'(fun c ↦ match c with {arms} | ⟨_ + {k}, h⟩ => {fallback})'


def pattern(s, names_per_frag, exist_names=None, witness=False):
    """rcases pattern for the def form of `s`."""
    ex = exist_names if exist_names is not None else exists_order(s)
    if len(names_per_frag) == 1:
        frags = list(names_per_frag[0])
    else:
        frags = ['⟨' + ', '.join(f) + '⟩' for f in names_per_frag]
    if witness:
        return '⟨wit, ' + ', '.join(frags) + '⟩'
    return '⟨' + ', '.join(list(ex) + frags) + '⟩'


def atom_names(s, prefix='a'):
    """Name every atom of every fragment; returns (names_per_frag, flat list of (name, text))."""
    per, flat = [], []
    for k, atoms in enumerate(frag_atoms(s)):
        names = []
        for j, t in enumerate(atoms):
            n = f'{prefix}{k}_{j}'
            names.append(n)
            flat.append((n, t.strip()))
        per.append(names)
    return per, flat


def first_out(flat):
    for n, t in flat:
        if t.startswith('outputs = '):
            return n, t
    return None, None


def use_rfl_out(per, flat):
    """Replace the output equation's name by `rfl` (substituting `outputs`)."""
    n, t = first_out(flat)
    return [[('rfl' if x == n else x) for x in f] for f in per]


# --------------------------------------------------------------------------- role adapters

def ad_gather_unpack(s, info, cx):
    k = info['params']['k']
    per, flat = atom_names(s)
    per = use_rfl_out(per, flat)
    gets = [n for n, t in flat if 'familyGetDynamic' in t]
    lo = [n for n, t in flat if t.startswith('0 ≤ ')][0]
    hi = [n for n, t in flat if re.match(r'^w_\d+_\d+ < ', t)][0]
    idxw = re.match(r'^MxxRuntime\.familyGetDynamic \S+ (\S+) ', dict(flat)[gets[0]]).group(1)
    idx = wire_term(s, idxw)
    binders, call, _ = header(s)
    concl = f'GatherUnpack.Spec (k := {k}) inputs {idx} outputs'
    proof = f'''  obtain {pattern(s, per)} := h
  exact GatherUnpack.sem {lo} {hi} {fin_match(k, gets)}'''
    return binders, call, concl, proof


def state_and_fams(s, k):
    ins = [w for w in s.wires.values() if w.src == 'input']
    terms = [w.term for w in ins]
    return terms[:k], terms[k:2 * k], terms[2 * k:]


def ad_sum_members_step(s, info, cx):
    k = info['params']['k']
    per, flat = atom_names(s)
    per = use_rfl_out(per, flat)
    gets = [n for n, t in flat if 'familyGetDynamic' in t]
    lo = [n for n, t in flat if t.startswith('0 ≤ ')][0]
    hi = [n for n, t in flat if re.match(r'^w_\d+_\d+ < ', t)][0]
    idxw = re.match(r'^MxxRuntime\.familyGetDynamic \S+ (\S+) ', dict(flat)[gets[0]]).group(1)
    idx = wire_term(s, idxw)
    st, fams, rest = state_and_fams(s, k)
    binders, call, _ = header(s)
    got = [re.match(r'^MxxRuntime\.familyGetDynamic \S+ \S+ (\S+)$', dict(flat)[g]).group(1) for g in gets]
    concl = f'MemberStep.Spec (k := {k}) {tup(fams)} {idx} {tup(st)} outputs'
    proof = f'''  obtain {pattern(s, per)} := h
  exact MemberStep.sem (got := {tup(got)}) {lo} {hi} {fin_match(k, gets)} {fin_match(k, ['rfl'] * k)}'''
    return binders, call, concl, proof


def ad_sum_members_step1(s, info, cx):
    per, flat = atom_names(s)
    per = use_rfl_out(per, flat)
    gets = [n for n, t in flat if 'familyGetDynamic' in t]
    if len(gets) != 1:
        raise Fail('step1 with several reads')
    lo = [n for n, t in flat if t.startswith('0 ≤ ')][0]
    hi = [n for n, t in flat if re.match(r'^w_\d+_\d+ < ', t)][0]
    m = re.match(r'^MxxRuntime\.familyGetDynamic (\S+) (\S+) (\S+)$', dict(flat)[gets[0]])
    fam, idx = wire_term(s, m.group(1)), wire_term(s, m.group(2))
    st = [w for w in s.wires.values() if w.src == 'input'][0].term
    binders, call, _ = header(s)
    concl = f'MemberStep1.Spec {fam} {idx} {st} outputs'
    proof = f'''  obtain {pattern(s, per)} := h
  exact MemberStep1.sem {lo} {hi} {gets[0]} rfl'''
    return binders, call, concl, proof


def ad_round_step(s, info, cx):
    per, flat = atom_names(s)
    per = use_rfl_out(per, flat)
    gets = [n for n, t in flat if 'familyGetDynamic' in t]
    lo = [n for n, t in flat if t.startswith('0 ≤ ')][0]
    hi = [n for n, t in flat if re.match(r'^w_\d+_\d+ < ', t)][0]
    nz = [n for n, t in flat if '≠ 0' in t][0]
    m = re.match(r'^MxxRuntime\.familyGetDynamic (\S+) (\S+) (\S+)$', dict(flat)[gets[0]])
    vals = wire_term(s, m.group(1))
    # the loop index binder (last index), the offset h and the divisor d from the lets
    ix = index_names(s)[-1]
    tm = {w.name: w for w in s.wires.values()}
    div = [w for w in tm.values() if w.src == 'let' and ' / ' in (w.term or '')][0]
    dv = re.match(r'^\((w_\d+_\d+) / (w_\d+_\d+)\)$', div.term)
    add = tm[dv.group(1)].term
    hm = re.match(r'^\((w_\d+_\d+) \+ (w_\d+_\d+)\)$', add)
    hterm, dterm = wire_term(s, hm.group(2)), wire_term(s, dv.group(2))
    st = [w for w in s.wires.values() if w.src == 'input'][0].term
    binders, call, _ = header(s)
    concl = f'RoundStep.Spec {vals} {hterm} {dterm} {ix} {st} outputs'
    proof = f'''  obtain {pattern(s, per)} := h
  exact RoundStep.sem {ix} {lo} {hi} {gets[0]} {nz} rfl'''
    return binders, call, concl, proof


def loop_atom(flat, child):
    for n, t in flat:
        if t.startswith('MxxIR.IterRuns') and f'=> {child} ' in t:
            return n
    raise Fail(f'no loop atom for {child}')


def par_atom(flat, child):
    for n, t in flat:
        if t.startswith('(∀ i : Fin') or t.startswith('∀ i : Fin'):
            if f' {child} ' in t:
                return n
    raise Fail(f'no par atom for {child}')


def ad_decode_column(s, info, cx):
    per, flat = atom_names(s)
    per = use_rfl_out(per, flat)
    ix = index_names(s)[-1]
    sl = [n for n, t in flat if t.startswith('MxxRuntime.sliceMatrix')][0]
    pv = [n for n, t in flat if t.startswith('MxxRuntime.polynomialValues')][0]
    ub = [n for n, t in flat if re.match(r'^\(1 \+ \(Int\.ofNat \w+\)\) ≤ ', t)][0]
    child = s.loops[0].loop.child
    lp = loop_atom(flat, child)
    x = [w for w in s.wires.values() if w.src == 'input'][1].term
    # the child's h and d are the parent's inputs 3 and 4 (positions of the loop args)
    ch = cx.sc[child]
    loopargs = s.loops[0].loop.args
    hterm, dterm = wire_term(s, loopargs[2]), wire_term(s, loopargs[3])
    binders, call, _ = header(s)
    concl = f'DecodeColumn.Spec {x} {hterm} {dterm} {ix} {[w for w in s.wires.values() if w.src == "input"][0].term} outputs'
    proof = f'''  obtain {pattern(s, per, witness=True)} := h
  exact DecodeColumn.sem {ix} (by have := {ub}; simp only [Int.ofNat_eq_natCast] at this; omega) {sl} {pv}
    {lp} (fun j c c' hb ↦ {child}.sem hb)'''
    return binders, call, concl, proof


def getdyn(t):
    m = re.match(r'^MxxRuntime\.familyGet(?:Dynamic|Static) (\S+) (\(\d+\)|\S+) (\S+)$', t)
    return m.groups() if m else None


def loop_child_atom(s, flat, kind):
    for a in s.loops:
        if a.loop.kind == kind:
            n = loop_atom(flat, a.loop.child) if kind == 'seq' else par_atom(flat, a.loop.child)
            return a.loop, n
    raise Fail(f'no {kind} loop')


def mat_cols(t):
    """(rows, columns) of the last `ExactMatrix q n r c` in the type text `t`."""
    i = t.rfind('ExactMatrix ')
    if i < 0:
        return None
    rest = t[i + len('ExactMatrix '):]
    parts = [p for p in xmodel.split_top(rest, ' ') if p]
    try:
        return int(xmodel.strip_parens(parts[2])), int(xmodel.strip_parens(parts[3]).rstrip(')'))
    except (IndexError, ValueError):
        return None


def ad_rowsum(s, info, cx):
    k, W = info['params']['k'], info['params']['W']
    per, flat = atom_names(s)
    per = use_rfl_out(per, flat)
    o = index_names(s)[-1]
    T = dict(flat)
    statics = [(n, getdyn(t)) for n, t in flat if t.startswith('MxxRuntime.familyGetStatic')]
    s0 = [n for n, g in statics if g[1] == '(0)']
    s1 = [n for n, g in statics if g[1] == '(1)']
    cells = [g[0] for n, g in statics if g[1] == '(0)']
    s0w = [g[2] for n, g in statics if g[1] == '(0)']
    s1w = [g[2] for n, g in statics if g[1] == '(1)']
    pl, pa = loop_child_atom(s, flat, 'par')
    sl, sa = loop_child_atom(s, flat, 'seq')
    init = [wire_term(s, x) for x in xmodel.tuple_items(sl.init)]
    binders, call, _ = header(s)
    concl = f'RowSum.Spec (k := {k}) inputs {W} {o} outputs'
    proof = f"""  obtain {pattern(s, per, witness=True)} := h
  exact RowSum.sem (k := {k}) (W := {W}) (fams := inputs) (cells := {tup(cells)}) (s0 := {tup(s0w)}) (s1 := {tup(s1w)})
    (init := {tup(init)}) {o} (by decide) (fun j ↦ by gen_omega) (fun i ↦ by gen_omega)
    (fun j ↦ {pl.child}.sem ({pa} j)) {fin_match(k, s0)} {fin_match(k, s1)} {fin_match(k, ['rfl'] * k)}
    (MemberSum.sem (k := {k}) {sa} (fun i cur next hb ↦ {sl.child}.sem hb))"""
    return binders, call, concl, proof


def ad_columns_step(s, info, cx):
    k, W = info['params']['k'], info['params']['W']
    per, flat = atom_names(s)
    per = use_rfl_out(per, flat)
    i = index_names(s)[-1]
    reads = [(n, getdyn(t)) for n, t in flat if t.startswith('MxxRuntime.familyGetDynamic')]
    idxs = list(dict.fromkeys(g[1] for _, g in reads))
    if len(idxs) != 2:
        raise Fail('column step reads')
    r0 = [(n, g) for n, g in reads if g[1] == idxs[0]]
    r1 = [(n, g) for n, g in reads if g[1] == idxs[1]]
    fams = [g[0] for _, g in r0]
    tens = [(n, xmodel.app_split(t)[1]) for n, t in flat if t.startswith('MxxRuntime.tensorRuns')]
    tw = [a[2] for _, a in tens]
    cw = [a[1] for _, a in tens]
    hc = [n for n, t in flat if re.match(r'^\(\(1 \+ \(Int\.ofNat \w+\)\)\) < ', t)][0]
    sl, sa = loop_child_atom(s, flat, 'seq')
    init = [wire_term(s, x) for x in xmodel.tuple_items(sl.init)]
    # C from the unit row ascription, m from the families' element type
    ur = [w for w in s.wires.values() if w.term and 'unitRow' in w.term][0]
    C = mat_cols(ur.term)[1]
    m = mat_cols(s.inputs[k])[1]
    binders, call, _ = header(s)
    st = [w.term for w in s.wires.values() if w.src == 'input'][:k]
    concl = f'ColStep.Spec (k := {k}) (C := {C}) (m := {m}) {tup([wire_term(s, f) for f in fams])} {W} {i} {tup(st)} outputs'
    proof = f"""  obtain {pattern(s, per, witness=True)} := h
  exact ColStep.sem (C := {C}) (m := {m}) (W := {W}) (k := {k}) (by decide) (fams := {tup([wire_term(s, f) for f in fams])})
    (s0 := {tup([g[2] for _, g in r0])}) (s1 := {tup([g[2] for _, g in r1])}) (init := {tup(init)})
    (col := {tup(xmodel.tuple_items(sl.final))}) (t := {tup(tw)}) (by decide) {i} (by have := {hc}; gen_omega)
    (by gen_omega) (by gen_omega) (fun j ↦ by gen_omega)
    {fin_match(k, [n for n, _ in r0])} {fin_match(k, [n for n, _ in r1])} {fin_match(k, ['rfl'] * k)}
    (MemberSum.sem (k := {k}) {sa} (fun i cur next hb ↦ {sl.child}.sem hb)) {fin_match(k, [n for n, _ in tens])}
    {fin_match(k, ['rfl'] * k)}"""
    return binders, call, concl, proof


def ad_slice_step(s, info, cx):
    per, flat = atom_names(s)
    per = use_rfl_out(per, flat)
    i = index_names(s)[-1]
    sl = [n for n, t in flat if t.startswith('MxxRuntime.sliceMatrix')][0]
    te = [n for n, t in flat if t.startswith('MxxRuntime.tensorRuns')][0]
    hc = [n for n, t in flat if re.match(r'^\(\(1 \+ \(Int\.ofNat \w+\)\)\) < ', t)][0]
    ins = [w.term for w in s.wires.values() if w.src == 'input']
    ur = [w for w in s.wires.values() if w.term and 'unitRow' in w.term][0]
    C = mat_cols(ur.term)[1]
    xcols = mat_cols(s.inputs[1])[1]
    m = xcols // C
    binders, call, _ = header(s)
    concl = f'ColSliceStep.Spec (C := {C}) (m := {m}) {ins[1]} {ins[2]} {i} {ins[0]} outputs'
    proof = f"""  obtain {pattern(s, per)} := h
  exact ColSliceStep.sem (C := {C}) (m := {m}) {i} (by have := {hc}; gen_omega) (by gen_omega) (by gen_omega)
    {sl} {te} rfl"""
    return binders, call, concl, proof


