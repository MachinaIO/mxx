def import_modules(package, view, modules):
    text = ['import W_Stage_import_0_Facts\nimport W_Stage_import_1_Facts\n',
            'import Gen_W_Stage_import_0_Scopes\nimport Gen_W_Stage_import_1_Scopes\n',
            'import W_Claim\nimport Dio2InitialTargets\n\n',
            '/-! Generated import identities and relation transport.\n'
            'Copy outputs are aliases in v2, not calls to retained unused scopes.\n'
            'The import-1 source is the refreshed online-0 output, not S_0.\n'
            'Plaintext agreement with external exponents remains a separate premise. -/\n\n',
            HEADER, 'open GeneratedClaim W_GeneratedClaim\n\n']
    n, columns = view['ring_dimension'], view['columns']
    stages = claim_stages(package)
    for step in range(2):
        module = modules[f'import_{step}']
        scope = module.root
        output_wires = meta.output_wires(scope)
        stage = f'W_Stage_import_{step}'
        out_type = '(' + dict(scope.sig)['outputs'].replace('generatedRoot.', stage + '.generatedRoot.') + ')'
        in_type = '(' + dict(scope.sig)['inputs'].replace('generatedRoot.', stage + '.generatedRoot.') + ')'
        text.append(f'''/-- All imported roots and helpers, with label publics evaluated symbolically. -/
noncomputable def import{step}_expected (inputs : {in_type}) : {out_type} :=
''')
        for wire in scope.wires.values():
            if wire.src == 'input':
                text.append(f'  let {wire.name} := {wire.term}\n')
        rewrites = []
        definitions = []
        for atom in scope.atoms:
            if not atom.loop:
                continue
            parent = atom.loop
            meta.require(len(parent.outs) == 3 and len(parent.args) == 4,
                         'unexpected imported label shape')
            row0, row1, coefficient, exponent = [arg.replace(' i', ' member') for arg in parent.args]
            expressions = [row0, row1, f'MxxRuntime.multiplyMonomial (MxxRuntime.liftInteger ({coefficient})) ({exponent})']
            for index, (out, expression) in enumerate(zip(parent.outs, expressions)):
                wire = out.split()[0]
                count = meta.family_count(scope.wires[wire].type)
                text.append(f'  let {wire} := fun member : Fin {count} ↦ {expression}\n')
                rewrites.append('eq_' + wire)
                local_expression = replace_wires(expression, lambda w: f'({stage}.generatedRoot.{w} ctx)')
                select = 'Prod.fst' if index == 0 else '(fun result ↦ result.2.1)' if index == 1 else '(fun result ↦ result.2.2.1)'
                definitions.append(f'''  have eq_{wire} : {stage}.generatedRoot.{wire} ctx =
      fun member : Fin {count} ↦ {local_expression} := by
    funext member
    exact congrArg {select} ({stage}.{parent.child}.sem ({atom_fact(atom)} member))
''')
        for wire in scope.wires.values():
            if wire.src == 'let':
                text.append(f'  let {wire.name} := {wire.term}\n')
        out_atom = next(a for a in scope.atoms if a.kind == 'out')
        text.append('  ' + out_atom.args[0] + '\n\n')
        text.append(f'''/-- Exact import semantics for every output at once, without expanding family members. -/
theorem import{step}_spec {{params : {stage}.Params}} {{inputs : _}} {{outputs : _}}
    (h : {stage}.generatedRoot params inputs outputs) : outputs = import{step}_expected inputs := by
  obtain ⟨witness, hbody⟩ := h
  let ctx : {stage}.generatedRoot.Ctx params := ⟨inputs, witness⟩
  have F := {stage}.generatedRoot.facts ctx hbody
  rw [{atom_fact(out_atom)}]
''')
        text.extend(definitions)
        text.append(f'  unfold {stage}.generatedRoot.outs import{step}_expected\n')
        text.append('  simp only [' + ', '.join(rewrites) + '] <;> rfl\n\n')
        text.append(f'''/-- Any root-family/online-input projection preserves an established encoding relation. -/
theorem import{step}_online_from_rows {{params : {stage}.Params}} {{inputs : _}} {{outputs : _}}
    (h : {stage}.generatedRoot params inputs outputs)
    (rows : {out_type} → Fin 2 → ExactMatrix {stage}.modulus_0 {n} 1 {columns})
    {{sm : ErrorPoly {n}}} {{key : Fin 2 → Fin 2 → ExactMatrix {stage}.modulus_0 {n} 1 {columns}}}
    {{target : Fin 2 → ExactMatrix {stage}.modulus_0 {n} 1 {columns}}} {{bound : Nat}}
    (hrel : Rel sm key target (rows (import{step}_expected inputs)) bound) :
    Rel sm key target (rows outputs) bound := by
  rw [import{step}_spec h]
  exact hrel

''')
        for atom in scope.atoms:
            if not atom.loop:
                continue
            parent = atom.loop
            meta.require(len(parent.outs) == 3, 'unexpected imported label arity')
            wire = parent.outs[2].split()[0]
            count = meta.family_count(scope.wires[wire].type)
            coefficient, exponent = [expand(scope, arg.replace(' i', ' member')) for arg in parent.args[2:]]
            out = output_projection(scope, output_wires.index(wire))
            text.append(f'''theorem import{step}_payload_{identifier(parent.child)}
    {{params : W_Stage_import_{step}.Params}} {{inputs : _}} {{outputs : _}}
    (h : W_Stage_import_{step}.generatedRoot params inputs outputs) (member : Fin {count}) :
    {out} member = fun _ _ ↦ reducePoly W_Stage_import_{step}.modulus_0 {n}
      (message ({coefficient}) ({exponent})) := by
  obtain ⟨witness, hbody⟩ := h
  let ctx : W_Stage_import_{step}.generatedRoot.Ctx params := ⟨inputs, witness⟩
  have F := W_Stage_import_{step}.generatedRoot.facts ctx hbody
  rw [{atom_fact(next(a for a in scope.atoms if a.kind == 'out'))}]
  have hscope := W_Stage_import_{step}.{parent.child}.sem ({atom_fact(atom)} member)
  exact (congrArg (fun result ↦ result.2.2.1) hscope).trans
    (multiplyMonomial_liftInteger _ _)

''')
        text.append(f'''/-- The actual claim import run, with source connections resolved by `W_Claim`. -/
theorem import{step}_claim_runs {{hashModel : HashModel}} {{external : GeneratedClaim.ExternalInputs}}
    {{execution : GeneratedClaim.Execution}} (h : W_GeneratedClaim.Runs hashModel external execution) :
    ''' + stages[f'import_{step}'][1].strip().removesuffix(' ∧') + f''' :=
  {claim_hypothesis(f'import_{step}', stages)}

''')
        text.append(f'''/-- The matching online run consumes the import outputs wired by `W_Claim`. -/
theorem import{step}_online_claim_runs {{hashModel : HashModel}} {{external : GeneratedClaim.ExternalInputs}}
    {{execution : GeneratedClaim.Execution}} (h : W_GeneratedClaim.Runs hashModel external execution) :
    ''' + stages[f'online_{step}'][1].strip().removesuffix(' ∧') + f''' :=
  {claim_hypothesis(f'online_{step}', stages)}

''')
    text.append('end Dio2Proof\n')
    return ''.join(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('package', type=Path)
    parser.add_argument('--output-dir', type=Path)
    args = parser.parse_args()
    metadata = meta.extract(args.package)
    view = metadata['views']['worst']
    output = args.output_dir or args.package / 'proof'
    output.mkdir(parents=True, exist_ok=True)
    modules = {stage: meta.Module(args.package / 'worst', 'W_Stage_' + stage, {})
               for stage in ['initial', 'anchors', 'preimages_0_0', 'preimages_1_1', 'import_0', 'import_1']}
    initial = Initial(args.package, view, modules)
    rows, targets = initial.generate()
    (output / 'Dio2Initial.lean').write_text('import W_Stage_initial_Facts\nimport Dio2Inv\nimport ExponentRefresh\nimport ExponentIterate\n\n' + INITIAL_GENERIC + initial_basic(initial) + 'end Dio2Proof\n')
    (output / 'Dio2InitialRows.lean').write_text(rows)
    (output / 'Dio2InitialTargets.lean').write_text(targets)
    (output / 'Dio2Preimage.lean').write_text(preimage_modules(args.package, view, modules))
    (output / 'Dio2Import.lean').write_text(import_modules(args.package, view, modules))


if __name__ == '__main__':
    main()
