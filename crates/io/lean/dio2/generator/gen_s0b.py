"""Generate symbolic step-zero certificate and import-one assembly.

Export geometry is read from checked dio2_meta metadata. Only the prime family
is specialized; no label, part, digit, or coefficient family is expanded.
Prerequisites are the generated s0 support, InitialTargets, and shared
Online1Inputs interfaces. --modules permits independent groups to regenerate
before the step-one interface has been published for a package. All requested
sources are constructed successfully before any output file is replaced.
"""

