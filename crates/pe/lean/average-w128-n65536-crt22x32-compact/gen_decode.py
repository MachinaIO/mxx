    anchors = []
    for j in range(128):
        h, c, a = rot[12 + 4 * j]
        assert c == 1 + 1024 * j and a == 11 + 4 * j, (j, c, a)
        anchors.append(f"Stage_decode.generatedRoot.w_{10 + 4 * j}_0 ctx")
        lines.append(f"  have e{j} := routing_slot (i := {j}) (by norm_num) (F.c{chunk_of[h]}.{h})")
