#!/usr/bin/env bash
# Checks the Lean packages built on mathcal-A: the core's (crates/core/lean), the lattice
# leaves' proofs (crates/ir-core/lean/leaves), and, when `cargo test -p mxx-core claims` has
# written them, the generated example claims (test_data/core_claims) and their proofs
# (crates/core/lean/MxxCore/Proofs, crates/ir-core/lean/leaves/MxxLatticeLeaves/Proofs).
#
# MATHCAL_A_DIR must point at a mathcal-A checkout whose `lake build` has been run; its build
# outputs are only read. Each package's modules are compiled in dependency order into its own
# `.lake/build`, then every leaf `spec` theorem's axioms are printed.
set -euo pipefail
: "${MATHCAL_A_DIR:?set MATHCAL_A_DIR to a built mathcal-A checkout}"
ROOT=$(cd "$(dirname "$0")/.." && pwd)
LEAN=${LEAN:-$(elan which lean 2>/dev/null || command -v lean)}
BASE_PATH=$(ls -d "$MATHCAL_A_DIR"/.lake/packages/*/.lake/build/lib/lean | tr '\n' ':')$MATHCAL_A_DIR/.lake/build/lib/lean
LEAN_PATH=$BASE_PATH:$ROOT/crates/core/lean/.lake/build/lib/lean:$ROOT/crates/ir-core/lean/leaves/.lake/build/lib/lean:$ROOT/test_data/core_claims/.lake/build/lib/lean
export LEAN_PATH
compile() {
  local package=$1 module=${2%.lean}
  local out=$package/.lake/build/lib/lean
  mkdir -p "$out/$(dirname "$module")"
  (cd "$package" && "$LEAN" -o "$out/$module.olean" -i "$out/$module.ilean" "$2")
}
core=$ROOT/crates/core/lean
compile "$core" MxxCore/Algorithm.lean
compile "$core" MxxCore/Glue.lean
compile "$core" MxxCore/Sym.lean
compile "$core" MxxCore/Copy.lean
compile "$core" MxxCore/Leaf.lean
compile "$core" MxxCore/Compose.lean
for f in "$core"/MxxCore/Examples/*.lean; do compile "$core" "MxxCore/Examples/$(basename "$f")"; done
compile "$core" MxxCore.lean
leaves=$ROOT/crates/ir-core/lean/leaves
for f in "$leaves"/MxxLatticeLeaves/Code/*.lean; do compile "$leaves" "MxxLatticeLeaves/Code/$(basename "$f")"; done
for f in "$leaves"/MxxLatticeLeaves/Math/*.lean; do compile "$leaves" "MxxLatticeLeaves/Math/$(basename "$f")"; done
for f in "$leaves"/MxxLatticeLeaves/*.lean "$leaves"/MxxLatticeLeaves/Examples/*.lean; do
  compile "$leaves" "${f#"$leaves"/}"
done
compile "$leaves" MxxLatticeLeaves.lean
claims=$ROOT/test_data/core_claims
if [ -d "$claims/Generated" ]; then
  for f in "$claims"/Generated/*/Images.lean "$claims"/Generated/*/Progs.lean; do
    compile "$claims" "${f#"$claims"/}"
  done
  for f in "$claims"/Generated/*.lean; do compile "$claims" "${f#"$claims"/}"; done
  # Run proofs generated by `mxx_core::compose`, when an image's glue is straight-line.
  for f in "$claims"/Generated/*/Run/*.lean; do
    [ -e "$f" ] && compile "$claims" "${f#"$claims"/}"
  done
  # Proofs of generated claims.
  for f in "$core"/MxxCore/Proofs/*.lean; do compile "$core" "MxxCore/Proofs/$(basename "$f")"; done
  for f in "$leaves"/MxxLatticeLeaves/Proofs/*.lean; do
    compile "$leaves" "MxxLatticeLeaves/Proofs/$(basename "$f")"
  done
fi
check=$(mktemp --suffix=.lean)
trap 'rm -f "$check"' EXIT
proofs=()
runs=()
if [ -d "$claims/Generated" ]; then
  for f in "$core"/MxxCore/Proofs/*.lean; do proofs+=("MxxCore.Proofs.$(basename "$f" .lean)"); done
  for f in "$leaves"/MxxLatticeLeaves/Proofs/*.lean; do
    proofs+=("MxxLatticeLeaves.Proofs.$(basename "$f" .lean)")
  done
  for f in "$claims"/Generated/*/Run/*.lean; do
    [ -e "$f" ] || continue
    m=${f#"$claims"/}
    m=${m%.lean}
    runs+=("${m//\//.}")
  done
fi
{
  echo "import MxxLatticeLeaves"
  for m in "${proofs[@]}" "${runs[@]}"; do echo "import $m"; done
  for m in "${proofs[@]}"; do echo "#print axioms $m.correctness"; done
  for m in "${runs[@]}"; do echo "#print axioms $m.halts"; done
  for f in "$leaves"/MxxLatticeLeaves/*.lean; do
    echo "#print axioms MxxLatticeLeaves.$(basename "$f" .lean).spec"
    echo "#print axioms MxxLatticeLeaves.$(basename "$f" .lean).byteSpec"
  done
} > "$check"
"$LEAN" "$check"
