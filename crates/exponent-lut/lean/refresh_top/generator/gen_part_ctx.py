#!/usr/bin/env python3
"""Generate `Gen_Part_Ctx.lean` (WP D): the instance contexts of a run.

For every stage of the Claim's `Runs` with an instance root (`Stage_X.generatedRoot` running
`∀ i : Fin S, I … i …`), the theorem `inst_<Stage_X>` turns a run into, at instance `i`, the root
context `rM`, the instance context `cM`, the instance facts `I.Facts cM (rootOuts rM i)` and exactly
the four hypotheses the stage links of `Gen_Stage_Links` take (`hout`, `hinst`, `hin`, `hroot`):

    ∃ rM cM, I.Facts cM (rootOuts rM i) ∧ execution.«stage_k» = generatedRoot.outs rM ∧
      rootOuts rM i = I.outs cM ∧ cM.inputs = rootArgs rM i ∧ rM.inputs = claimArgs external execution

The root facts come from `generatedRoot.facts`, the instance facts from the root's
`generatedRoot.h<K>_at`, the output equations from the facts records' `hout` fields.

Usage: gen_part_ctx.py <generated dir> <out file>
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
import xmodel  # noqa: E402
from gen_stage_links import Stage  # noqa: E402
from gen_instance import facts_fields  # noqa: E402


def gen(gdir):
    calls = xmodel.parse_claim(gdir)
    out = ['import Gen_Stage_Links', '',
           '/-! Generated by `generator/gen_part_ctx.py` (WP D): the instance contexts of a run and the',
           'hypotheses of the stage links (see the generator\'s docstring). -/', '',
           'set_option maxHeartbeats 4000000', 'set_option maxRecDepth 16384', '',
           'namespace RefreshTopProof.GenPartCtx', '',
           'open GeneratedClaim RefreshTopProof.StageLinks', '']
    n = 0
    for k, c in enumerate(calls):
        if not c.get('module'):
            continue
        s = Stage(gdir, c)
        if not s.ok:
            continue
        text = open(f'{gdir}/{s.M}_Facts.lean').read()
        at = re.search(r'^theorem generatedRoot\.(h\d+_\d+_at) ', text, re.M).group(1)
        fields = facts_fields(text, s.inst)
        hf = [f for f, (_, t) in fields.items() if t.strip() == f'outputs = {s.inst}.outs ctx']
        rf = facts_fields(text, 'generatedRoot')
        rh = [f for f, (_, t) in rf.items() if t.strip() == 'outputs = generatedRoot.outs ctx']
        if len(hf) != 1 or len(rh) != 1:
            continue
        hfrag, rfrag = fields[hf[0]][0], rf[rh[0]][0]
        proj = 'hR' + '.2' * k + ('.1' if k < len(calls) - 1 else '')
        ctx = f'{s.M}.generatedRoot.Ctx Backend.backend model {s.params}'
        out.append(f'''/-- The instance `i` of `{s.M}` in a run: contexts, facts and the stage-link hypotheses. -/
theorem inst_{s.M} {{model : MxxRuntime.HashModel}} {{external : ExternalInputs}} {{execution : Execution}}
    (hR : Runs model external execution) (i : Fin {s.S}) :
    ∃ (rM : {ctx}) (cM : {s.M}.{s.inst}.Ctx Backend.backend model {s.params} (i : Nat)),
      {s.M}.{s.inst}.Facts cM ({s.M}.rootOuts rM i) ∧ {s.stage_out} = {s.M}.generatedRoot.outs rM ∧
      {s.M}.rootOuts rM i = {s.M}.{s.inst}.outs cM ∧ cM.inputs = {s.M}.rootArgs rM i ∧
      rM.inputs = {s.M}.claimArgs external execution := by
  obtain ⟨w, hb⟩ := {proj}
  have FR := {s.M}.generatedRoot.facts (⟨_, w⟩ : {ctx}) hb
  obtain ⟨wi, FI⟩ := {s.M}.generatedRoot.{at} FR i
  exact ⟨⟨_, w⟩, ⟨_, wi⟩, FI, FR.c{rfrag}.{rh[0]}, FI.c{hfrag}.{hf[0]}, rfl, rfl⟩
''')
        n += 1
    out.append('end RefreshTopProof.GenPartCtx\n')
    return '\n'.join(out), n


if __name__ == '__main__':
    txt, n = gen(sys.argv[1])
    open(sys.argv[2], 'w').write(txt)
    print(f'{sys.argv[2]}: {n} theorems')
