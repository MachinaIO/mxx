pub const GENERATOR_VERSION: &str = "mxx-correctness-emitter-v1";

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct EmittedProtocol {
    pub protocol_hash: String,
    pub ir: String,
    pub statement: String,
    pub proof_scaffold: String,
}

#[derive(Debug, Error)]
pub enum EmitError {
    #[error(transparent)]
    Protocol(#[from] ProtocolError),
    #[error("protocol serialization failed: {0}")]
    Serialization(#[from] serde_json::Error),
    #[error("Lean denotation is not implemented for Graph IR node {0}")]
    UnsupportedNode(&'static str),
    #[error("Lean parameter validation cannot evaluate irrational expression {0}")]
    IrrationalConstraint(String),
    #[error("Lean denotation does not yet support child Graph IR scopes")]
    ChildScope,
    #[error("Lean denotation is not implemented for Graph IR wire type {0}")]
    UnsupportedWireType(&'static str),
}

pub fn emit_protocol_for(
    name: &str,
    protocol: &ProtocolDecl,
    module_root: &str,
) -> Result<EmittedProtocol, EmitError> {
    protocol.validate()?;
    ensure_supported_wire_types(protocol)?;
    let normalized = normalized_protocol(protocol)?;
    let canonical = serde_json::to_vec(&normalized)?;
    let protocol_hash = format!("{:x}", Sha256::digest(&canonical));
    let lean_name = lean_identifier(name);
    let syntax_literal = lean_syntax(&normalized, 2);
    let executable = lean_workflow(&lean_name, protocol)?;
    let ir = format!(
        "-- Generated by {GENERATOR_VERSION}; do not edit.\nimport Mxx.Ir\n\nnamespace {module_root}.Generated.{lean_name}\n\ndef {lean_name}_protocolHash : String := \"{protocol_hash}\"\n\n/-- Complete normalized declaration retained as a constructor tree for review and hashing. -/\ndef {lean_name}_protocolSource : Mxx.Ir.Syntax :=\n  {syntax_literal}\n\n{executable}\nend {module_root}.Generated.{lean_name}\n"
    );
    let params = protocol
        .params
        .iter()
        .map(|parameter| {
            let ty = match parameter.kind {
                crate::ParameterKind::Dimension => "Nat",
                crate::ParameterKind::Integer => "Int",
                crate::ParameterKind::Rational => "Rat",
            };
            format!("  {} : {ty}", lean_field_identifier(&parameter.name))
        })
        .collect::<Vec<_>>()
        .join("\n");
    let inputs = protocol
        .correctness
        .protocol_inputs
        .iter()
        .map(|(name, destinations)| -> Result<_, EmitError> {
            let (stage, input) = destinations.first().expect("validated nonempty input mapping");
            let stage = protocol.stages.iter().find(|candidate| &candidate.id == stage).unwrap();
            let wire_type = stage
                .graph
                .root_scope()
                .nodes()
                .iter()
                .find_map(|node| match node.kind() {
                    NodeKind::Input { name, .. } if name == &input.0 => {
                        Some(&node.output_types()[0])
                    }
                    _ => None,
                })
                .expect("validated stage input");
            Ok(format!("  {} : {}", lean_field_identifier(&name.0), lean_wire_type(wire_type)?))
        })
        .collect::<Result<Vec<_>, _>>()?
        .join("\n");
    let mut constrained_graphs =
        protocol.stages.iter().map(|stage| &stage.graph).collect::<Vec<_>>();
    constrained_graphs.push(&protocol.correctness.ideal.graph);
    constrained_graphs
        .extend(protocol.correctness.requires.iter().map(|requirement| &requirement.graph));
    if let Comparator::EqualAfterMap { map } = &protocol.correctness.comparator {
        constrained_graphs.push(&map.graph);
    }
    let constraints = constrained_graphs
        .into_iter()
        .flat_map(|graph| {
            derive_param_constraints(graph)
                .expect("validated protocol graph has derivable parameter constraints")
        })
        .map(|constraint| lean_constraint(&constraint, protocol))
        .collect::<Result<BTreeSet<_>, _>>()?
        .into_iter()
        .collect::<Vec<_>>();
    let params_valid =
        if constraints.is_empty() { "true".to_owned() } else { constraints.join(" &&\n    ") };
    let semantics = lean_correctness_semantics(protocol, &lean_name);
    let statement = format!(
        "-- Generated by {GENERATOR_VERSION}; do not edit.\nimport {module_root}.Generated.{lean_name}.Ir\nimport Mxx.Correctness\n\nset_option linter.unusedVariables false\n\nopen Mxx\n\nnamespace {module_root}.Generated.{lean_name}\n\nstructure {lean_name}Params where\n{params}\n\nstructure {lean_name}Inputs (_p : {lean_name}Params) where\n{inputs}\n\ndef {lean_name}ParamsValid (p : {lean_name}Params) : Bool :=\n  {params_valid}\n\n{semantics}\n\nstructure {lean_name}CorrectStatement (checker : {lean_name}Params → Bool) : Prop where\n  probability_zero :\n    ∀ samplers : MxxSamplerFamily, MxxBoundedSamplerContract samplers →\n    ∀ p : {lean_name}Params, checker p = true → {lean_name}ParamsValid p = true →\n    ∀ x : {lean_name}Inputs p, {lean_name}InputsWF p x → {lean_name}Preconditions p x →\n      {lean_name}FailureProbability samplers p x = 0\n\nend {module_root}.Generated.{lean_name}\n"
    );
    let lower = lower_identifier(name);
    let proof_scaffold = format!(
        "import {module_root}.Generated.{lean_name}.Statement\n\nopen {module_root}.Generated.{lean_name}\n\ndef {lower}Checker : {lean_name}Params → Bool := fun _ => false\n\ntheorem {lower}_correct : {lean_name}CorrectStatement {lower}Checker := by\n  constructor\n  intro samplers contract p checker params x preconditions\n  contradiction\n"
    );
    Ok(EmittedProtocol { protocol_hash, ir, statement, proof_scaffold })
}

fn lean_correctness_semantics(protocol: &ProtocolDecl, lean_name: &str) -> String {
    let params = protocol
        .params
        .iter()
        .map(|parameter| {
            let field = format!("p.{}", lean_field_identifier(&parameter.name));
            let value = match parameter.kind {
                crate::ParameterKind::Dimension => {
                    format!(".integer (Int.ofNat {field})")
                }
                crate::ParameterKind::Integer => format!(".integer {field}"),
                crate::ParameterKind::Rational => format!(".rational {field}"),
            };
            format!("({}, {value})", lean_string(&parameter.name))
        })
        .collect::<Vec<_>>()
        .join(", ");
    let input_well_formedness = protocol
        .correctness
        .protocol_inputs
        .iter()
        .map(|(name, destinations)| {
            let wire_type = protocol_input_wire_type(protocol, destinations);
            lean_input_well_formedness(
                wire_type,
                &format!("x.{}", lean_field_identifier(&name.0)),
                protocol,
            )
        })
        .collect::<Vec<_>>();
    let input_well_formedness = if input_well_formedness.is_empty() {
        "True".to_owned()
    } else {
        input_well_formedness.join(" ∧\n    ")
    };
    let preconditions = protocol
        .correctness
        .requires
        .iter()
        .enumerate()
        .map(|(index, _)| {
            format!(
                "Mxx.Ir.singleBooleanOutput\n      (Mxx.Ir.denotePure {lean_name}_requirement_{index}\n        ({lean_name}ParamEnvironment p) ({lean_name}InputEnvironment p x) |>.getD []) = some true"
            )
        })
        .collect::<Vec<_>>();
    let preconditions =
        if preconditions.is_empty() { "True".to_owned() } else { preconditions.join(" ∧\n    ") };
    let inputs = protocol
        .correctness
        .protocol_inputs
        .iter()
        .map(|(name, destinations)| {
            let (stage_id, input_name) = destinations.first().expect("validated input mapping");
            let stage = protocol
                .stages
                .iter()
                .find(|stage| &stage.id == stage_id)
                .expect("validated input stage");
            let wire_type = stage
                .graph
                .root_scope()
                .nodes()
                .iter()
                .find_map(|node| match node.kind() {
                    NodeKind::Input { name, .. } if name == &input_name.0 => {
                        Some(&node.output_types()[0])
                    }
                    _ => None,
                })
                .expect("validated input type");
            let field = format!("x.{}", lean_field_identifier(&name.0));
            format!("({}, {})", lean_string(&name.0), lean_input_value(wire_type, &field))
        })
        .collect::<Vec<_>>()
        .join(", ");
    let compared_names = protocol
        .correctness
        .compared_outputs
        .iter()
        .map(|output| lean_string(&output.output))
        .collect::<Vec<_>>()
        .join(", ");
    let comparison = match &protocol.correctness.comparator {
        Comparator::Equal => format!(
            "(!Mxx.Ir.environmentValid concrete ||\n        !Mxx.Ir.environmentValid ideal ||\n        !Mxx.Ir.valuesEqual (Mxx.Ir.environmentValues concrete)\n          (Mxx.Ir.environmentValues ideal))"
        ),
        Comparator::EqualAfterMap { .. } => format!(
            "match Mxx.Ir.denotePure {lean_name}_comparatorMap ({lean_name}ParamEnvironment p)\n          (Mxx.Ir.rebindInputs {lean_name}_comparatorMap\n            (Mxx.Ir.environmentValues concrete)) with\n      | none => true\n      | some mapped => (!Mxx.Ir.environmentValid mapped ||\n          !Mxx.Ir.environmentValid ideal ||\n          !Mxx.Ir.valuesEqual (Mxx.Ir.environmentValues mapped)\n            (Mxx.Ir.environmentValues ideal))"
        ),
        Comparator::NormWithin { bound } => format!(
            "match Mxx.Ir.valuesDistance (Mxx.Ir.environmentValues concrete)\n          (Mxx.Ir.environmentValues ideal) with\n      | none => true\n      | some distance => (!Mxx.Ir.environmentValid concrete ||\n          !Mxx.Ir.environmentValid ideal ||\n          decide ((distance : Rat) > {}))",
            lean_rat_expr(bound, protocol)
        ),
    };
    format!(
        "def {lean_name}ParamEnvironment (p : {lean_name}Params) : Mxx.Ir.ParamEnvironment :=\n  [{params}]\n\ndef {lean_name}InputEnvironment (p : {lean_name}Params) (x : {lean_name}Inputs p) : Mxx.Ir.Environment :=\n  [{inputs}]\n\ndef {lean_name}ConcreteOutcomes (samplers : MxxSamplerFamily) (p : {lean_name}Params)\n    (x : {lean_name}Inputs p) : List Mxx.Ir.Environment :=\n  Mxx.Ir.denoteWorkflow samplers {lean_name}_workflow\n    ({lean_name}ParamEnvironment p) ({lean_name}InputEnvironment p x)\n\ndef {lean_name}IdealOutput (p : {lean_name}Params)\n    (x : {lean_name}Inputs p) : Option Mxx.Ir.Environment :=\n  Mxx.Ir.denotePure {lean_name}_ideal ({lean_name}ParamEnvironment p)\n    ({lean_name}InputEnvironment p x)\n\ndef {lean_name}FailureBool (p : {lean_name}Params) (x : {lean_name}Inputs p)\n    (workflowOutput : Mxx.Ir.Environment) : Bool :=\n  let concrete := Mxx.Ir.projectOutputs [{compared_names}] workflowOutput\n  match {lean_name}IdealOutput p x with\n  | none => true\n  | some ideal =>\n      {comparison}\n\ndef {lean_name}FailureEvent (p : {lean_name}Params) (x : {lean_name}Inputs p)\n    (workflowOutput : Mxx.Ir.Environment) : Prop :=\n  {lean_name}FailureBool p x workflowOutput = true\n\ndef {lean_name}SupportCorrect (samplers : MxxSamplerFamily) (p : {lean_name}Params)\n    (x : {lean_name}Inputs p) : Prop :=\n  ∀ output ∈ {lean_name}ConcreteOutcomes samplers p x,\n    ¬ {lean_name}FailureEvent p x output\n\n@[irreducible] def {lean_name}FailureProbability (samplers : MxxSamplerFamily) (p : {lean_name}Params)\n    (x : {lean_name}Inputs p) : ENNReal :=\n  if ({lean_name}ConcreteOutcomes samplers p x).any ({lean_name}FailureBool p x)\n  then 1 else 0"
    )
    .replace(
        &format!(
            "@[irreducible] def {lean_name}FailureProbability (samplers : MxxSamplerFamily) (p : {lean_name}Params)\n    (x : {lean_name}Inputs p) : ENNReal :=\n  if ({lean_name}ConcreteOutcomes samplers p x).any ({lean_name}FailureBool p x)\n  then 1 else 0"
        ),
        &format!(
            "def {lean_name}FailureProbability (samplers : MxxSamplerFamily) (p : {lean_name}Params)\n    (x : {lean_name}Inputs p) : ENNReal :=\n  Mxx.booleanFailureProbability ({lean_name}ConcreteOutcomes samplers p x)\n    ({lean_name}FailureBool p x)"
        ),
    )
    .replace(
        &format!(
            "def {lean_name}InputEnvironment (p : {lean_name}Params) (x : {lean_name}Inputs p) : Mxx.Ir.Environment :=\n  [{inputs}]\n\n"
        ),
        &format!(
            "def {lean_name}InputEnvironment (p : {lean_name}Params) (x : {lean_name}Inputs p) : Mxx.Ir.Environment :=\n  [{inputs}]\n\ndef {lean_name}InputsWF (p : {lean_name}Params) (x : {lean_name}Inputs p) : Prop :=\n  {input_well_formedness}\n\ndef {lean_name}Preconditions (p : {lean_name}Params) (x : {lean_name}Inputs p) : Prop :=\n  {preconditions}\n\n"
        ),
    )
}

fn lean_input_value(wire_type: &WireType, field: &str) -> String {
    match wire_type {
        WireType::ConstantInt | WireType::Int => format!(".integer {field}"),
        WireType::ConstantReal | WireType::Real => format!(".rational {field}"),
        WireType::ConstantBool | WireType::Bool => format!(".boolean {field}"),
        WireType::Bytes { .. } => format!(".bytes {field}"),
        WireType::Matrix(_) | WireType::Preimage(_) => format!(".matrix {field}"),
        WireType::Trapdoor { .. } | WireType::TypedBlob { .. } | WireType::IndexedFamily { .. } => {
            ".invalid \"unsupported protocol input type\"".to_owned()
        }
    }
}

fn protocol_input_wire_type<'a>(
    protocol: &'a ProtocolDecl,
    destinations: &[(StageId, crate::StageInputName)],
) -> &'a WireType {
    let (stage_id, input_name) = destinations.first().expect("validated protocol input mapping");
    let stage = protocol
        .stages
        .iter()
        .find(|stage| &stage.id == stage_id)
        .expect("validated protocol input stage");
    stage
        .graph
        .root_scope()
        .nodes()
        .iter()
        .find_map(|node| match node.kind() {
            NodeKind::Input { name, .. } if name == &input_name.0 => Some(&node.output_types()[0]),
            _ => None,
        })
        .expect("validated protocol input type")
}

fn lean_input_well_formedness(
    wire_type: &WireType,
    field: &str,
    protocol: &ProtocolDecl,
) -> String {
    match wire_type {
        WireType::Bytes { length } => {
            format!("{field}.size = ({}).toNat", lean_int_expr(length, protocol))
        }
        WireType::Matrix(matrix) | WireType::Preimage(matrix) => {
            let coefficient_count = IntExpr::Mul(
                Box::new(IntExpr::Mul(
                    Box::new(matrix.rows.clone()),
                    Box::new(matrix.columns.clone()),
                )),
                Box::new(matrix.ring_dimension.clone()),
            );
            let modulus = lean_int_expr(&matrix.modulus, protocol);
            format!(
                "{field}.coefficients.length = ({}).toNat ∧\n      \
                 ∀ coefficient ∈ {field}.coefficients, 0 ≤ coefficient ∧ coefficient < {modulus}",
                lean_int_expr(&coefficient_count, protocol),
            )
        }
        WireType::Trapdoor { .. } | WireType::TypedBlob { .. } | WireType::IndexedFamily { .. } => {
            unreachable!("unsupported protocol wire types are rejected before emission")
        }
        WireType::ConstantInt |
        WireType::Int |
        WireType::ConstantReal |
        WireType::Real |
        WireType::ConstantBool |
        WireType::Bool => "True".to_owned(),
    }
}

fn lean_rat_expr(expression: &crate::RatExpr, protocol: &ProtocolDecl) -> String {
    match expression {
        crate::RatExpr::Constant(value) => {
            format!("(({} : Rat) / ({} : Rat))", value.numerator(), value.denominator())
        }
        crate::RatExpr::Parameter(name) => {
            let field = format!("p.{}", lean_field_identifier(name));
            match protocol.params.iter().find(|parameter| parameter.name == *name).map(|p| &p.kind)
            {
                Some(crate::ParameterKind::Rational) => field,
                Some(crate::ParameterKind::Dimension | crate::ParameterKind::Integer) => {
                    format!("({field} : Rat)")
                }
                None => unreachable!("comparator parameter validation ran before emission"),
            }
        }
        crate::RatExpr::Add(left, right) => {
            format!("({} + {})", lean_rat_expr(left, protocol), lean_rat_expr(right, protocol))
        }
        crate::RatExpr::Multiply(left, right) => {
            format!("({} * {})", lean_rat_expr(left, protocol), lean_rat_expr(right, protocol))
        }
        crate::RatExpr::Divide(left, right) => {
            format!("({} / {})", lean_rat_expr(left, protocol), lean_rat_expr(right, protocol))
        }
        crate::RatExpr::Power(value, exponent) => {
            format!("({} ^ {exponent})", lean_rat_expr(value, protocol))
        }
    }
}

fn lean_workflow(lean_name: &str, protocol: &ProtocolDecl) -> Result<String, EmitError> {
    let mut definitions = Vec::new();
    for stage in topological_stages(protocol) {
        definitions.push(format!(
            "def {lean_name}_stage_{} : Mxx.Ir.Prog :=\n{}",
            lower_identifier(&stage.id.0),
            lean_program(&stage.graph, 2)?
        ));
    }
    definitions.push(format!(
        "def {lean_name}_ideal : Mxx.Ir.Prog :=\n{}",
        lean_program(&protocol.correctness.ideal.graph, 2)?
    ));
    for (index, requirement) in protocol.correctness.requires.iter().enumerate() {
        definitions.push(format!(
            "def {lean_name}_requirement_{index} : Mxx.Ir.Prog :=\n{}",
            lean_program(&requirement.graph, 2)?
        ));
    }
    if let Comparator::EqualAfterMap { map } = &protocol.correctness.comparator {
        definitions.push(format!(
            "def {lean_name}_comparatorMap : Mxx.Ir.Prog :=\n{}",
            lean_program(&map.graph, 2)?
        ));
    }

    let protocol_sources = protocol
        .correctness
        .protocol_inputs
        .iter()
        .flat_map(|(protocol_name, destinations)| {
            destinations.iter().map(move |(stage, input)| {
                ((stage.clone(), input.0.clone()), protocol_name.0.clone())
            })
        })
        .collect::<BTreeMap<_, _>>();
    let stages = topological_stages(protocol)
        .into_iter()
        .map(|stage| {
            let artifact_sources = stage
                .bindings
                .iter()
                .map(|binding| (binding.consumer_input.0.clone(), binding))
                .collect::<BTreeMap<_, _>>();
            let inputs = stage
                .graph
                .root_scope()
                .nodes()
                .iter()
                .filter_map(|node| match node.kind() {
                    NodeKind::Input { name, .. } => {
                        let source = if let Some(binding) = artifact_sources.get(name) {
                            format!(
                                ".artifact {} {}",
                                lean_string(&binding.producer_stage.0),
                                lean_string(&binding.producer_output.0)
                            )
                        } else {
                            let protocol_name = protocol_sources
                                .get(&(stage.id.clone(), name.clone()))
                                .expect("validated protocol input mapping");
                            format!(".protocol {}", lean_string(protocol_name))
                        };
                        Some(format!("({}, {source})", lean_string(name)))
                    }
                    _ => None,
                })
                .collect::<Vec<_>>()
                .join(", ");
            format!(
                "    {{ id := {}, program := {lean_name}_stage_{}, inputs := [{inputs}] }}",
                lean_string(&stage.id.0),
                lower_identifier(&stage.id.0)
            )
        })
        .collect::<Vec<_>>()
        .join(",\n");
    definitions.push(format!(
        "def {lean_name}_workflow : Mxx.Ir.Workflow :=\n  {{ stages := [\n{stages}\n  ], entrypoint := {} }}",
        lean_string(&protocol.entrypoint.0)
    ));
    Ok(definitions.join("\n\n") + "\n")
}

fn topological_stages(protocol: &ProtocolDecl) -> Vec<&ProtocolStage> {
    fn visit<'a>(
        id: &StageId,
        stages: &BTreeMap<&'a StageId, &'a ProtocolStage>,
        visited: &mut BTreeSet<StageId>,
        output: &mut Vec<&'a ProtocolStage>,
    ) {
        if !visited.insert(id.clone()) {
            return;
        }
        let stage = stages[id];
        for dependency in stage.bindings.iter().map(|binding| &binding.producer_stage) {
            visit(dependency, stages, visited, output);
        }
        output.push(stage);
    }
    let stages = protocol.stages.iter().map(|stage| (&stage.id, stage)).collect::<BTreeMap<_, _>>();
    let mut output = Vec::new();
    visit(&protocol.entrypoint, &stages, &mut BTreeSet::new(), &mut output);
    output
}

fn lean_program(graph: &Graph, indent: usize) -> Result<String, EmitError> {
    let padding = " ".repeat(indent);
    let root = lean_scope(graph, &FrozenGraphScopeId::Root, graph.root_scope(), indent + 4)?;
    let definitions = graph
        .scopes()
        .iter()
        .filter(|(id, _)| !matches!(id, FrozenGraphScopeId::Root))
        .map(|(id, scope)| {
            Ok(format!(
                "{}({},\n{})",
                " ".repeat(indent + 2),
                lean_string(&lean_scope_name(id)),
                lean_scope(graph, id, scope, indent + 4)?
            ))
        })
        .collect::<Result<Vec<_>, EmitError>>()?
        .join(",\n");
    Ok(format!(
        "{padding}{{ root :=\n{root}\n{padding}  definitions := [\n{definitions}\n{padding}  ]\n{padding}}}"
    ))
}

fn lean_scope(
    graph: &Graph,
    scope_id: &FrozenGraphScopeId,
    scope: &GraphScope,
    indent: usize,
) -> Result<String, EmitError> {
    let padding = " ".repeat(indent);
    let child_padding = " ".repeat(indent + 2);
    let nodes = scope
        .nodes()
        .iter()
        .enumerate()
        .map(|(node_id, node)| -> Result<_, EmitError> {
            let arguments = scope
                .arguments(node)
                .expect("frozen root arguments")
                .iter()
                .map(lean_wire_ref)
                .collect::<Vec<_>>()
                .join(", ");
            Ok(format!(
                "{child_padding}{{ kind := {}, arguments := [{arguments}], outputCount := {} }}",
                lean_node_kind(graph, scope_id, mxx_ir_core::NodeId(node_id as u64), node)?,
                node.output_types().len()
            ))
        })
        .collect::<Result<Vec<_>, _>>()?
        .join(",\n");
    let outputs = if matches!(scope_id, FrozenGraphScopeId::Root) {
        graph
            .outputs()
            .iter()
            .map(|(name, output)| {
                format!("({}, {})", lean_string(name), lean_wire_ref(&output.value))
            })
            .collect::<Vec<_>>()
    } else {
        scope
            .outputs()
            .iter()
            .enumerate()
            .map(|(index, output)| {
                format!("({}, {})", lean_string(&format!("output-{index}")), lean_wire_ref(output))
            })
            .collect::<Vec<_>>()
    }
    .join(", ");
    let input_names = if matches!(scope_id, FrozenGraphScopeId::Root) {
        scope
            .nodes()
            .iter()
            .filter_map(|node| match node.kind() {
                NodeKind::Input { name, .. } => Some(lean_string(name)),
                _ => None,
            })
            .collect::<Vec<_>>()
    } else {
        scope
            .inputs()
            .iter()
            .map(|wire| {
                let node = scope.node(wire.node).expect("scope input references an existing node");
                match node.kind() {
                    NodeKind::Input { name, .. } => lean_string(name),
                    _ => unreachable!("scope inputs always reference input nodes"),
                }
            })
            .collect::<Vec<_>>()
    }
    .join(", ");
    Ok(format!(
        "{padding}{{ nodes := [\n{nodes}\n{padding}]\n{padding}  outputs := [{outputs}]\n{padding}  inputNames := [{input_names}] }}"
    ))
}

fn lean_scope_name(id: &FrozenGraphScopeId) -> String {
    match id {
        FrozenGraphScopeId::Root => "__root".to_owned(),
        FrozenGraphScopeId::Subgraph { canonical_name } => {
            format!("subgraph:{canonical_name}")
        }
        FrozenGraphScopeId::ParallelBody { parent, owner } => {
            format!("parallel:{}:{}", lean_scope_name(parent), owner.0)
        }
    }
}

fn lean_wire_ref(wire: &mxx_ir_core::WireRef) -> String {
    format!("{{ node := {}, port := {} }}", wire.node.0, wire.port.0)
}

fn lean_node_kind(
    graph: &Graph,
    scope_id: &FrozenGraphScopeId,
    node_id: mxx_ir_core::NodeId,
    node: &mxx_ir_core::NodeHandle,
) -> Result<String, EmitError> {
    Ok(match node.kind() {
        NodeKind::Input { name, .. } => format!(".input {}", lean_string(name)),
        NodeKind::ConstantInt(value) => format!(".constantInt ({value} : Int)"),
        NodeKind::EvaluateInt(value) => format!(".evaluateInt ({})", lean_ir_int_expr(value)),
        NodeKind::ConstantBool(value) => format!(".constantBool {value}"),
        NodeKind::ConstantMatrix { matrix_type, value: ConstantMatrix::Zero } => {
            format!(".zeroMatrix {}", lean_matrix_type(matrix_type))
        }
        NodeKind::ConstantMatrix { matrix_type, value: ConstantMatrix::Identity } => {
            format!(".identityMatrix {}", lean_matrix_type(matrix_type))
        }
        NodeKind::ConstantMatrix {
            matrix_type,
            value: ConstantMatrix::Polynomial { coefficients },
        } => format!(
            ".constantMatrix {} [{}]",
            lean_matrix_type(matrix_type),
            coefficients
                .iter()
                .map(|coefficient| format!("({})", lean_ir_int_expr(coefficient)))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        NodeKind::BoolToInt => ".boolToInt".to_owned(),
        NodeKind::IntBinary(operation) => format!(
            ".intBinary .{}",
            match operation {
                IntBinaryOp::Add => "add",
                IntBinaryOp::Subtract => "subtract",
                IntBinaryOp::Multiply => "multiply",
                IntBinaryOp::Divide => "divide",
                IntBinaryOp::Remainder => "remainder",
            }
        ),
        NodeKind::IntCompare(operation) => format!(
            ".intCompare .{}",
            match operation {
                IntCompareOp::Equal => "equal",
                IntCompareOp::Less => "less",
                IntCompareOp::LessEqual => "lessEqual",
            }
        ),
        NodeKind::BitExtract { bit } => format!(".bitExtract ({})", lean_ir_int_expr(bit)),
        NodeKind::ExtractCoefficient { position } => {
            format!(".extractCoefficient ({})", lean_ir_int_expr(position))
        }
        NodeKind::Select { .. } => ".select".to_owned(),
        NodeKind::UniformSample { matrix_type, range } => format!(
            ".uniformSample {} ({}) ({})",
            lean_matrix_type(matrix_type),
            lean_ir_int_expr(&range.minimum),
            lean_ir_int_expr(&range.maximum)
        ),
        NodeKind::GaussianSample { matrix_type, max_coefficient_bound, .. } => {
            format!(
                ".gaussianSample {} ({})",
                lean_matrix_type(matrix_type),
                lean_ir_int_expr(max_coefficient_bound)
            )
        }
        NodeKind::TrapdoorSample { matrix_type, preimage_max_coefficient_bound, .. } => format!(
            ".trapdoorSample {} ({})",
            lean_matrix_type(matrix_type),
            lean_ir_int_expr(preimage_max_coefficient_bound)
        ),
        NodeKind::TrapdoorPublic => ".trapdoorPublic".to_owned(),
        NodeKind::PreimageSample { matrix_type, max_coefficient_bound } => format!(
            ".preimageSample {} ({})",
            lean_matrix_type(matrix_type),
            lean_ir_int_expr(max_coefficient_bound)
        ),
        NodeKind::MatrixBinary(MatrixBinaryOp::Add) => ".matrixAdd".to_owned(),
        NodeKind::MatrixBinary(MatrixBinaryOp::Subtract) => ".matrixSubtract".to_owned(),
        NodeKind::MatrixBinary(MatrixBinaryOp::Multiply) => ".matrixMultiply".to_owned(),
        NodeKind::MatrixNegate => ".matrixNegate".to_owned(),
        NodeKind::MatrixScale { scalar } => {
            format!(".matrixScale ({})", lean_ir_int_expr(scalar))
        }
        NodeKind::Concat { axis } => format!(
            ".concat .{}",
            match axis {
                ConcatAxis::Rows => "rows",
                ConcatAxis::Columns => "columns",
                ConcatAxis::Diagonal => "diagonal",
            }
        ),
        NodeKind::ThresholdDecode { plaintext_modulus, length, output_bool: true } => {
            let scope = graph.scope(scope_id).ok_or(EmitError::ChildScope)?;
            let modulus = scope
                .arguments(node)
                .and_then(|arguments| arguments.first().copied())
                .and_then(|wire| scope.node(wire.node))
                .and_then(|source| source.output_types().first())
                .and_then(|wire_type| match wire_type {
                    WireType::Matrix(matrix) | WireType::Preimage(matrix) => Some(matrix),
                    WireType::Trapdoor { matrix, .. } => Some(matrix),
                    _ => None,
                })
                .map(|matrix| matrix.modulus.clone());
            match modulus {
                Some(modulus) => format!(
                    ".thresholdDecodeBool ({}) ({}) ({})",
                    lean_ir_int_expr(&modulus),
                    lean_ir_int_expr(plaintext_modulus),
                    lean_ir_int_expr(length)
                ),
                None => return Err(EmitError::UnsupportedNode("ThresholdDecode")),
            }
        }
        NodeKind::FamilyPack { .. } => ".familyPack".to_owned(),
        NodeKind::FamilyGetStatic { index } => {
            format!(".familyGetStatic ({})", lean_ir_int_expr(index))
        }
        NodeKind::FamilyGetDynamic => ".familyGetDynamic".to_owned(),
        NodeKind::SubgraphCall(call) => {
            let child = graph.child_scope_id(scope_id, node_id).ok_or(EmitError::ChildScope)?;
            format!(
                ".subgraphCall {} [{}]",
                lean_string(&lean_scope_name(&child)),
                lean_bindings(&call.bindings)
            )
        }
        NodeKind::ParallelLoop(loop_spec) => {
            let child = graph.child_scope_id(scope_id, node_id).ok_or(EmitError::ChildScope)?;
            let modes = loop_spec
                .input_modes
                .iter()
                .map(|mode| match mode {
                    LoopInputMode::Broadcast => ".broadcast".to_owned(),
                    LoopInputMode::Zip => ".zip".to_owned(),
                    LoopInputMode::ZipOffset { offset } => format!(".zipOffset {offset}"),
                })
                .collect::<Vec<_>>()
                .join(", ");
            format!(
                ".parallelLoop {} ({}) {} [{}] [{}]",
                lean_string(&lean_scope_name(&child)),
                lean_ir_int_expr(&loop_spec.count),
                loop_spec.index_slot,
                lean_bindings(&loop_spec.bindings),
                modes
            )
        }
        kind => return Err(EmitError::UnsupportedNode(node_kind_name(kind))),
    })
}

