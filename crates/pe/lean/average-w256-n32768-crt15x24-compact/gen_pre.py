def u64_selector(text):
    start = text.index('.u64Le (') + len('.u64Le (')
    depth = 1
    for end in range(start, len(text)):
        depth += (text[end] == '(') - (text[end] == ')')
        if depth == 0:
            return text[start:end]
    raise ValueError('unclosed selector')


