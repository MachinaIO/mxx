def sources_text(geo, sources_path):
    path = sources_path or geo.package / 'proof' / 'Dio2Online0Sources.lean'
    meta.require(path.exists(), f'missing step-zero source interface {path}; run gen_s0a.py first')
    return path.read_text()


def agree_sources(geo, sources_path=None, child_budget=12000, root_budget=2500):
    import s0o_agree as agree
    from xmodel import app_split, strip_parens
    text = sources_text(geo, sources_path)
    rows_m = re.search(r'def sigmaRows .*?:=\n  (.*?)\n\n', text, re.S)
    meta.require(rows_m is not None, 'sigmaRows definition')
    sigma_rows = re.findall(r'generatedRoot\.(w_\d+_\d+) online', rows_m.group(1))
    meta.require(len(sigma_rows) == 6, 'sigmaRows arity')
    skey = re.search(r'def sigmaKey .*?Enc\.A \(sigmaRows online\) key 1 \* \(generatedRoot\.(w_\d+_\d+) online\)',
                     text, re.S)
    okey = re.search(r'def oneKey .*?labelKeysG model \(generatedRoot\.(w_\d+_\d+) online\).*?'
                     r'key 1 \* \(generatedRoot\.(w_\d+_\d+) online\)', text, re.S)
    meta.require(skey is not None and okey is not None, 'sigmaKey/oneKey definitions')
    sigma_mult = skey.group(1)
    one_seed, one_mult = okey.group(1), okey.group(2)
    kargs = [a.split()[0] for a in geo.keys[0]['arguments']]
    kg0, kone0, krefresh, kcx0, kfresh0, kgadget, ksrow, kweights, ksm0, ksm1, kg1, kone1, kcx1, kfresh1 = kargs
    pin, pargs = geo.part_inputs, geo.part_args
    w0 = geo.primes[0]['wires']
    target_family = pargs[pin.index(w0['target'])].split()[0][:-2]
    fivers = [a for a in pargs if a.endswith('_5')]
    fresh_base, smudge_base = fivers[0][:-2], fivers[1][:-2]
    weights_online = pargs[pargs.index(fivers[1]) + 1]

    gen = agree.Generator(geo.package, ONLINE, KEYS)
    R = agree.RootLemma(gen)
    B = gen.info('B', 'generatedRoot')
    K = f'{KEYS}.generatedRoot'

    def e(a, b):
        names = R.eq(a, b)
        meta.require(len(names) == 1, f'no single equality for {a} {b}')
        return names[0]

    def keylet(w):
        node = B.node(w)
        meta.require(node[0] == 'let', f'key {w} is not a product')
        head, args = app_split(node[1])
        meta.require(head == 'MxxRuntime.matrixMul', f'key {w} is not a product')
        return [strip_parens(x) for x in args]
    fields = []
    for name, kw, row in (('g0', kg0, sigma_rows[1]), ('g1', kg1, sigma_rows[3])):
        x, y = keylet(kw)
        ex, ey = e(row, x), e(sigma_mult, y)
        fields.append((name, f'(by rw [show ({K}.{kw} ck) = ({K}.{x} ck) * ({K}.{y} ck) from rfl, '
                             f'← {ex}, ← {ey}]; rfl)', [ex, ey]))
    for name, kw in (('one0', kone0), ('one1', kone1)):
        x, y = keylet(kw)
        hx = B.node(x)
        meta.require(hx[0] == 'atom' and hx[1].kind == 'hashSample', f'key {x} is not hashed')
        seed = strip_parens(hx[1].args[-2])
        es, ey = e(one_seed, seed), e(one_mult, y)
        fields.append((name, f'(by rw [show ({K}.{kw} ck) = ({K}.{x} ck) * ({K}.{y} ck) from rfl, '
                             f'MxxExponentLut.hashSample_eq Fk.c{hx[1].frag}.{hx[1].field}, ← {ey}, ← {es}]; rfl)',
                       [es, ey]))
    for name, ow, kw in (('refresh', target_family + '_3', krefresh), ('cx0', target_family + '_1', kcx0),
                         ('cx1', target_family + '_2', kcx1), ('fresh0', fresh_base + '_1', kfresh0),
                         ('fresh1', fresh_base + '_3', kfresh1), ('weights', weights_online, kweights),
                         ('smudge0', smudge_base + '_1', ksm0), ('smudge1', smudge_base + '_3', ksm1)):
        name_e = e(ow, kw)
        fields.append((name, f'{name_e}.symm', [name_e]))
    final_refs = sorted({r for _, _, refs in fields for r in refs})
    binders = ('{model : HashModel} {external : GeneratedClaim.ExternalInputs}\n'
               '    {execution : GeneratedClaim.Execution}\n'
               '    (co : Step0Rows.OnlineCtx model) (ck : Step0Rows.KeyCtx model)\n'
               '    {outputs koutputs : _}\n'
               f'    (Fo : {ONLINE}.generatedRoot.Facts co outputs)\n'
               f'    (Fk : {KEYS}.generatedRoot.Facts ck koutputs)\n'
               '    (hino : co.inputs = Claim0.onlineInputs external execution)\n'
               '    (hink : ck.inputs = Online0Claim.keyInputs external execution)')
    theorems, rebuild = agree.render_root(R, binders, 'co ck Fo Fk hino hink', root_budget,
                                          final_refs, 'root_part')
    final = (f'/-- The online and key-stage part inputs agree (`Step0Rows.KeyLinks`). -/\n'
             f'theorem key_links {binders} :\n    Step0Rows.KeyLinks co ck := by\n' +
             '\n'.join(rebuild) + '\n  exact {\n' +
             ',\n'.join(f'    {n} := {p}' for n, p, _ in fields) + ' }\n')
    # Module layout: child lemmas (with the prelude first), then root chunks.
    header = HEADER.format(title='Step-zero key agreement',
                           summary='Online and key-stage key computations agree wire by wire;\n'
                           'no ciphertext, plaintext or noise statement is involved.')
    blocks = [gen.render_child(L) for L in gen.order] + theorems + [final]
    modules, current, size = [], [], 0
    for block in blocks:
        current.append(block)
        size += block.count('\n')
        if size >= child_budget:
            modules.append(current)
            current, size = [], 0
    if current:
        modules.append(current)
    names = ['Dio2Step0Agree'] + [f'Dio2Step0Agree{k}' for k in range(1, len(modules))]
    sources = {}
    for k, (name, body) in enumerate(zip(names, modules)):
        imp = 'import Dio2Step0Rows\n\n' if k == 0 else f'import {names[k - 1]}\n\n'
        text = imp + header + 'namespace Step0Agree\n\n'
        if k == 0:
            text += AGREE_PRELUDE
        text += '\n'.join(body) + '\nend Step0Agree\n\nend Dio2Proof\n'
        sources[name] = text
    return sources


