    #[test]
    fn declared_preconditions_are_hashed_and_mechanically_denoted() {
        let without_requirement = declaration(1);
        let mut with_requirement = declaration(1);
        let ring = Ring::new(17, 8);
        let requirement = PurePredicateSpec::new(
            DslContext::new("message-precondition")
                .bool_output(
                    "holds",
                    ring.input("message", (1, 1))
                        .threshold_decode_bools(IntExpr::constant(2), 1)
                        .into_iter()
                        .next()
                        .unwrap(),
                )
                .unwrap()
                .build()
                .unwrap(),
        )
        .unwrap();
        with_requirement.correctness.requires.push(requirement);
        with_requirement.validate().unwrap();

        let baseline = emit_test_protocol("precondition", &without_requirement).unwrap();
        let emitted = emit_test_protocol("precondition", &with_requirement).unwrap();
        assert_ne!(baseline.protocol_hash, emitted.protocol_hash);
        assert!(emitted.ir.contains("def Precondition_requirement_0 : Mxx.Ir.Prog"));
        assert!(emitted.statement.contains("Mxx.Ir.denotePure Precondition_requirement_0"));
        assert!(emitted.statement.contains("PreconditionPreconditions"));
    }

